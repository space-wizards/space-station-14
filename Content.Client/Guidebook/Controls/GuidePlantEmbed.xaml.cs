/// <summary>
///   Control for embedding a plant in the guidebook.
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuidePlantEmbed : PanelContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IComponentFactory _factory = default!;
    [Dependency] private IEntitySystemManager _systems = default!;
    [Dependency] private ILogManager _logManager = default!;
    private readonly ISawmill _sawmill;
    //Needed because if the width richprototypelinks is too small it crashes the client
    private const float MinimumTextWidth = 50;

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuidePlantEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;
        _sawmill = _logManager.GetSawmill("guidebook.plant");
    }

    public GuidePlantEmbed(EntityPrototype plant) : this()
    {
        GenerateControl(plant);
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Plant", out var id))
        {
            _sawmill.Error("Plant embed tag is missing plant prototype argument");
            return false;
        }

        if (!_prototype.TryIndex<EntityPrototype>(id, out var plant) || !plant.HasComp<PlantDataComponent>(_factory))
        {
            _sawmill.Error($"Specified plant prototype \"{id}\" is not a valid plant prototype because it lacks a plantdatacomponent");
            return false;
        }

        GenerateControl(plant);

        control = this;
        return true;
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    private void GenerateControl(EntityPrototype plant)
    {
        if (!plant.TryComp<PlantDataComponent>(out var data, _factory))
            return;

        RepresentedPrototype = plant;
        PlantName.Text = Loc.GetString(data.Name);

        if (plant.TryComp<PlantComponent>(out var growth, _factory))
        {
            for (var stage = 1; stage <= growth.GrowthStages; stage++)
            {
                AddGrowthStage(plant, $"stage-{stage}", Loc.GetString("guidebook-plant-growth-stage", ("stage", stage)));
            }
        }
        AddGrowthStage(plant, "harvest", Loc.GetString("guidebook-plant-grown"));
        ProductsContainer.AddChild(new Separator
        {
            StyleClasses = { "LowDivider" },
            Margin = new Thickness(0, 5, 0, 5),
        });
        foreach (var product in data.ProductPrototypes)
        {
            ProductsContainer.AddChild(CreateProductRow(plant, product));
            ProductsContainer.AddChild(new Separator
            {
                StyleClasses = { "LowDivider" },
                Margin = new Thickness(0, 5, 0, 5),
            });
        }

        AddMutations(MutatesFromContainer,
            _prototype.EnumeratePrototypes<EntityPrototype>().Where(p => !p.Abstract &&
                p.TryComp<PlantDataComponent>(out var parent, _factory) && parent.MutationPrototypes.Contains(plant.ID)));
        AddMutations(MutatesToContainer, data.MutationPrototypes.Select(id => _prototype.Index(id)));
        MutatesFromSection.Visible = MutatesFromContainer.ChildCount > 0;
        MutatesToSection.Visible = MutatesToContainer.ChildCount > 0;
        MutationsContainer.Visible = MutatesFromSection.Visible || MutatesToSection.Visible;
    }

    private void AddGrowthStage(EntityPrototype plant, string state, string label)
    {
        var stage = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };
        var sprite = CreatePlantSprite(plant, state);
        sprite.Margin = new Thickness(0);
        stage.AddChild(sprite);
        stage.AddChild(new Label { Text = label, HorizontalAlignment = HAlignment.Center });
        GrowthStagesContainer.AddChild(stage);
    }

    private GuideEntityEmbed CreatePlantSprite(EntityPrototype plant, string state = "harvest")
    {
        var embed = new GuideEntityEmbed(plant.ID, false, false) { Scale = new Vector2(2) };
        if (embed.Sprite is { } sprite)
        {
            var sprites = _systems.GetEntitySystem<SpriteSystem>();
            sprites.LayerSetRsiState(sprite.AsNullable(), PlantLayers.Plant, state);
            sprites.LayerSetVisible(sprite.AsNullable(), PlantLayers.Plant, true);
        }
        return embed;
    }

    private BoxContainer CreateProductRow(EntityPrototype plant, EntProtoId productId)
    {
        var product = _prototype.Index(productId);
        IEnumerable<ProtoId<ReagentPrototype>> juice = [];
        IEnumerable<ProtoId<ReagentPrototype>> grind = [];
        if (product.TryComp<ExtractableComponent>(out var extractable, _factory))
        {
            juice = GetReagents(extractable.JuiceSolution);
            if (plant.TryComp<PlantChemicalsComponent>(out var chemicals, _factory))
            {
                grind = chemicals.Chemicals.Keys;
            }
        }

        var butcher = new List<EntProtoId>();
        if (product.TryComp<ToolRefinableComponent>(out var refinable, _factory) && refinable.QualityNeeded == "Slicing")
        {
            butcher.AddRange(refinable.RefineResult.Select(result => result.PrototypeId!.Value));
            if (product.TryComp<EdibleComponent>(out var edible, _factory))
                butcher.AddRange(edible.Trash);
        }

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 10,
            HorizontalExpand = true,
        };

        void AddColumn(string heading, Control content)
        {
            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 8,
                HorizontalExpand = true,
            };
            column.AddChild(new Label { Text = Loc.GetString(heading), HorizontalAlignment = HAlignment.Center });
            column.AddChild(content);
            row.AddChild(column);
        }

        AddColumn("guidebook-plant-produce", CreateProduct(product));
        if (butcher.Any())
            AddColumn("guidebook-plant-butchering", CreateButchering(butcher));
        if (grind.Any())
            AddColumn("guidebook-plant-grinding", CreateReagents(grind));
        if (juice.Any())
            AddColumn("guidebook-plant-juicing", CreateReagents(juice));

        return row;
    }

    private Control CreateProduct(EntityPrototype product)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        box.AddChild(new GuideEntityEmbed(product.ID, false, false) { Scale = new Vector2(2) });
        var name = new RichTextLabel { HorizontalAlignment = HAlignment.Center, MinWidth = MinimumTextWidth };
        name.SetMessage(FormattedMessage.FromUnformatted(product.Name));
        box.AddChild(name);
        return box;
    }

    private static IEnumerable<ProtoId<ReagentPrototype>> GetReagents(Solution? solution)
    {
        return solution?.Contents.Select(r => r.Reagent.Prototype) ?? [];
    }

    private Control CreateReagents(IEnumerable<ProtoId<ReagentPrototype>> reagents)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        foreach (var reagent in reagents.Distinct().Select(id => _prototype.Index(id)).OrderBy(r => r.LocalizedName))
        {
            var color = reagent.SubstanceColor;
            // Yoinked from the reagent code
            var textColor = 0.2126f * color.R + 0.7152f * color.G + 0.0722f * color.B > 0.5
                ? Color.Black
                : Color.White;
            var label = new RichTextLabel
            {
                Margin = new Thickness(4, 2),
                HorizontalAlignment = HAlignment.Center,
                MinWidth = MinimumTextWidth,
            };
            var message = new FormattedMessage();
            message.PushColor(textColor);
            message.AddText(reagent.LocalizedName);
            message.Pop();
            label.SetMessage(message);
            box.AddChild(new PanelContainer
            {
                PanelOverride = new StyleBoxFlat { BackgroundColor = color },
                Children = { label },
            });
        }
        return box;
    }

    private Control CreateButchering(List<EntProtoId> results)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        foreach (var id in results)
        {
            box.AddChild(CreateProduct(_prototype.Index(id)));
        }
        return box;
    }

    private void AddMutations(BoxContainer container, IEnumerable<EntityPrototype> plants)
    {
        foreach (var plant in plants.OrderBy(p => p.TryComp<PlantDataComponent>(out var data, _factory)
                     ? Loc.GetString(data.Name) : p.Name))
        {
            if (!plant.TryComp<PlantDataComponent>(out var data, _factory))
                continue;
            var icon = CreatePlantSprite(plant);
            icon.Scale = Vector2.One;
            icon.Margin = new Thickness(0);
            var link = new GuidebookRichPrototypeLink
            {
                LinkedPrototype = plant,
                VerticalAlignment = VAlignment.Center,
                MinWidth = MinimumTextWidth,
            };
            link.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString(data.Name)));
            container.AddChild(new BoxContainer
            {
                SeparationOverride = 4,
                HorizontalAlignment = HAlignment.Center,
                Children = { icon, link },
            });
        }
    }
}
