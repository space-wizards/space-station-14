using System.Diagnostics.CodeAnalysis;
using Content.Client.Guidebook.Richtext;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

using Content.Shared.SpaceLaw;

namespace Content.Client.Guidebook.Controls;

/// <summary>
/// Embed for the Space Law crimes guidebook section.
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideSpaceLawEmbed : Control, IDocumentTag
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private DocumentParsingManager _parsing = default!;

    private ISawmill _logging = default!;

    public GuideSpaceLawEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;
    }

    /// <summary>
    /// Makes a Space Law severity tier table for a given severity, such as Minor Crimes, Moderate Crimes, etc.
    /// </summary>
    private void MakeTierTable(SpaceLawTierPrototype tier)
    {
        var xmlString = new System.Text.StringBuilder();
        xmlString.AppendLine("<Document>");

        xmlString.AppendLine($"## {Loc.GetString(tier.Name)}");
        xmlString.AppendLine($"- {Loc.GetString(tier.Sentence)}");

        xmlString.AppendLine("<Table Columns=\"4\">");

        AppendHeader(xmlString, Loc.GetString("crime-column-offense"));
        AppendHeader(xmlString, Loc.GetString("crime-column-desc"));
        AppendHeader(xmlString, Loc.GetString("crime-column-notes"));
        AppendHeader(xmlString, Loc.GetString("crime-column-code"));

        foreach (var lawID in tier.Laws)
        {
            if (!_prototype.TryIndex(lawID, out var crime))
            {
                _logging.Error($"SpaceLawPrototype \"{lawID}\" not found");
                continue;
            }

            AppendColored(xmlString, Loc.GetString(crime.Name), crime.Color);
            AppendNormal(xmlString, Loc.GetString(crime.Desc));
            AppendNormal(xmlString, Loc.GetString(crime.Notes));
            AppendNormal(xmlString, Loc.GetString(crime.Code));
        }

        xmlString.AppendLine("</Table>");
        xmlString.AppendLine("</Document>");

        if (!_parsing.TryAddMarkup(SpaceLawContainer, xmlString.ToString()))
        {
            _logging.Error($"Failed to parse severity tier table XML for \"{tier.ID}\"");
        }
    }

    /// <summary>
    /// Makes the Space Law Quick Crime Guide table by building it out of the individual severity tiers.
    /// </summary>
    private void MakeQCGTable(List<SpaceLawTierPrototype> tiers)
    {
        var tierMap = new List<Dictionary<string, (string Name, string Color)>>();
        var ordered = new List<string>();
        var seen = new HashSet<string>();

        foreach (var tier in tiers)
        {
            var map = new Dictionary<string, (string Name, string Color)>();
            foreach (var lawID in tier.Laws)
            {
                if (!_prototype.TryIndex(lawID, out var crime))
                {
                    _logging.Error($"SpaceLawPrototype \"{lawID}\" not found");
                    continue;
                }

                var code = Loc.GetString(crime.Code);
                var suffix = code.Contains('-') ? code.Split('-')[1] : code;
                map[suffix] = (Loc.GetString(crime.Name), crime.Color);

                if (seen.Add(suffix))
                {
                    ordered.Add(suffix);
                }
            }
            tierMap.Add(map);
        }

        ordered.Sort((a, b) =>
        {
            if (int.TryParse(a, out var ia) && int.TryParse(b, out var ib))
            {
                return ia.CompareTo(ib);
            }
            return string.Compare(a, b, StringComparison.Ordinal);
        });

        var xmlString = new System.Text.StringBuilder();
        xmlString.AppendLine("<Document>");
        xmlString.AppendLine($"<Table Columns=\"{tiers.Count + 1}\">");

        foreach (var tier in tiers)
        {
            AppendHeader(xmlString, $"{Loc.GetString(tier.Code)} - {Loc.GetString(tier.Name)}");
        }
        AppendHeader(xmlString, Loc.GetString("crime-column-code"));

        foreach (var suffix in ordered)
        {
            for (var t = 0; t < tiers.Count; t++)
            {
                if (tierMap[t].TryGetValue(suffix, out var crime))
                {
                    AppendColored(xmlString, crime.Name, crime.Color);
                }
                else
                {
                    AppendNormal(xmlString, string.Empty);
                }
            }
            AppendNormal(xmlString, suffix);
        }

        xmlString.AppendLine("</Table>");
        xmlString.AppendLine("</Document>");

        if (!_parsing.TryAddMarkup(SpaceLawContainer, xmlString.ToString()))
        {
            _logging.Error("Failed to parse quick table XML");
        }
    }

    /// <summary>
    /// Some simple methods for adding stuff to the tables.
    /// </summary>
    private static void AppendHeader(System.Text.StringBuilder xmlString, string text)
    {
        xmlString.AppendLine("<ColorBox>");
        xmlString.AppendLine($"  <Box>{text}</Box>");
        xmlString.AppendLine("</ColorBox>");
    }

    private static void AppendColored(System.Text.StringBuilder xmlString, string text, string color)
    {
        xmlString.AppendLine($"<ColorBox Color=\"{color}\">");
        xmlString.AppendLine($"  <Box HorizontalAlignment=\"Left\" VerticalAlignment=\"Stretch\" Margin=\"2\">{text}</Box>");
        xmlString.AppendLine("</ColorBox>");
    }

    private static void AppendNormal(System.Text.StringBuilder xmlString, string text)
    {
        xmlString.AppendLine("<ColorBox>");
        xmlString.AppendLine($"  <Box HorizontalAlignment=\"Left\" VerticalAlignment=\"Stretch\" Margin=\"2\">{text}</Box>");
        xmlString.AppendLine("</ColorBox>");
    }

    /// <summary>
    /// If Tier is passed, it makes a single severity table. If Tiers is passed, it makes the Quick Crime Guide.
    /// </summary>
    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;

        if (args.TryGetValue("Tier", out var tierID))
        {
            if (!_prototype.TryIndex<SpaceLawTierPrototype>(tierID, out var tier))
            {
                _logging.Error($"SpaceLawTierPrototype \"{tierID}\" is not a valid prototype");
                return false;
            }

            MakeTierTable(tier);
            control = this;
            return true;
        }

        if (args.TryGetValue("Tiers", out var tiersArg))
        {
            var tiers = new List<SpaceLawTierPrototype>();
            foreach (var tiersID in tiersArg.Split(','))
            {
                if (!_prototype.TryIndex<SpaceLawTierPrototype>(tiersID, out var tier))
                {
                    _logging.Error($"SpaceLawTierPrototype \"{tiersID}\" is not a valid prototype");
                    continue;
                }
                tiers.Add(tier);
            }

            if (tiers.Count == 0)
            {
                _logging.Error("Tiers argument contained no valid IDs");
                return false;
            }

            MakeQCGTable(tiers);
            control = this;
            return true;
        }

        _logging.Error("Missing either a Tier or Tiers argument");
        return false;
    }
}
