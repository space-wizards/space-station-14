namespace Content.Client.Genetics.UI;

[GenerateTypedNameReferences]
public sealed partial class GeneticsConsoleWindow : DefaultWindow
{
    private string? _selectedMutationId;
    private string? _sequenceMutationId;
    private string? _subjectName;
    private string? _subjectGenomeSignature;
    private string? _selectedMemoryId;
    private GeneticsMutationUiEntry? _selectedMutation;
    private readonly Dictionary<string, string> _candidateSequences = new();
    private readonly Dictionary<string, string> _candidateComplementSequences = new();
    private readonly List<Button> _topStrandButtons = new();
    private readonly List<Button> _bottomStrandButtons = new();
    private Action<GeneticsMutationUiEntry, GeneticsConsoleAction, string, string>? _onMutationAction;
    private Action<string>? _onCreateInjector;
    private Action? _onHumanize;
    private Action? _onScramble;

    public GeneticsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        ModeTabs.SetTabTitle(0, Loc.GetString("genetics-console-tab-storage"));
        ModeTabs.SetTabTitle(1, Loc.GetString("genetics-console-tab-sequencer"));
        ModeTabs.SetTabTitle(2, Loc.GetString("genetics-console-tab-enzymes"));
        ModeTabs.SetTabTitle(3, Loc.GetString("genetics-console-tab-features"));
        GuessButton.OnPressed += OnGuessPressed;
        AnalyzeButton.OnPressed += OnAnalyzePressed;
        ApplySelectedButton.OnPressed += OnApplyPressed;
        ScrambleButton.OnPressed += OnScramblePressed;
    }

    public void Populate(
        GeneticsConsoleBoundUserInterfaceState state,
        Action<GeneticsMutationUiEntry, GeneticsConsoleAction, string, string> onMutationAction,
        Action<string> onCreateInjector,
        Action onHumanize,
        Action onScramble)
    {
        var genomeSignature = string.Join("|", state.Mutations.Select(mutation => $"{mutation.Id}:{mutation.Sequence}"));
        if (_subjectName != state.SubjectName || _subjectGenomeSignature != genomeSignature)
        {
            _subjectName = state.SubjectName;
            _subjectGenomeSignature = genomeSignature;
            _candidateSequences.Clear();
            _candidateComplementSequences.Clear();
            _sequenceMutationId = null;
        }

        _onMutationAction = onMutationAction;
        _onCreateInjector = onCreateInjector;
        _onHumanize = onHumanize;
        _onScramble = onScramble;

        ScannerStatus.Text = !state.ScannerConnected
            ? Loc.GetString("genetics-console-no-scanner")
            : !state.ScannerInRange
                ? Loc.GetString("genetics-console-scanner-out-of-range")
                : Loc.GetString("genetics-console-scanner-ready");
        SubjectLabel.Text = state.SubjectName == null
            ? Loc.GetString("genetics-console-no-subject")
            : Loc.GetString("genetics-console-subject", ("name", state.SubjectName));
        InstabilityLabel.Text = Loc.GetString("genetics-console-instability", ("value", state.Instability));
        HealthBar.Value = state.MaxHealth <= 0
            ? 0f
            : Math.Clamp(state.Health / (float) state.MaxHealth, 0f, 1f);
        HealthValueLabel.Text = $"{state.Health}/{state.MaxHealth}";
        GeneticDamageBar.Value = state.MaxGeneticDamage <= 0
            ? 0f
            : Math.Clamp(state.GeneticDamage / (float) state.MaxGeneticDamage, 0f, 1f);
        GeneticDamageValueLabel.Text = $"{state.GeneticDamage}/{state.MaxGeneticDamage}";
        HumanizeButton.Visible = true;
        HumanizeButton.Disabled = !state.CanHumanizeSubject;
        HumanizeButton.OnPressed -= OnHumanizePressed;
        HumanizeButton.OnPressed += OnHumanizePressed;
        ScrambleButton.Disabled = !state.IsHumanoidSubject || state.SubjectName == null;
        FeedbackLabel.Text = state.ResultMessage ?? string.Empty;

        var selected = state.Mutations.FirstOrDefault(entry => entry.Id == _selectedMutationId)
                       ?? state.Mutations.FirstOrDefault();
        if (selected == null)
        {
            _selectedMutation = null;
        }
        else
        {
            var candidateSequence = selected.Discovered
                ? selected.CandidateSequence
                : _candidateSequences.TryGetValue(selected.Id, out var candidate)
                    ? candidate
                    : selected.CandidateSequence;
            var candidateComplement = selected.Discovered
                ? selected.CandidateComplementSequence
                : _candidateComplementSequences.TryGetValue(selected.Id, out var complement)
                    ? complement
                    : selected.CandidateComplementSequence;
            _candidateSequences[selected.Id] = candidateSequence;
            _candidateComplementSequences[selected.Id] = candidateComplement;
            _selectedMutation = CopyWithCandidate(selected, candidateSequence, candidateComplement);
        }

        _selectedMutationId = _selectedMutation?.Id;

        PopulateMutationSelector(state);
        PopulateSelectedMutation(state);
        PopulateStorage(state, onCreateInjector);
        PopulateFeatures(state, onCreateInjector);

        AnalyzeButton.Text = state.JokerCooldown > 0
            ? Loc.GetString("genetics-console-joker-cooldown-button", ("seconds", state.JokerCooldown))
            : Loc.GetString("genetics-console-joker");
        AnalyzeButton.Disabled |= state.JokerCooldown > 0;
    }

    private void PopulateMutationSelector(GeneticsConsoleBoundUserInterfaceState state)
    {
        MutationList.Children.Clear();
        foreach (var mutation in state.Mutations)
        {
            var index = state.Mutations.IndexOf(mutation) + 1;
            var button = new Button
            {
                Text = mutation.Discovered ? mutation.Name : Loc.GetString("genetics-console-gene-button-unknown", ("index", index)),
                HorizontalExpand = true,
                MinSize = new System.Numerics.Vector2(0, 48),
                ToolTip = mutation.Discovered
                    ? mutation.Description
                    : Loc.GetString("genetics-console-unknown-description"),
            };
            if (mutation.Id == _selectedMutationId)
                button.ModulateSelfOverride = Color.FromHex("#357c88");
            else if (!mutation.Discovered)
                button.ModulateSelfOverride = Color.FromHex("#514565");
            else if (mutation.Active)
                button.ModulateSelfOverride = Color.FromHex("#3e704d");
            button.OnPressed += _ =>
            {
                _selectedMutationId = mutation.Id;
                var candidateSequence = _candidateSequences.TryGetValue(mutation.Id, out var candidate)
                    ? candidate
                    : mutation.CandidateSequence;
                var candidateComplement = _candidateComplementSequences.TryGetValue(mutation.Id, out var complement)
                    ? complement
                    : mutation.CandidateComplementSequence;
                _selectedMutation = CopyWithCandidate(mutation, candidateSequence, candidateComplement);
                PopulateMutationSelector(state);
                PopulateSelectedMutation(state);
            };
            MutationList.AddChild(button);
        }
    }

    private void PopulateSelectedMutation(GeneticsConsoleBoundUserInterfaceState state)
    {
        if (_selectedMutation is not { } mutation)
        {
            SelectedMutationName.Text = string.Empty;
            SelectedMutationDescription.Text = string.Empty;
            SequenceProgressLabel.Text = string.Empty;
            GuessButton.Disabled = true;
            AnalyzeButton.Disabled = true;
            ApplySelectedButton.Disabled = true;
            SequenceTopStrand.Children.Clear();
            SequenceBottomStrand.Children.Clear();
            _topStrandButtons.Clear();
            _bottomStrandButtons.Clear();
            _sequenceMutationId = null;
            return;
        }

        SelectedMutationName.Text = mutation.Name;
        SelectedMutationDescription.Text = mutation.Description;
        if (_sequenceMutationId != mutation.Id ||
            _topStrandButtons.Count != mutation.Sequence.Length ||
            _bottomStrandButtons.Count != mutation.Sequence.Length)
        {
            BuildSequenceLadder(mutation);
        }

        RefreshSequenceLadder(mutation);
        var completedPairs = 0;
        for (var i = 0; i < mutation.Sequence.Length; i++)
        {
            if (mutation.KnownPositions.Contains(i) ||
                (mutation.CandidateSequence[i] is 'A' or 'T' or 'G' or 'C') &&
                (mutation.CandidateComplementSequence[i] is 'A' or 'T' or 'G' or 'C'))
                completedPairs++;
        }
        var partialPairs = mutation.HalfKnownPositions.Count(i =>
            mutation.CandidateComplementSequence[i] is not ('A' or 'T' or 'G' or 'C'));
        var unknownPairs = mutation.Sequence.Length - completedPairs - partialPairs;
        SequenceProgressLabel.Text = Loc.GetString(
            "genetics-console-sequence-status",
            ("known", completedPairs),
            ("partial", partialPairs),
            ("unknown", unknownPairs));
        GuessButton.Disabled = mutation.Discovered ||
                              state.SubjectName == null ||
                              !HasCompleteCandidate(mutation);
        AnalyzeButton.Disabled = mutation.Discovered || state.SubjectName == null;
        ApplySelectedButton.Disabled = !mutation.Discovered || mutation.Active || state.SubjectName == null;
    }

    private void BuildSequenceLadder(GeneticsMutationUiEntry mutation)
    {
        SequenceTopStrand.Children.Clear();
        SequenceBottomStrand.Children.Clear();
        _topStrandButtons.Clear();
        _bottomStrandButtons.Clear();

        for (var i = 0; i < mutation.Sequence.Length; i++)
        {
            var index = i;
            var topButton = CreateNucleotideButton();
            topButton.OnPressed += _ => CycleNucleotide(index, true);
            SequenceTopStrand.AddChild(topButton);
            _topStrandButtons.Add(topButton);

            var bottomButton = CreateNucleotideButton();
            bottomButton.OnPressed += _ => CycleNucleotide(index, false);
            SequenceBottomStrand.AddChild(bottomButton);
            _bottomStrandButtons.Add(bottomButton);
        }

        _sequenceMutationId = mutation.Id;
    }

    private static Button CreateNucleotideButton()
    {
        return new Button
        {
            Text = "?",
            MinSize = new System.Numerics.Vector2(27, 34),
            ToolTip = Loc.GetString("genetics-console-cycle-nucleotide-tooltip"),
        };
    }

    private void CycleNucleotide(int index, bool topStrand)
    {
        if (_selectedMutation is not { Discovered: false } mutation)
            return;

        if (mutation.KnownPositions.Contains(index))
            return;

        if (topStrand && mutation.HalfKnownPositions.Contains(index))
            return;

        var button = topStrand ? _topStrandButtons[index] : _bottomStrandButtons[index];
        var bases = "ATGC";
        var current = button.Text is { Length: 1 } currentBase && currentBase[0] != '?'
            ? bases.IndexOf(currentBase[0])
            : -1;
        var next = bases[(current + 1) % bases.Length];
        var candidate = mutation.CandidateSequence.ToCharArray();
        var candidateComplement = mutation.CandidateComplementSequence.ToCharArray();
        if (topStrand)
            candidate[index] = next;
        else
            candidateComplement[index] = next;
        var candidateSequence = new string(candidate);
        var candidateComplementSequence = new string(candidateComplement);

        _candidateSequences[mutation.Id] = candidateSequence;
        _candidateComplementSequences[mutation.Id] = candidateComplementSequence;
        _selectedMutation = CopyWithCandidate(mutation, candidateSequence, candidateComplementSequence);
        RefreshSequenceLadder(_selectedMutation);
        _onMutationAction?.Invoke(
            _selectedMutation,
            GeneticsConsoleAction.SetSequence,
            candidateSequence,
            candidateComplementSequence);

        var completedPairs = Enumerable.Range(0, mutation.Sequence.Length).Count(i =>
            mutation.KnownPositions.Contains(i) ||
            (candidateSequence[i] is 'A' or 'T' or 'G' or 'C') &&
            (candidateComplementSequence[i] is 'A' or 'T' or 'G' or 'C'));
        SequenceProgressLabel.Text = Loc.GetString(
            "genetics-console-sequence-status",
            ("known", completedPairs),
            ("partial", mutation.HalfKnownPositions.Count(i =>
                candidateComplementSequence[i] is not ('A' or 'T' or 'G' or 'C'))),
            ("unknown", mutation.Sequence.Length - completedPairs - mutation.HalfKnownPositions.Count(i =>
                candidateComplementSequence[i] is not ('A' or 'T' or 'G' or 'C'))));
        GuessButton.Disabled = !HasCompleteCandidate(_selectedMutation);
    }

    private void RefreshSequenceLadder(GeneticsMutationUiEntry mutation)
    {
        for (var i = 0; i < mutation.Sequence.Length; i++)
        {
            var candidate = mutation.CandidateSequence[i];
            var discovered = mutation.Discovered;
            var positionKnown = discovered || mutation.KnownPositions.Contains(i);

            if (positionKnown)
            {
                var top = mutation.CandidateSequence[i];
                var bottom = GeneticMutationPrototype.GetComplement(top);
                SetNucleotideButton(_topStrandButtons[i], top, true, true);
                SetNucleotideButton(_bottomStrandButtons[i], bottom, true, true);
                continue;
            }

            if (mutation.HalfKnownPositions.Contains(i))
            {
                SetNucleotideButton(_topStrandButtons[i], mutation.CandidateSequence[i], true, false);
                SetNucleotideButton(_bottomStrandButtons[i], mutation.CandidateComplementSequence[i], false, false);
                _bottomStrandButtons[i].ModulateSelfOverride = Color.FromHex("#c99735");
                continue;
            }

            var guessedTop = candidate is 'A' or 'T' or 'G' or 'C' ? candidate : '?';
            var guessedBottom = mutation.CandidateComplementSequence[i] is 'A' or 'T' or 'G' or 'C'
                ? mutation.CandidateComplementSequence[i]
                : '?';
            var pairHasComplement = (guessedTop is 'A' or 'T' or 'G' or 'C') &&
                                    guessedBottom == GeneticMutationPrototype.GetComplement(guessedTop);
            SetNucleotideButton(_topStrandButtons[i], guessedTop, false, pairHasComplement);
            SetNucleotideButton(_bottomStrandButtons[i], guessedBottom, false, pairHasComplement);
        }
    }

    private static void SetNucleotideButton(Button button, char nucleotide, bool disabled, bool correct)
    {
        button.Text = nucleotide.ToString();
        button.Disabled = disabled;
        button.ModulateSelfOverride = correct
            ? Color.FromHex("#46d66c")
            : nucleotide is 'A' or 'T' or 'G' or 'C'
                ? NucleotideColor(nucleotide)
                : Color.FromHex("#78828a");
    }

    private static GeneticsMutationUiEntry CopyWithCandidate(
        GeneticsMutationUiEntry mutation,
        string candidateSequence,
        string candidateComplementSequence)
    {
        var sequence = candidateSequence.ToCharArray();
        var complement = candidateComplementSequence.ToCharArray();
        for (var i = 0; i < mutation.Sequence.Length; i++)
        {
            if (mutation.KnownPositions.Contains(i))
            {
                sequence[i] = mutation.CandidateSequence[i];
                complement[i] = mutation.CandidateComplementSequence[i];
            }
            else if (mutation.HalfKnownPositions.Contains(i))
            {
                sequence[i] = mutation.CandidateSequence[i];
            }
        }

        return new GeneticsMutationUiEntry(
            mutation.Id,
            mutation.Name,
            mutation.Description,
            mutation.Sequence,
            new string(sequence),
            new string(complement),
            mutation.SequenceProgress,
            mutation.Discovered,
            mutation.Active,
            mutation.Instability,
            mutation.KnownPositions,
            mutation.HalfKnownPositions);
    }

    private static bool HasCompleteCandidate(GeneticsMutationUiEntry mutation)
    {
        for (var i = 0; i < mutation.Sequence.Length; i++)
        {
            if (mutation.KnownPositions.Contains(i))
                continue;
            if (mutation.CandidateSequence[i] is not ('A' or 'T' or 'G' or 'C') ||
                mutation.CandidateComplementSequence[i] is not ('A' or 'T' or 'G' or 'C'))
                return false;
        }

        return true;
    }

    private void PopulateStorage(GeneticsConsoleBoundUserInterfaceState state, Action<string> onCreateInjector)
    {
        MemoryList.Children.Clear();
        StorageMutationList.Children.Clear();
        MemoryCapacityLabel.Text = Loc.GetString(
            "genetics-console-memory-title",
            ("used", state.Memory.Count),
            ("max", state.MaxMemorySlots));

        foreach (var memory in state.Memory)
        {
            var select = new Button
            {
                Text = Loc.GetString("genetics-console-memory-slot", ("slot", state.Memory.IndexOf(memory) + 1), ("name", memory.Name)),
                HorizontalExpand = true,
            };
            if (memory.Id == _selectedMemoryId)
                select.ModulateSelfOverride = Color.FromHex("#357c88");
            select.OnPressed += _ =>
            {
                _selectedMemoryId = memory.Id;
                UpdateStorageDetails(memory);
                PopulateStorage(state, onCreateInjector);
            };
            MemoryList.AddChild(select);
        }

        if (state.Memory.Count == 0)
            MemoryList.AddChild(new Label { Text = Loc.GetString("genetics-console-memory-empty") });

        foreach (var mutation in state.Mutations.Where(entry => entry.Discovered))
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            row.AddChild(new Label { Text = mutation.Name, HorizontalExpand = true });
            var save = new Button
            {
                Text = Loc.GetString("genetics-console-save-to-memory", ("name", mutation.Name)),
                Disabled = state.Memory.Any(entry => entry.Id == mutation.Id) ||
                           state.Memory.Count >= state.MaxMemorySlots,
            };
            save.OnPressed += _ => _onMutationAction?.Invoke(
                mutation,
                GeneticsConsoleAction.SaveToMemory,
                string.Empty,
                string.Empty);
            row.AddChild(save);
            StorageMutationList.AddChild(row);
        }

        if (state.Mutations.All(m => !m.Discovered))
            StorageMutationList.AddChild(new Label { Text = Loc.GetString("genetics-console-no-discovered-mutations") });

        _selectedMemoryId ??= state.Memory.FirstOrDefault()?.Id;
        var selectedMemory = state.Memory.FirstOrDefault(entry => entry.Id == _selectedMemoryId);
        UpdateStorageDetails(selectedMemory);
        PrintActivatorButton.Disabled = selectedMemory == null;
        PrintMutatorButton.Disabled = selectedMemory == null;
        PrintActivatorButton.OnPressed -= OnPrintActivatorPressed;
        PrintMutatorButton.OnPressed -= OnPrintMutatorPressed;
        PrintActivatorButton.OnPressed += OnPrintActivatorPressed;
        PrintMutatorButton.OnPressed += OnPrintMutatorPressed;
    }

    private void UpdateStorageDetails(GeneticsMemoryUiEntry? memory)
    {
        StorageSelectedName.Text = memory?.Name ?? Loc.GetString("genetics-console-memory-empty");
        StorageSelectedDescription.Text = memory?.Description ?? string.Empty;
        StorageSelectedInstability.Text = memory == null
            ? string.Empty
            : Loc.GetString("genetics-console-mutation-instability", ("value", memory.Instability));
    }

    private void OnPrintActivatorPressed(BaseButton.ButtonEventArgs args)
    {
        if (_selectedMemoryId is { } id)
            _onCreateInjector?.Invoke($"{id}:activator");
    }

    private void OnPrintMutatorPressed(BaseButton.ButtonEventArgs args)
    {
        if (_selectedMemoryId is { } id)
            _onCreateInjector?.Invoke($"{id}:mutator");
    }

    private void PopulateFeatures(GeneticsConsoleBoundUserInterfaceState state, Action<string> onCreateInjector)
    {
        FeaturesList.Children.Clear();
        foreach (var mutation in state.Mutations)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(4),
            };
            row.AddChild(new Label { Text = mutation.Name, HorizontalExpand = true });
            if (mutation.Discovered)
            {
                row.AddChild(new Label
                {
                    Text = $"{mutation.Description} ({Loc.GetString("genetics-console-mutation-instability", ("value", mutation.Instability))})",
                    HorizontalExpand = true,
                });
                
                var buttonRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
                
                var apply = new Button
                {
                    Text = Loc.GetString(mutation.Active
                        ? "genetics-console-applied"
                        : "genetics-console-apply"),
                    Disabled = mutation.Active,
                    HorizontalExpand = true,
                };
                apply.OnPressed += _ => _onMutationAction?.Invoke(
                    mutation,
                    GeneticsConsoleAction.Apply,
                    string.Empty,
                    string.Empty);
                buttonRow.AddChild(apply);
                
                var activator = new Button
                {
                    Text = "Activator (5m)",
                    HorizontalExpand = true,
                };
                activator.OnPressed += _ => onCreateInjector($"{mutation.Id}:activator");
                buttonRow.AddChild(activator);
                
                var mutator = new Button
                {
                    Text = "Mutator (∞)",
                    HorizontalExpand = true,
                };
                mutator.OnPressed += _ => onCreateInjector($"{mutation.Id}:mutator");
                buttonRow.AddChild(mutator);
                
                row.AddChild(buttonRow);
            }
            else
            {
                row.AddChild(new Label { Text = Loc.GetString("genetics-console-feature-undiscovered") });
            }

            FeaturesList.AddChild(row);
        }
    }

    private void OnGuessPressed(BaseButton.ButtonEventArgs args)
    {
        if (_selectedMutation is { } mutation && !GuessButton.Disabled)
            _onMutationAction?.Invoke(
                mutation,
                GeneticsConsoleAction.GuessSequence,
                mutation.CandidateSequence,
                mutation.CandidateComplementSequence);
    }

    private void OnAnalyzePressed(BaseButton.ButtonEventArgs args)
    {
        if (_selectedMutation is { } mutation && !AnalyzeButton.Disabled)
            _onMutationAction?.Invoke(mutation, GeneticsConsoleAction.Analyze, string.Empty, string.Empty);
    }

    private void OnApplyPressed(BaseButton.ButtonEventArgs args)
    {
        if (_selectedMutation is { } mutation && !ApplySelectedButton.Disabled)
            _onMutationAction?.Invoke(mutation, GeneticsConsoleAction.Apply, string.Empty, string.Empty);
    }

    private void OnHumanizePressed(BaseButton.ButtonEventArgs args)
    {
        _onHumanize?.Invoke();
    }

    private void OnScramblePressed(BaseButton.ButtonEventArgs args)
    {
        _onScramble?.Invoke();
    }

    private static Color NucleotideColor(char nucleotide)
    {
        return nucleotide switch
        {
            'A' => Color.FromHex("#36a765"),
            'T' => Color.FromHex("#159bb3"),
            'G' => Color.FromHex("#3276c2"),
            'C' => Color.FromHex("#2858a8"),
            _ => Color.White,
        };
    }
}
