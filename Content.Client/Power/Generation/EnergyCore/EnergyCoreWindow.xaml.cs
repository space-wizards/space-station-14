using Content.Shared.Power.Generation.EnergyCore;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Power.Generation.EnergyCore;

[GenerateTypedNameReferences]
public sealed partial class EnergyCoreWindow : DefaultWindow
{
    public event Action<bool>? OnSetEnabled;
    public event Action<float>? OnSetOutput;
    private bool _running;

    public EnergyCoreWindow()
    {
        RobustXamlLoader.Load(this);
        PowerButton.OnPressed += OnPowerPressed;
        OutputSlider.OnReleased += slider => OnSetOutput?.Invoke(slider.Value * 1000);
        OutputSlider.OnValueChanged += _ => UpdateTargetLabel();
    }

    private void OnPowerPressed(BaseButton.ButtonEventArgs args)
    {
        OnSetEnabled?.Invoke(!_running);
    }

    private void UpdateTargetLabel()
    {
        Target.Text = Loc.GetString("energy-core-target", ("power", OutputSlider.Value));
    }

    public void UpdateState(EnergyCoreUiState state)
    {
        _running = state.State is EnergyCoreState.Enabled or EnergyCoreState.Starting;
        Status.Text = Loc.GetString(!state.Connected ? "energy-core-disconnected" : state.State switch
        {
            EnergyCoreState.Enabled => "energy-core-enabled",
            EnergyCoreState.Starting => "energy-core-starting",
            EnergyCoreState.Stopping => "energy-core-stopping",
            _ => "energy-core-disabled",
        });
        Radiation.Text = Loc.GetString("energy-core-radiation", ("radiation", state.Radiation));
        OutputSlider.Disabled = !state.Connected;
        Fuel.Text = Loc.GetString("energy-core-fuel", ("energy", state.FuelEnergy / 1000000));
        Temperature.Text = Loc.GetString("energy-core-temperature", ("temperature", state.Temperature),
            ("restart", state.RestartTemperature));
        Supply.Text = Loc.GetString("energy-core-supply", ("power", state.Supply / 1000));
        Heat.Text = Loc.GetString("energy-core-heat", ("power", state.HeatOutput / 1000));
        Reaction.Text = Loc.GetString("energy-core-reaction", ("power", state.FissionPower / 1000), ("decay", state.DecayHeat / 1000));
        Conversion.Text = Loc.GetString("energy-core-conversion", ("efficiency", state.Efficiency * 100), ("energy", state.ElectricalEnergy / 1000));
        Flow.Text = Loc.GetString("energy-core-flow", ("flow", state.CoolantFlow));
        Inlet.Text = Loc.GetString("energy-core-inlet", ("temperature", state.InletTemperature), ("pressure", state.InletPressure));
        Outlet.Text = Loc.GetString("energy-core-outlet", ("temperature", state.OutletTemperature), ("pressure", state.OutletPressure));
        if (!OutputSlider.Grabbed)
        {
            OutputSlider.MaxValue = Math.Max(1, state.MaxSupply / 1000);
            OutputSlider.SetValueWithoutEvent(state.TargetSupply / 1000);
            UpdateTargetLabel();
        }
        PowerButton.Text = Loc.GetString(_running ? "energy-core-stop" : "energy-core-start");
        PowerButton.Disabled = !state.Connected || state.State == EnergyCoreState.Stopping ||
            (!_running && (state.FuelEnergy <= 0 || state.Temperature >= state.RestartTemperature));
    }
}
