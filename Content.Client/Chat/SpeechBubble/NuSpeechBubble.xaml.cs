using System.Numerics;
using Content.Shared.Chat;
using Content.Shared.IdentityManagement;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.Chat.SpeechBubble;

[GenerateTypedNameReferences]
public sealed partial class NuSpeechBubble : Control
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IEyeManager _eyeManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    public enum SpeechType : byte
    {
        Emote,
        Say,
        Whisper,
        Looc
    }

    /// <summary>
    ///     The total time a speech bubble stays on screen.
    /// </summary>
    private static readonly TimeSpan TotalTime = TimeSpan.FromSeconds(4f);

    /// <summary>
    ///     The amount of time at the end of the bubble's life at which it starts fading.
    /// </summary>
    private static readonly TimeSpan FadeTime = TimeSpan.FromSeconds(0.25f);

    /// <summary>
    /// The time this bubble was created
    /// </summary>
    public TimeSpan SpawnTime;

    /// <summary>
    /// The time at which this bubble will die.
    /// </summary>
    private TimeSpan _deathTime;

    private readonly EntityUid _senderEntity;

    public event Action<EntityUid, NuSpeechBubble>? OnDied;

    public Vector2 ContentSize { get; private set; }

    public NuSpeechBubble(ChatMessage message, SpeechType type, EntityUid senderEntity, Color? fontColor = null)
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        RectClipContent = true;

        var styleClass = GetStyle(type);
        LabelPanel.StyleClasses.Add(styleClass);

        //Probably need a better way of handling this
        if (message.Channel == ChatChannel.Dead)
        {
            fontColor = Color.MediumPurple;
            var name = Identity.Name(senderEntity, _entityManager);
            NameLabel.SetMessage(name, Color.MediumSlateBlue);
            NameLabel.Visible = true;
        }

        //TODO: Kill bubbleContent in chat code so we don't have to regex everything ever made
        switch (type)
        {
            case SpeechType.Emote:
                Label.SetMessage(FormatSpeech(message.WrappedMessage, Color.White));
                break;
            case SpeechType.Looc:
                Label.SetMessage(FormatSpeech(message.WrappedMessage, Color.FromHex("#48d1cc")));
                break;
            case SpeechType.Whisper:
                Label.SetMessage(ExtractAndFormatSpeechSubstring(message, "BubbleContent", fontColor));
                break;
            case SpeechType.Say:
                Label.SetMessage(ExtractAndFormatSpeechSubstring(message, "BubbleContent", fontColor));
                break;

            default:
                throw new ArgumentOutOfRangeException();
        }

        _senderEntity = senderEntity;

        LabelPanel.Measure(Vector2Helpers.Infinity);
        ContentSize = LabelPanel.DesiredSize;

        SpawnTime = _timing.RealTime;
        _deathTime = _timing.RealTime + TotalTime;
        OverlaySetup();
    }

    private FormattedMessage FormatSpeech(string message, Color? fontColor = null)
    {
        var msg = new FormattedMessage();
        if (fontColor != null)
            msg.PushColor(fontColor.Value);
        msg.AddMarkupOrThrow(message);
        return msg;
    }

    private FormattedMessage ExtractAndFormatSpeechSubstring(ChatMessage message, string tag, Color? fontColor = null)
    {
        return FormatSpeech(SharedChatSystem.GetStringInsideTag(message, tag), fontColor);
    }

    private static string GetStyle(SpeechType type)
    {
        return type switch
        {
            SpeechType.Emote => "emoteBox",
            SpeechType.Whisper => "whisperBox",
            SpeechType.Looc => "emoteBox",
            _ => "sayBox",
        };
    }

    /// <summary>
    /// These are typically drawn in the overlay, so regular FrameUpdate doesn't apply.
    /// This is called from the overlay.
    /// </summary>
    public void Update(FrameEventArgs args)
    {
        var timeLeft = (float)(_deathTime - _timing.RealTime).TotalSeconds;

        if (_entityManager.Deleted(_senderEntity) || timeLeft <= 0)
        {
            // Timer spawn to prevent concurrent modification exception.
            Timer.Spawn(0, Die);
            return;
        }

        //Hide if offscreen
        if (!_entityManager.TryGetComponent<TransformComponent>(_senderEntity, out var xform) || xform.MapID != _eyeManager.CurrentEye.Position.MapId)
        {
            Modulate = Color.White.WithAlpha(0);
            return;
        }

        if (timeLeft <= FadeTime.TotalSeconds)
        {
            // Update alpha if we're fading.
            Modulate = Color.White.WithAlpha(timeLeft / (float)FadeTime.TotalSeconds);
        }
        else
        {
            // Make opaque otherwise, because it might have been hidden before
            Modulate = Color.White;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        //If for some reason this isn't drawn in an overlay.
        //Probably shouldn't happen.
        Update(args);
    }

    //TODO: Replace
    private void Die()
    {
        if (Disposed)
        {
            return;
        }

        OnDied?.Invoke(_senderEntity, this);
    }

    /// <summary>
    /// Causes the speech bubble to start fading IMMEDIATELY.
    /// </summary>
    public void FadeNow()
    {
        if (_deathTime > _timing.RealTime)
        {
            _deathTime = _timing.RealTime + FadeTime;
        }
    }

    /// <summary>
    /// Prepares the control to be used in an overlay.
    /// TODO: Figure out how much of this is actually needed.
    /// </summary>
    private void OverlaySetup()
    {
        InvalidateStyleSheet();
        ForceRunStyleUpdate();

        InvalidateMeasure();
        InvalidateArrange();

        Measure(Vector2.PositiveInfinity);

        Arrange(UIBox2.FromDimensions(Vector2.Zero, DesiredSize));
    }
}

