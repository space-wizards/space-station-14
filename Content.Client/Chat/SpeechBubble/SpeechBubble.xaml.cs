using Content.Shared.CCVar;
using Content.Shared.Chat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Utility;

namespace Content.Client.Chat.SpeechBubble;

[GenerateTypedNameReferences]
public sealed partial class SpeechBubble : BaseSpeechBubble
{
    [Dependency] private IConfigurationManager _config = default!;

    public enum SpeechType : byte
    {
        Emote,
        Say,
        Whisper,
        Looc
    }

    public SpeechBubble(ChatMessage message, SpeechType type, string name, EntityUid senderEntity, Color? fontColor = null) : base(senderEntity)
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        RectClipContent = true;

        if (fontColor == null)
            fontColor = Color.White;

        //Probably need a better way of handling this
        if (message.Channel == ChatChannel.Dead)
        {
            //ghost speak in white text, ghosts are white
            fontColor = Color.White;
            NameLabel.SetMessage(name, Color.White);
            NameLabel.Visible = true;
        }

        //For bubble background.
        //I guess it improves readability against floor tiles, mostly here to make people happy.
        //TODO: Add an accessibility option for actual contrast
        if (_config.GetCVar(CCVars.ChatBubbleBackground))
        {
            LabelPanel.StyleClasses.Add("bubblePanel");
            LabelPanel.ModulateSelfOverride = fontColor.Value.WithAlpha(_config.GetCVar(CCVars.SpeechBubbleBackgroundOpacity));
        }

        var styleClass = GetStyle(type);
        LabelPanel.StyleClasses.Add(styleClass);

        //TODO: Chat refactor make me happy happy happy
        switch (type)
        {
            case SpeechType.Emote:
                Label.SetMessage(FormatSpeech(message.WrappedMessage, Color.White));
                break;
            case SpeechType.Looc:
                Label.SetMessage(FormatSpeech(message.WrappedMessage, Color.FromHex("#48d1cc")));
                break;
            case SpeechType.Whisper:
                Label.SetMessage(ExtractAndFormatSpeechSubstring(message, "BubbleContent", fontColor));
                break;
            case SpeechType.Say:
                Label.SetMessage(ExtractAndFormatSpeechSubstring(message, "BubbleContent", fontColor));
                break;

            default:
                throw new ArgumentOutOfRangeException();
        }

        LabelPanel.Measure(Vector2Helpers.Infinity);
        SetContentSize(LabelPanel.DesiredSize);

        OverlaySetup();
    }

    private FormattedMessage FormatSpeech(string message, Color? fontColor = null)
    {
        var msg = new FormattedMessage();
        if (fontColor != null)
            msg.PushColor(fontColor.Value);
        msg.AddMarkupOrThrow(message);
        return msg;
    }

    private FormattedMessage ExtractAndFormatSpeechSubstring(ChatMessage message, string tag, Color? fontColor = null)
    {
        return FormatSpeech(SharedChatSystem.GetStringInsideTag(message, tag), fontColor);
    }

    private static string GetStyle(SpeechType type)
    {
        return type switch
        {
            SpeechType.Emote => "emoteBox",
            SpeechType.Whisper => "whisperBox",
            SpeechType.Looc => "maldBox",
            _ => "sayBox",
        };
    }
}

