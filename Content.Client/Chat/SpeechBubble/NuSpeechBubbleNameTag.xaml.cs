using System.Numerics;
using Content.Shared.IdentityManagement;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.Chat.SpeechBubble;

[GenerateTypedNameReferences]
public sealed partial class NuSpeechBubbleNameTag : Control
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IEyeManager _eyeManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;


    /// <summary>
    ///     The total time a speech bubble stays on screen.
    /// </summary>
    private static readonly TimeSpan TotalTime = TimeSpan.FromSeconds(4f);

    /// <summary>
    ///     The amount of time at the end of the bubble's life at which it starts fading.
    /// </summary>
    private static readonly TimeSpan FadeTime = TimeSpan.FromSeconds(0.25f);

    /// <summary>
    /// The time at which this bubble will die.
    /// </summary>
    private TimeSpan _deathTime;

    private readonly EntityUid _senderEntity;

    public event Action<EntityUid, NuSpeechBubbleNameTag>? OnDied;

    public Vector2 ContentSize { get; private set; }

    public NuSpeechBubbleNameTag(EntityUid entity, Color? nameColor = null)
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        var name = Identity.Name(entity, _entityManager);

        NameLabel.SetMessage(name, nameColor);

        LabelPanel.Measure(Vector2Helpers.Infinity);
        ContentSize = LabelPanel.DesiredSize;

        _senderEntity = entity;
        _deathTime = _timing.RealTime + TotalTime;
        OverlaySetup();
    }

    public void SetDeathTime(TimeSpan time)
    {
        _deathTime = time;
    }

    /// <summary>
    /// These are typically drawn in the overlay, so regular FrameUpdate doesn't apply.
    /// This is called from the overlay.
    /// </summary>
    public void Update(FrameEventArgs args)
    {
        var timeLeft = (float)(_deathTime - _timing.RealTime).TotalSeconds;

        if (_entityManager.Deleted(_senderEntity) || timeLeft <= 0)
        {
            // Timer spawn to prevent concurrent modification exception.
            Timer.Spawn(0, Die);
            return;
        }

        //Hide if offscreen
        if (!_entityManager.TryGetComponent<TransformComponent>(_senderEntity, out var xform) || xform.MapID != _eyeManager.CurrentEye.Position.MapId)
        {
            Modulate = Color.White.WithAlpha(0);
            return;
        }

        if (timeLeft <= FadeTime.TotalSeconds)
        {
            // Update alpha if we're fading.
            Modulate = Color.White.WithAlpha(timeLeft / (float)FadeTime.TotalSeconds);
        }
        else
        {
            // Make opaque otherwise, because it might have been hidden before
            Modulate = Color.White;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        //If for some reason this isn't drawn in an overlay.
        //Probably shouldn't happen.
        Update(args);
    }

    //TODO: Replace
    private void Die()
    {
        if (Disposed)
        {
            return;
        }

        OnDied?.Invoke(_senderEntity, this);
    }

    /// <summary>
    /// Causes the speech bubble to start fading IMMEDIATELY.
    /// </summary>
    public void FadeNow()
    {
        if (_deathTime > _timing.RealTime)
        {
            _deathTime = _timing.RealTime + FadeTime;
        }
    }

    /// <summary>
    /// Prepares the control to be used in an overlay.
    /// TODO: Figure out how much of this is actually needed.
    /// </summary>
    private void OverlaySetup()
    {
        InvalidateStyleSheet();
        ForceRunStyleUpdate();

        InvalidateMeasure();
        InvalidateArrange();

        Measure(Vector2.PositiveInfinity);

        Arrange(UIBox2.FromDimensions(Vector2.Zero, DesiredSize));
    }
}

