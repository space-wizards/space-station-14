using Content.Shared.IdentityManagement;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Chat.SpeechBubble;

[GenerateTypedNameReferences]
public sealed partial class NuSpeechBubbleNameTag : BaseSpeechBubble
{
    [Dependency] private IEntityManager _entityManager = default!;

    public NuSpeechBubbleNameTag(EntityUid senderEntity, Color? nameColor = null) : base(senderEntity)
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        RectClipContent = true;

        var name = Identity.Name(senderEntity, _entityManager);
        NameLabel.SetMessage(name, nameColor);

        LabelPanel.Measure(Vector2Helpers.Infinity);

        if (nameColor != null)
        {
            var style = new StyleBoxFlat
            {
                BackgroundColor = nameColor.Value,
                ContentMarginLeftOverride = 2,
                ContentMarginBottomOverride = 2
            };
            DividerPanel.PanelOverride = style;
        }


        SetContentSize(LabelPanel.DesiredSize);
        OverlaySetup();
    }
}

