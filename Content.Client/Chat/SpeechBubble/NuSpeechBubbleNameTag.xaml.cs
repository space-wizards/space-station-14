using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Chat.SpeechBubble;

[GenerateTypedNameReferences]
public sealed partial class NuSpeechBubbleNameTag : BaseSpeechBubble
{
    public NuSpeechBubbleNameTag(EntityUid senderEntity, string name, Color? nameColor = null) : base(senderEntity)
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        RectClipContent = true;

        Update(name, nameColor);
    }

    public void Update(string name, Color? nameColor = null)
    {
        NameLabel.SetMessage(name, nameColor);

        LabelPanel.Measure(Vector2Helpers.Infinity);

        if (nameColor != null)
        {
            var style = new StyleBoxFlat
            {
                BackgroundColor = nameColor.Value,
                ContentMarginLeftOverride = 2,
                ContentMarginBottomOverride = 2
            };
            DividerPanel.PanelOverride = style;
        }

        SetContentSize(LabelPanel.DesiredSize);
        OverlaySetup();
    }
}

