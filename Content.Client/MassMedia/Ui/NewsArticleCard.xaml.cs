using Content.Shared.MassMedia.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client.MassMedia.Ui;

[GenerateTypedNameReferences]
public sealed partial class NewsArticleCard : Control
{
    private string? _authorMarkup;
    private TimeSpan? _publicationTime;

    public Action<int>? OnDeletePressed;
    public Action<int>? OnToggleLockCommentsPressed;
    public Action<int, int>? OnDeleteCommentPressed;
    public Action<int, bool>? OnCommentsExpandedChanged;
    public int ArtcileNumber;
    public int ArticleId;

    public string? Title
    {
        get => TitleLabel.Text;
        set => TitleLabel.Text = value?.Length <= 30 ? value : $"{value?[..30]}...";
    }

    public string? Author
    {
        get => _authorMarkup;
        set
        {
            _authorMarkup = value;
            AuthorLabel.Text = _authorMarkup ?? "";
        }
    }

    public TimeSpan? PublicationTime
    {
        get => _publicationTime;
        set
        {
            _publicationTime = value;
            PublishTimeLabel.Text = value?.ToString(@"hh\:mm\:ss") ?? "";
        }
    }

    public NewsArticleCard()
    {
        RobustXamlLoader.Load(this);
        DeleteButton.OnPressed += _ => OnDeletePressed?.Invoke(ArtcileNumber);
        LockCommentsButton.OnPressed += _ => OnToggleLockCommentsPressed?.Invoke(ArtcileNumber);
        ToggleCommentsButton.OnPressed += _ =>
        {
            CommentsContainer.Visible = !CommentsContainer.Visible;
            OnCommentsExpandedChanged?.Invoke(ArticleId, CommentsContainer.Visible);
        };
    }

    /// <summary>
    /// Populates the reaction summary, thread lock status, and comment moderation entries for this article card.
    /// </summary>
    public void PopulateArticleDetails(NewsArticle article, bool commentsExpanded)
    {
        ArticleId = article.ArticleId;
        CommentsContainer.Visible = commentsExpanded;

        var counts = article.ReactionCounts;
        var up = counts != null && counts.TryGetValue(NewsReactionType.Upvote, out var u) ? u : 0;
        var down = counts != null && counts.TryGetValue(NewsReactionType.Downvote, out var d) ? d : 0;
        var laugh = counts != null && counts.TryGetValue(NewsReactionType.Laugh, out var l) ? l : 0;
        var shock = counts != null && counts.TryGetValue(NewsReactionType.Shock, out var s) ? s : 0;
        var heart = counts != null && counts.TryGetValue(NewsReactionType.Heart, out var h) ? h : 0;

        ReactionsSummaryLabel.Text = Loc.GetString(
            "news-write-ui-reactions-summary",
            ("upSymbol", Loc.GetString("news-read-ui-reaction-upvote")),
            ("up", up),
            ("downSymbol", Loc.GetString("news-read-ui-reaction-downvote")),
            ("down", down),
            ("laughSymbol", Loc.GetString("news-read-ui-reaction-laugh")),
            ("laugh", laugh),
            ("shockSymbol", Loc.GetString("news-read-ui-reaction-shock")),
            ("shock", shock),
            ("heartSymbol", Loc.GetString("news-read-ui-reaction-heart")),
            ("heart", heart));

        var comments = article.Comments;
        var commentCount = comments?.Count ?? 0;

        ToggleCommentsButton.Text = Loc.GetString("news-write-ui-comments-button", ("count", commentCount));
        LockCommentsButton.Text = Loc.GetString(article.CommentsLocked
            ? "news-write-ui-unlock-comments-text"
            : "news-write-ui-lock-comments-text");

        CommentsContainer.Children.Clear();
        if (comments == null || comments.Count == 0)
        {
            var noComments = new Label
            {
                Text = Loc.GetString("news-read-ui-no-comments"),
                FontColorOverride = Color.FromHex("#808080"),
                Margin = new Thickness(4, 2, 4, 2)
            };
            noComments.StyleClasses.Add("LabelSmall");
            CommentsContainer.AddChild(noComments);
            return;
        }

        foreach (var comment in comments)
        {
            var entry = new NewsCommentEntry(comment, canDelete: true);
            entry.OnDeleteCommentPressed += InvokeDeleteComment;
            CommentsContainer.AddChild(entry);
        }
    }

    private void InvokeDeleteComment(int commentId)
    {
        OnDeleteCommentPressed?.Invoke(ArtcileNumber, commentId);
    }
}


