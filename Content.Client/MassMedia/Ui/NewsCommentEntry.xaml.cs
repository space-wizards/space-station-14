using Content.Client.Message;
using Content.Shared.MassMedia.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.MassMedia.Ui;

/// <summary>
/// UI control representing a single comment on a <see cref="NewsArticle"/>,
/// shared by both the PDA news reader and the journalist news management console.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NewsCommentEntry : Control
{
    private readonly int _commentId;

    public event Action<int>? OnDeleteCommentPressed;

    public NewsCommentEntry(NewsComment comment, bool canDelete)
    {
        RobustXamlLoader.Load(this);

        _commentId = comment.CommentId;

        var authorName = FormattedMessage.EscapeText(comment.Author ?? Loc.GetString("news-read-ui-no-author"));
        var timeStr = comment.PostedTime.ToString(@"hh\:mm\:ss");
        MetaLabel.SetMarkup(Loc.GetString("news-read-ui-comment-meta", ("author", authorName), ("time", timeStr)));

        ContentLabel.SetMarkup(FormattedMessage.EscapeText(comment.Content));

        DeleteButton.Visible = canDelete;
        if (canDelete)
        {
            DeleteButton.OnPressed += _ => OnDeleteCommentPressed?.Invoke(_commentId);
        }
    }
}
