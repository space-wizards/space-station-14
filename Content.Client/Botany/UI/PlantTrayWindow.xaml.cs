using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.Botany.Components;
using Content.Shared.Botany.Systems;
using Content.Shared.Chemistry.EntitySystems;
using Content.Shared.IdentityManagement;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Botany.UI;

/// <summary>
/// Window displaying the current state of a plant tray.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PlantTrayWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    private readonly SharedSolutionContainerSystem _solutionSystem;
    private readonly PlantTraySystem _plantTraySystem;

    public PlantTrayWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _solutionSystem = _entityManager.System<SharedSolutionContainerSystem>();
        _plantTraySystem = _entityManager.System<PlantTraySystem>();
    }

    public void Update(EntityUid owner)
    {
        if (!_entityManager.TryGetComponent<PlantTrayComponent>(owner, out var tray))
            return;

        TraySprite.SetEntity(owner);
        TrayName.Text = Identity.Name(owner, _entityManager);
        UpdateStatus((owner, tray));
        UpdateResources(tray);
        UpdateReagents((owner, tray));
        UpdateWarnings((owner, tray));
    }

    private void UpdateStatus(Entity<PlantTrayComponent> tray)
    {
        var status = Loc.GetString("botany-ui-status-empty");
        if (_plantTraySystem.TryGetPlant(tray.AsNullable(), out var plant)
            && _entityManager.TryGetComponent<PlantDataComponent>(plant.Value, out var data))
        {
            status = Loc.GetString("botany-ui-tray-plant", ("plant", Loc.GetString(data.Name)));
        }

        Status.SetMessage(FormattedMessage.FromMarkupPermissive(status));
    }

    private void UpdateResources(PlantTrayComponent tray)
    {
        UpdateResource(Water, "botany-ui-water", tray.WaterLevel, tray.MaxWaterLevel, "units-u");
        UpdateResource(Nutrients, "botany-ui-nutrients", tray.NutritionLevel, tray.MaxNutritionLevel, "units-u");
        UpdateResource(Weeds, "botany-ui-weeds", tray.WeedLevel, tray.MaxWeedLevel);
        UpdateResource(Pests, "botany-ui-pests", tray.PestLevel, tray.MaxPestLevel);
        UpdateResource(Toxins, "botany-ui-toxins", tray.ToxinLevel, tray.MaxToxinLevel);
    }

    private void UpdateReagents(Entity<PlantTrayComponent> tray)
    {
        Reagents.ClearDisplay();

        if (_solutionSystem.ResolveSolution(tray.Owner, tray.Comp.SoilSolutionName, ref tray.Comp.SoilSolution, out var solution))
        {
            foreach (var (reagent, quantity) in solution.Contents)
            {
                Reagents.AddReagent(reagent, quantity);
            }
        }

        if (Reagents.ChildCount == 0)
        {
            Reagents.AddChild(new Label
            {
                Text = Loc.GetString("botany-ui-reagents-none"),
                StyleClasses = { StyleClass.LabelWeak },
            });
        }
    }

    private void UpdateWarnings(Entity<PlantTrayComponent> tray)
    {
        Warnings.RemoveAllChildren();

        var trayWarnings = _plantTraySystem.GetTrayWarningsMarkup(tray.AsNullable());
        if (string.IsNullOrEmpty(trayWarnings))
        {
            Warnings.AddChild(new Label
            {
                Text = Loc.GetString("botany-ui-warnings-none"),
                StyleClasses = { StyleClass.LabelWeak },
            });
        }
        else
        {
            foreach (var warning in trayWarnings.Split('\n'))
            {
                var label = new RichTextLabel { Margin = new Thickness(4, 1) };
                label.SetMessage(FormattedMessage.FromMarkupPermissive($"[bullet/][font size=11]{warning}[/font]"),
                    tagsAllowed: null);
                Warnings.AddChild(label);
            }
        }
    }

    private static void UpdateResource(BotanyMetricControl control,
        string name,
        float value,
        float maximum,
        string? unit = null)
    {
        var suffix = unit == null ? string.Empty : $" {Loc.GetString(unit)}";
        control.Update(Loc.GetString(name),
            $"{value:0.#} / {maximum:0.#}{suffix}",
            progress: maximum > 0f ? value / maximum : 0f);
    }
}
