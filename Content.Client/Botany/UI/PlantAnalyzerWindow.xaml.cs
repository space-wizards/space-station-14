namespace Content.Client.Botany.UI;

/// <summary>
/// Window displaying the results of a plant analysis.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PlantAnalyzerWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    private readonly BotanySystem _botanySystem;
    private readonly PlantSystem _plantSystem;

    public PlantAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _botanySystem = _entityManager.System<BotanySystem>();
        _plantSystem = _entityManager.System<PlantSystem>();
    }

    public void Update(BotanyAnalyzerState state)
    {
        if (!_entityManager.TryGetEntity(state.Target, out var target))
            return;

        EntityUid? plantEntity = null;
        if (_entityManager.TryGetEntity(state.Plant, out var plantUid))
            plantEntity = plantUid;

        if (!_botanySystem.TryGetPlantComponent<PlantComponent>(plantEntity, state.PlantProtoId, out var plant))
            return;

        PlantSprite.SetEntity(target.Value);
        PlantName.Text = Identity.Name(target.Value, _entityManager);
        UpdateWarnings(plantEntity, plant);
        UpdatePlantStatus(plantEntity, state.PlantProtoId, plant);
        UpdateTraits(plantEntity, state.PlantProtoId, plant);
        UpdateConditions(plantEntity, state.PlantProtoId, plant);
        UpdateGases(plantEntity, state.PlantProtoId);
        UpdateChemicals(plantEntity, state.PlantProtoId, plant);
        UpdateMutations(state.Mutations);
    }

    private void UpdatePlantStatus(EntityUid? plantEntity, EntProtoId? prototypeId, PlantComponent plant)
    {
        if (!_botanySystem.TryGetPlantComponent<PlantHolderComponent>(plantEntity, prototypeId, out var holder))
            return;

        var harvestAge = plantEntity is { } plantUid
            ? _plantSystem.GetNextHarvestAge((plantUid, plant))
            : plant.Maturation;

        Health.Update(Loc.GetString("botany-ui-health"), $"{holder.Health:0.#} / {plant.Endurance:0.#}", progress: plant.Endurance > 0f ? holder.Health / plant.Endurance : 1f);

        var growth = holder.ReadyForHarvest ? Loc.GetString("botany-ui-harvest-ready") : $"{holder.Age} / {harvestAge} {Loc.GetString("botany-ui-unit-cycles")}";
        var growthProgress = holder.ReadyForHarvest || harvestAge <= 0 ? 1f : holder.Age / harvestAge;

        Growth.Update(Loc.GetString("botany-ui-growth"), growth, progress: growthProgress);
    }

    private void UpdateTraits(EntityUid? plantEntity, EntProtoId? prototypeId, PlantComponent plant)
    {
        if (!_botanySystem.TryGetPlantComponent<PlantHolderComponent>(plantEntity, prototypeId, out var holder))
            return;

        Endurance.Text = $"{plant.Endurance:0.#}";
        Yield.Text = $"{plant.Yield}";
        Lifespan.Text = $"{plant.Lifespan:0.#}";
        Maturation.Text = $"{plant.Maturation:0.#}";
        Production.Text = $"{plant.Production:0.#}";
        Potency.Text = $"{plant.Potency:0.#}";
        Mutation.Text = $"{holder.MutationLevel:0.#} / {holder.MaxMutationLevel:0.#}";
        MutationMod.Text = $"{holder.MutationMod:0.#} / {holder.MaxMutationMod:0.#}";
        Age.Text = $"{holder.Age}";
        var growthStage = plantEntity is { } plantUid
            ? _plantSystem.GetGrowthStageValue((plantUid, plant))
            : 0f;
        GrowthStage.Text = $"{growthStage} / {plant.GrowthStages}";
        GrowthType.Text = GetGrowthType(plantEntity, prototypeId);

        if (!_botanySystem.TryGetPlantComponent<PlantComponent>(null, prototypeId, out var prototypePlant))
            return;

        UpdateDelta(EnduranceDelta, plant.Endurance, prototypePlant.Endurance);
        UpdateDelta(YieldDelta, plant.Yield, prototypePlant.Yield);
        UpdateDelta(LifespanDelta, plant.Lifespan, prototypePlant.Lifespan);
        UpdateDelta(MaturationDelta, plant.Maturation, prototypePlant.Maturation, invert: true);
        UpdateDelta(ProductionDelta, plant.Production, prototypePlant.Production);
        UpdateDelta(PotencyDelta, plant.Potency, prototypePlant.Potency);
    }

    private void UpdateDelta(Label label, float value, float prototypeValue, bool invert = false)
    {
        var delta = value - prototypeValue;
        label.Text = $"({delta:+#.#;-#.#;0})";

        label.FontColorOverride = delta switch
        {
            > 0f => invert ? Color.Crimson : Color.LimeGreen,
            < 0f => invert ? Color.LimeGreen : Color.Crimson,
            _ => Color.DimGray,
        };
    }

    private void UpdateConditions(EntityUid? plantEntity, EntProtoId? prototypeId, PlantComponent plant)
    {
        if (!_botanySystem.TryGetPlantComponent<PlantAtmosphericComponent>(plantEntity, prototypeId, out var atmospheric))
            return;

        UpdateCondition(Temperature,
            "botany-ui-temperature",
            atmospheric.LowHeatTolerance,
            atmospheric.HighHeatTolerance,
            "units-kelvin");
        UpdateCondition(Pressure,
            "botany-ui-pressure",
            atmospheric.LowPressureTolerance,
            atmospheric.HighPressureTolerance,
            "units-k-pascal");

        if (!_botanySystem.TryGetPlantComponent<PlantGrowthComponent>(plantEntity, prototypeId, out var growth))
            return;

        var waterConsumption = growth.WaterConsumption;
        var nutrientConsumption = growth.NutrientConsumption;
        if (plantEntity is { } plantUid && _plantSystem.TryGetTray((plantUid, plant), out var tray))
        {
            waterConsumption *= tray.Comp.TrayConsumptionMultiplier;
            nutrientConsumption *= tray.Comp.TrayConsumptionMultiplier;
        }

        UpdateCondition(Water,
            "botany-ui-water",
            waterConsumption,
            null,
            "units-u");
        UpdateCondition(Nutrients,
            "botany-ui-nutrients",
            nutrientConsumption,
            null,
            "units-u");
    }

    private static void UpdateCondition(
        BotanyMetricControl control,
        string name,
        float? minimum,
        float? maximum,
        string unit)
    {
        var localizedUnit = Loc.GetString(unit);
        var target = (minimum, maximum) switch
        {
            ({ } min, { } max) => Loc.GetString(
                "botany-ui-condition-range",
                ("minimum", $"{min:0.#}"),
                ("maximum", $"{max:0.#}"),
                ("unit", localizedUnit)),

            ({ } min, null) => Loc.GetString(
                "botany-ui-condition-minimum",
                ("minimum", $"{min:0.#}"),
                ("unit", localizedUnit)),

            (null, { } max) => Loc.GetString(
                "botany-ui-condition-maximum",
                ("maximum", $"{max:0.#}"),
                ("unit", localizedUnit)),

            _ => Loc.GetString("botany-ui-condition-current-missing"),
        };

        control.Update(Loc.GetString(name), target);
    }

    private void UpdateGases(EntityUid? plantEntity, EntProtoId? prototypeId)
    {
        if (!_botanySystem.TryGetPlantComponent<PlantConsumeExudeGasComponent>(plantEntity, prototypeId, out var gases))
            return;

        Consumed.ClearDisplay();
        var consumed = gases.ConsumeGasses
            .Where(x => x.Value > 0f)
            .Select(x => new GasEntry(x.Key, x.Value))
            .ToArray();
        foreach (var gas in consumed)
        {
            Consumed.AddGas(gas);
        }

        if (consumed.Length == 0)
            Consumed.ShowEmptyMessage();

        Exuded.ClearDisplay();
        var exuded = gases.ExudeGasses
            .Where(x => x.Value > 0f)
            .Select(x => new GasEntry(x.Key, x.Value))
            .ToArray();
        foreach (var gas in exuded)
        {
            Exuded.AddGas(gas);
        }

        if (exuded.Length == 0)
            Exuded.ShowEmptyMessage();
    }

    private string GetGrowthType(EntityUid? plantEntity, EntProtoId? prototypeId)
    {
        if (!_botanySystem.TryGetPlantComponent<PlantHarvestComponent>(plantEntity, prototypeId, out var harvest))
            return string.Empty;

        var type = harvest.HarvestRepeat;
        return Loc.GetString("botany-ui-harvest-type-value", ("type", $"{type}"));
    }

    private void UpdateChemicals(EntityUid? plantEntity, EntProtoId? prototypeId, PlantComponent plant)
    {
        Chemicals.ClearDisplay();

        if (!_botanySystem.TryGetPlantComponent<PlantChemicalsComponent>(plantEntity, prototypeId, out var plantChemicals)
            || plantChemicals.Chemicals.Count == 0)
        {
            if (Chemicals.ChildCount == 0)
                Chemicals.ShowEmptyMessage();
            return;
        }

        foreach (var (reagent, quantity) in plantChemicals.Chemicals)
        {
            var amount = quantity.Min;

            if (quantity.PotencyDivisor > 0f && plant.Potency > 0f)
                amount += plant.Potency / quantity.PotencyDivisor;

            if (quantity.Max > 0)
                amount = Math.Min((float)amount, (float)quantity.Max);

            if (amount > 0f)
                Chemicals.AddReagent(new ReagentId(reagent, null), amount);
        }
    }

    private void UpdateMutations(IEnumerable<string> mutations)
    {
        UpdateTextList(Mutations, mutations.Select(Loc.GetString), "botany-ui-mutations-none");
    }

    private void UpdateWarnings(EntityUid? plantEntity, PlantComponent plant)
    {
        if (plantEntity is not { } plantUid)
        {
            UpdateTextList(Warnings, [], "botany-ui-warnings-none");
            return;
        }

        UpdateTextList(
            Warnings,
            [
                _plantSystem.GetPlantExamineMarkup((plantUid, plant)),
                _plantSystem.GetPlantWarningsMarkup(plantUid),
            ],
            "botany-ui-warnings-none");
    }

    private static void UpdateTextList(Control container, IEnumerable<string> lines, string emptyLoc)
    {
        container.RemoveAllChildren();
        var any = false;
        foreach (var line in lines.SelectMany(x => x.Split('\n')).Where(x => !string.IsNullOrEmpty(x)))
        {
            any = true;
            var label = new RichTextLabel { Margin = new Thickness(4, 1) };
            label.SetMessage(
                FormattedMessage.FromMarkupPermissive($"[bullet/][font size=11]{line}[/font]"),
                tagsAllowed: null);
            container.AddChild(label);
        }

        if (!any)
            container.AddChild(new Label { Text = Loc.GetString(emptyLoc), StyleClasses = { StyleClass.LabelWeak } });
    }
}
