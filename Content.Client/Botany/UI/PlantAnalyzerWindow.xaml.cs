using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.Atmos.Components;
using Content.Shared.Botany;
using Content.Shared.Botany.Components;
using Content.Shared.Botany.Systems;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Botany.UI;

/// <summary>
/// Window displaying the results of a plant analysis.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PlantAnalyzerWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    private readonly BotanySystem _botanySystem;
    private readonly PlantSystem _plantSystem;

    public PlantAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _botanySystem = _entityManager.System<BotanySystem>();
        _plantSystem = _entityManager.System<PlantSystem>();
    }

    public void Update(BotanyAnalyzerState state)
    {
        if (!_entityManager.TryGetEntity(state.Target, out var target))
            return;

        if (!_entityManager.TryGetComponent<PlantComponent>(target.Value, out var plant)
            || !_entityManager.TryGetComponent<PlantDataComponent>(target.Value, out var data))
            return;

        PlantSprite.SetEntity(target.Value);
        PlantName.Text = Loc.GetString(data.Name);
        UpdateWarnings(target.Value, plant);
        UpdatePlantStatus(target.Value, plant);
        UpdateTraits(target.Value, plant);
        UpdateConditions(target.Value, plant);
        UpdateGases(target.Value);
        UpdateChemicals(target.Value, plant);
        UpdateMutations(state.Mutations);
    }

    private void UpdatePlantStatus(EntityUid target, PlantComponent plant)
    {
        if (!_entityManager.TryGetComponent<PlantHolderComponent>(target, out var holder))
            return;

        var harvestAge = _plantSystem.GetNextHarvestAge((target, plant));

        Health.Update(Loc.GetString("botany-ui-health"), $"{holder.Health:0.#} / {plant.Endurance:0.#}", progress: plant.Endurance > 0f ? holder.Health / plant.Endurance : 1f);

        var growth = holder.ReadyForHarvest ? Loc.GetString("botany-ui-harvest-ready") : $"{holder.Age} / {harvestAge} {Loc.GetString("botany-ui-unit-cycles")}";
        var growthProgress = holder.ReadyForHarvest || harvestAge <= 0 ? 1f : (float)holder.Age / harvestAge;

        Growth.Update(Loc.GetString("botany-ui-growth"), growth, progress: growthProgress);
    }

    private void UpdateTraits(EntityUid target, PlantComponent plant)
    {
        if (!_entityManager.TryGetComponent<PlantHolderComponent>(target, out var holder))
            return;

        Endurance.Text = $"{plant.Endurance:0.#}";
        Yield.Text = $"{plant.Yield}";
        Lifespan.Text = $"{plant.Lifespan:0.#}";
        Maturation.Text = $"{plant.Maturation:0.#}";
        Production.Text = $"{plant.Production:0.#}";
        Potency.Text = $"{plant.Potency:0.#}";
        Mutation.Text = $"{holder.MutationLevel:0.#} / {holder.MaxMutationLevel:0.#}";
        MutationMod.Text = $"{holder.MutationMod:0.#} / {holder.MaxMutationMod:0.#}";
        Age.Text = $"{holder.Age}";
        GrowthStage.Text = $"{_plantSystem.GetGrowthStageValue((target, plant))} / {plant.GrowthStages}";
        GrowthType.Text = GetGrowthType(target);

        var prototypeId = _entityManager.GetComponent<MetaDataComponent>(target).EntityPrototype?.ID;
        if (!_botanySystem.TryGetPlantComponent<PlantComponent>(null, prototypeId, out var prototypePlant)
            || !_botanySystem.TryGetPlantComponent<PlantHolderComponent>(null, prototypeId, out var prototypeHolder))
            return;

        UpdateDelta(EnduranceDelta, plant.Endurance, prototypePlant.Endurance);
        UpdateDelta(YieldDelta, plant.Yield, prototypePlant.Yield);
        UpdateDelta(LifespanDelta, plant.Lifespan, prototypePlant.Lifespan);
        UpdateDelta(MaturationDelta, plant.Maturation, prototypePlant.Maturation);
        UpdateDelta(ProductionDelta, plant.Production, prototypePlant.Production);
        UpdateDelta(PotencyDelta, plant.Potency, prototypePlant.Potency);
        UpdateDelta(MutationModDelta, holder.MutationMod, prototypeHolder.MutationMod);
    }

    private static void UpdateDelta(Label label, float value, float prototypeValue)
    {
        var delta = value - prototypeValue;
        label.Text = $"({delta:+#.#;-#.#;0})";
        label.FontColorOverride = delta switch
        {
            > 0f => Color.LimeGreen,
            < 0f => Color.Crimson,
            _ => Color.DimGray,
        };
    }

    private void UpdateConditions(EntityUid target, PlantComponent plant)
    {
        if (!_entityManager.TryGetComponent<PlantAtmosphericComponent>(target, out var atmospheric))
            return;

        UpdateCondition(Temperature,
            "botany-ui-temperature",
            atmospheric.LowHeatTolerance,
            atmospheric.HighHeatTolerance,
            "units-kelvin");
        UpdateCondition(Pressure,
            "botany-ui-pressure",
            atmospheric.LowPressureTolerance,
            atmospheric.HighPressureTolerance,
            "units-k-pascal");

        if (!_plantSystem.TryGetTray((target, plant), out var tray) ||
            !_entityManager.TryGetComponent<PlantGrowthComponent>(target, out var growth))
            return;

        UpdateCondition(Water,
            "botany-ui-water",
            growth.WaterConsumption * tray.Comp.TrayConsumptionMultiplier,
            null,
            "units-u");
        UpdateCondition(Nutrients,
            "botany-ui-nutrients",
            growth.NutrientConsumption * tray.Comp.TrayConsumptionMultiplier,
            null,
            "units-u");
    }

    private static void UpdateCondition(
        BotanyMetricControl control,
        string name,
        float? minimum,
        float? maximum,
        string unit)
    {
        var localizedUnit = Loc.GetString(unit);
        var target = (minimum, maximum) switch
        {
            ({ } min, { } max) => Loc.GetString(
                "botany-ui-condition-range",
                ("minimum", $"{min:0.#}"),
                ("maximum", $"{max:0.#}"),
                ("unit", localizedUnit)),

            ({ } min, null) => Loc.GetString(
                "botany-ui-condition-minimum",
                ("minimum", $"{min:0.#}"),
                ("unit", localizedUnit)),

            (null, { } max) => Loc.GetString(
                "botany-ui-condition-maximum",
                ("maximum", $"{max:0.#}"),
                ("unit", localizedUnit)),

            _ => Loc.GetString("botany-ui-condition-current-missing"),
        };

        control.Update(Loc.GetString(name), target);
    }

    private void UpdateGases(EntityUid target)
    {
        if (!_entityManager.TryGetComponent<PlantConsumeExudeGasComponent>(target, out var gases))
            return;

        Consumed.ClearDisplay();
        var consumed = gases.ConsumeGasses
            .Where(x => x.Value > 0f)
            .Select(x => new GasEntry(x.Key, x.Value))
            .ToArray();
        foreach (var gas in consumed)
        {
            Consumed.AddGas(gas);
        }

        if (consumed.Length == 0)
            Consumed.ShowEmptyMessage();

        Exuded.ClearDisplay();
        var exuded = gases.ExudeGasses
            .Where(x => x.Value > 0f)
            .Select(x => new GasEntry(x.Key, x.Value))
            .ToArray();
        foreach (var gas in exuded)
        {
            Exuded.AddGas(gas);
        }

        if (exuded.Length == 0)
            Exuded.ShowEmptyMessage();
    }

    private string GetGrowthType(EntityUid target)
    {
        if (!_entityManager.TryGetComponent<PlantHarvestComponent>(target, out var harvest))
            return string.Empty;

        var type = harvest.HarvestRepeat;
        return Loc.GetString("botany-ui-harvest-type-value", ("type", $"{type}"));
    }

    private void UpdateChemicals(EntityUid target, PlantComponent plant)
    {
        Chemicals.ClearDisplay();

        if (!_entityManager.TryGetComponent<PlantChemicalsComponent>(target, out var plantChemicals)
            || plantChemicals.Chemicals.Count == 0)
        {
            Chemicals.AddChild(new Label
            {
                Text = Loc.GetString("botany-ui-chemicals-none"),
                StyleClasses = { StyleClass.LabelWeak },
            });
            return;
        }

        foreach (var (reagent, quantity) in plantChemicals.Chemicals)
        {
            var amount = quantity.Min;

            if (quantity.PotencyDivisor > 0f && plant.Potency > 0f)
                amount += plant.Potency / quantity.PotencyDivisor;

            if (quantity.Max > 0)
                amount = Math.Min((float)amount, (float)quantity.Max);

            if (amount > 0f)
                Chemicals.AddReagent(new ReagentId(reagent, null), amount);
        }
    }

    private void UpdateMutations(IEnumerable<string> mutations)
    {
        UpdateTextList(Mutations, mutations.Select(Loc.GetString), "botany-ui-mutations-none");
    }

    private void UpdateWarnings(EntityUid target, PlantComponent plant)
    {
        UpdateTextList(
            Warnings,
            [
                _plantSystem.GetPlantExamineMarkup((target, plant)),
                _plantSystem.GetPlantWarningsMarkup(target),
            ],
            "botany-ui-warnings-none");
    }

    private static void UpdateTextList(Control container, IEnumerable<string> lines, string emptyLoc)
    {
        container.RemoveAllChildren();
        var any = false;
        foreach (var line in lines.SelectMany(x => x.Split('\n')).Where(x => !string.IsNullOrEmpty(x)))
        {
            any = true;
            var label = new RichTextLabel { Margin = new Thickness(4, 1) };
            label.SetMessage(
                FormattedMessage.FromMarkupPermissive($"[bullet/][font size=11]{line}[/font]"),
                tagsAllowed: null);
            container.AddChild(label);
        }

        if (!any)
            container.AddChild(new Label { Text = Loc.GetString(emptyLoc), StyleClasses = { StyleClass.LabelWeak } });
    }
}
