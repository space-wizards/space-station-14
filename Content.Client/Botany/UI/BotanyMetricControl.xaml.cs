using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Botany.UI;

/// <summary>
/// Displays a labeled plant metric with an optional target and progress bar.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class BotanyMetricControl : PanelContainer
{
    private readonly bool _loaded;

    /// <summary>
    /// Gets or sets the accent color used by the metric border and progress bar.
    /// </summary>
    public Color AccentColor
    {
        get;
        set
        {
            field = value;
            ApplyAccentColor();
        }
    } = Color.White;

    /// <summary>
    /// Gets or sets the optional color used when a progress value requests it.
    /// </summary>
    public Color? ProgressColor { get; set; }

    public BotanyMetricControl()
    {
        RobustXamlLoader.Load(this);
        _loaded = true;
        ApplyAccentColor();
    }

    /// <summary>
    /// Updates the displayed metric values.
    /// </summary>
    /// <param name="title">The localized metric title.</param>
    /// <param name="value">The formatted current value.</param>
    /// <param name="target">The formatted target value, if any.</param>
    /// <param name="progress">The progress value in the range from zero to one, if any.</param>
    /// <param name="useProgressColor">Whether to use <see cref="ProgressColor"/> for the progress bar.</param>
    public void Update(string title,
        string value,
        string? target = null,
        float? progress = null,
        bool useProgressColor = false)
    {
        Title.Text = title;
        Value.Text = value;
        Target.Text = target;
        Target.Visible = target != null;
        Progress.Visible = progress != null;
        ((StyleBoxFlat)Progress.ForegroundStyleBoxOverride!).BackgroundColor =
            useProgressColor ? ProgressColor ?? AccentColor : AccentColor;
        if (progress != null)
            Progress.Value = Math.Clamp(progress.Value, 0f, 1f);
    }

    private void ApplyAccentColor()
    {
        if (!_loaded || PanelOverride is not StyleBoxFlat panelStyle ||
            Progress.ForegroundStyleBoxOverride is not StyleBoxFlat progressStyle)
            return;

        panelStyle.BorderColor = AccentColor;
        progressStyle.BackgroundColor = AccentColor;
    }
}
