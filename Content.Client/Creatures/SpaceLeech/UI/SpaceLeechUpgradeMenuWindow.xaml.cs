using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Creatures.SpaceLeech;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client.Creatures.SpaceLeech.UI;

[GenerateTypedNameReferences]
public sealed partial class SpaceLeechUpgradeMenuWindow : FancyWindow
{
    // Palette matching the design's corrupted-Nanotrasen theme.
    private static readonly Color PanelBorder   = Color.FromHex("#434863");
    private static readonly Color PanelBg       = Color.FromHex("#3a3b46");
    private static readonly Color PanelBgDark   = Color.FromHex("#232430");
    private static readonly Color BloodRedText  = Color.FromHex("#ff6b6b");
    private static readonly Color OwnedBorder   = Color.FromHex("#b62124");
    private static readonly Color GoldAccent    = Color.FromHex("#a88b5e");
    private static readonly Color GreenGood     = Color.FromHex("#3c854a");
    private static readonly Color LockedBorder  = Color.FromHex("#2f334b");
    private static readonly Color MutedText     = Color.FromHex("#a9a9a9");

    private static readonly Color OwnedBg  = new(0.525f, 0.078f, 0.094f, 0.18f);
    private static readonly Color NextBg   = new(0.659f, 0.545f, 0.369f, 0.08f);
    private static readonly Color LockedBg = Color.FromHex("#232430");

    private static readonly string[] Numerals = { "I", "II", "III" }; // must have MaxRank entries

    private readonly BloodVialControl _bloodVial;
    private readonly IPrototypeManager _protoMan;
    private readonly List<UpgradeRowState> _rows = new();

    /// <summary>Raised when the player clicks to evolve the next rank of an upgrade.</summary>
    public event Action<string>? OnEvolve;

    public SpaceLeechUpgradeMenuWindow()
    {
        RobustXamlLoader.Load(this);

        _bloodVial = new BloodVialControl();
        BloodVialContainer.AddChild(_bloodVial);

        _protoMan = IoCManager.Resolve<IPrototypeManager>();
    }

    public void UpdateState(SpaceLeechUpgradeMenuBuiState state)
    {
        // Lazy row initialization on first state push.
        if (_rows.Count == 0)
        {
            foreach (var upgradeId in SpaceLeechUpgradeData.UpgradeOrder)
            {
                if (!_protoMan.TryIndex<SpaceLeechUpgradePrototype>(upgradeId, out var proto))
                {
                    Logger.Warning($"[SpaceLeechUpgradeMenu] Missing upgrade prototype: {upgradeId}");
                    continue;
                }
                var row = BuildUpgradeRow(proto);
                UpgradeRowContainer.AddChild(row.Root);
                _rows.Add(row);
            }
        }

        BloodAvailableLabel.Text = state.BloodPool.ToString("0000.00");
        BloodFractionLabel.Text =
            $"{state.BloodPool:F2} / {state.MaxBloodPool} u · " +
            $"{(int)(state.BloodPool * 100f / Math.Max(1, state.MaxBloodPool))}%";
        _bloodVial.SetFill(state.BloodPool / (float)Math.Max(1, state.MaxBloodPool));

        var totalRanks = state.UpgradeRanks.Values.Sum();
        var maxRanks   = SpaceLeechUpgradeData.UpgradeOrder.Count * SpaceLeechUpgradePrototype.MaxRank;

        LifetimeLabel.Text  = $"{state.BloodConsumedTotal:F2} u";
        MutationsLabel.Text = $"{totalRanks} / {maxRanks}";
        MutationsLabel.FontColorOverride = totalRanks >= maxRanks ? GreenGood : GoldAccent;

        foreach (var row in _rows)
        {
            state.UpgradeRanks.TryGetValue(row.UpgradeId, out var rank);
            RefreshRow(row, rank, state.BloodPool);
        }
    }

    // ── Row construction ─────────────────────────────────────────────────────

    private UpgradeRowState BuildUpgradeRow(SpaceLeechUpgradePrototype upgrade)
    {
        var root = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = PanelBg,
                BorderColor = PanelBorder,
                BorderThickness = new Thickness(2),
            },
        };

        var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        root.AddChild(body);

        // ── Identity column (170px fixed) ──
        var identityPanel = new PanelContainer
        {
            MinWidth = 170,
            MaxWidth = 170,
            PanelOverride = new StyleBoxFlat { BackgroundColor = PanelBgDark },
        };
        var identityBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(10, 8),
        };
        identityPanel.AddChild(identityBox);

        // Stat tag (red pill)
        var statPanel = new PanelContainer
        {
            HorizontalAlignment = HAlignment.Left,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#871517"),
                BorderColor = PanelBorder,
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 6,
                ContentMarginRightOverride = 6,
                ContentMarginTopOverride = 1,
                ContentMarginBottomOverride = 1,
            },
        };
        statPanel.AddChild(new Label
        {
            Text = upgrade.Stat,
            FontColorOverride = Color.FromHex("#f3c9a0"),
            StyleClasses = { "LabelSubText" },
        });
        identityBox.AddChild(statPanel);

        identityBox.AddChild(new Label
        {
            Text = upgrade.Name,
            FontColorOverride = GoldAccent,
            StyleClasses = { "LabelHeading" },
            Margin = new Thickness(0, 4, 0, 0),
        });

        var rankDisplay = new Label
        {
            StyleClasses = { "LabelSubText" },
            Margin = new Thickness(0, 2, 0, 0),
        };
        identityBox.AddChild(rankDisplay);

        // ── Vertical separator ──
        body.AddChild(identityPanel);
        body.AddChild(MakeSeparator(vertical: true));

        // ── Three rank cells ──
        var rankCells = new RankCellRefs[3];
        var rankBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        for (var i = 0; i < 3; i++)
        {
            if (i > 0)
                rankBox.AddChild(MakeSeparator(vertical: true));

            rankCells[i] = BuildRankCell(upgrade, i);
            rankBox.AddChild(rankCells[i].Root);
        }

        body.AddChild(rankBox);

        return new UpgradeRowState(upgrade.ID, root, rankDisplay, rankCells);
    }

    private RankCellRefs BuildRankCell(SpaceLeechUpgradePrototype upgrade, int index)
    {
        var root = new ContainerButton
        {
            HorizontalExpand = true,
            Disabled = true,
        };

        var inner = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(8),
            HorizontalExpand = true,
        };
        root.AddChild(inner);

        var headerRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        var rankLabel = new Label { StyleClasses = { "LabelSubText" } };
        var spacer    = new Control { HorizontalExpand = true };
        var costLabel = new Label { StyleClasses = { "LabelSubText" } };
        headerRow.AddChild(rankLabel);
        headerRow.AddChild(spacer);
        headerRow.AddChild(costLabel);
        inner.AddChild(headerRow);

        var effectLabel = new Label
        {
            Text = upgrade.Effects[index],
            StyleClasses = { "LabelSubText" },
            HorizontalExpand = true,
            ClipText = true,
            Margin = new Thickness(0, 4, 0, 0),
        };
        inner.AddChild(effectLabel);

        var ctaLabel = new Label
        {
            HorizontalAlignment = HAlignment.Center,
            HorizontalExpand = true,
            ClipText = true,
            Margin = new Thickness(0, 4, 0, 0),
            Visible = false,
        };
        inner.AddChild(ctaLabel);

        var capturedId = upgrade.ID;
        root.OnPressed += _ => OnEvolve?.Invoke(capturedId);

        return new RankCellRefs(root, rankLabel, costLabel, ctaLabel, index);
    }

    private void RefreshRow(UpgradeRowState row, int rank, float bloodPool)
    {
        var maxed = rank >= SpaceLeechUpgradePrototype.MaxRank;

        row.RankDisplay.Text = maxed
            ? "RANK III / III  ▣ MAX"
            : $"RANK {(rank == 0 ? "0" : Numerals[rank - 1])} / III";
        row.RankDisplay.FontColorOverride = maxed ? GreenGood : MutedText;

        if (!_protoMan.TryIndex<SpaceLeechUpgradePrototype>(row.UpgradeId, out var upgrade))
            return;

        for (var i = 0; i < 3; i++)
        {
            var cell = row.RankCells[i];
            var cost = upgrade.Costs[i];

            if (i < rank)
            {
                ApplyOwned(cell, cost);
            }
            else if (i == rank && !maxed)
            {
                var canBuy = bloodPool >= cost;
                if (canBuy)
                    ApplyNext(cell, cost);
                else
                    ApplyNextUnaffordable(cell, cost, cost - bloodPool);
            }
            else
            {
                ApplyLocked(cell, cost);
            }
        }
    }

    private static void ApplyOwned(RankCellRefs cell, int cost)
    {
        cell.Root.StyleBoxOverride = CellBox(OwnedBg, OwnedBorder);
        cell.Root.Disabled = true;
        cell.RankLabel.Text = $"▣ RANK {Numerals[cell.Index]}";
        cell.RankLabel.FontColorOverride = OwnedBorder;
        cell.CostLabel.Text = "PAID";
        cell.CostLabel.FontColorOverride = GreenGood;
        cell.CtaLabel.Visible = false;
    }

    private static void ApplyNext(RankCellRefs cell, int cost)
    {
        cell.Root.StyleBoxOverride = CellBox(NextBg, GoldAccent);
        cell.Root.Disabled = false;
        cell.RankLabel.Text = $"▶ RANK {Numerals[cell.Index]}";
        cell.RankLabel.FontColorOverride = GoldAccent;
        cell.CostLabel.Text = $"{cost}u";
        cell.CostLabel.FontColorOverride = BloodRedText;
        cell.CtaLabel.Text = $"▸ EVOLVE · {cost}u";
        cell.CtaLabel.FontColorOverride = BloodRedText;
        cell.CtaLabel.Visible = true;
    }

    private static void ApplyNextUnaffordable(RankCellRefs cell, int cost, float shortfall)
    {
        cell.Root.StyleBoxOverride = CellBox(NextBg, GoldAccent);
        cell.Root.Disabled = true;
        cell.RankLabel.Text = $"▶ RANK {Numerals[cell.Index]}";
        cell.RankLabel.FontColorOverride = GoldAccent;
        cell.CostLabel.Text = $"{cost}u";
        cell.CostLabel.FontColorOverride = MutedText;
        cell.CtaLabel.Text = $"NEED {shortfall:F2}u MORE";
        cell.CtaLabel.FontColorOverride = MutedText;
        cell.CtaLabel.Visible = true;
    }

    private static void ApplyLocked(RankCellRefs cell, int cost)
    {
        cell.Root.StyleBoxOverride = CellBox(LockedBg, LockedBorder);
        cell.Root.Disabled = true;
        cell.RankLabel.Text = $"▢ RANK {Numerals[cell.Index]}";
        cell.RankLabel.FontColorOverride = MutedText;
        cell.CostLabel.Text = $"{cost}u";
        cell.CostLabel.FontColorOverride = LockedBorder;
        cell.CtaLabel.Visible = false;
    }

    private static StyleBoxFlat CellBox(Color bg, Color border) => new()
    {
        BackgroundColor = bg,
        BorderColor = border,
        BorderThickness = new Thickness(2),
        ContentMarginLeftOverride = 2,
        ContentMarginRightOverride = 2,
    };

    private static PanelContainer MakeSeparator(bool vertical)
    {
        return new PanelContainer
        {
            MinWidth = vertical ? 2 : 0,
            MaxWidth = vertical ? 2 : 0,
            VerticalExpand = vertical,
            HorizontalExpand = !vertical,
            PanelOverride = new StyleBoxFlat { BackgroundColor = PanelBorder },
        };
    }

    // ── Inner record types ────────────────────────────────────────────────────

    private sealed class UpgradeRowState(
        string upgradeId,
        PanelContainer root,
        Label rankDisplay,
        RankCellRefs[] rankCells)
    {
        public readonly string UpgradeId = upgradeId;
        public readonly PanelContainer Root = root;
        public readonly Label RankDisplay = rankDisplay;
        public readonly RankCellRefs[] RankCells = rankCells;
    }

    private sealed class RankCellRefs(
        ContainerButton root,
        Label rankLabel,
        Label costLabel,
        Label ctaLabel,
        int index)
    {
        public readonly ContainerButton Root = root;
        public readonly Label RankLabel = rankLabel;
        public readonly Label CostLabel = costLabel;
        public readonly Label CtaLabel = ctaLabel;
        public readonly int Index = index;
    }
}
