using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Creatures.SpaceLeech;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client.Creatures.SpaceLeech.UI;

[GenerateTypedNameReferences]
public sealed partial class SpaceLeechUpgradeMenuWindow : FancyWindow
{
    // Palette matching the design's corrupted-Nanotrasen theme.
    private static readonly Color GoldAccent = Color.FromHex("#a88b5e");
    private static readonly Color GreenGood = Color.FromHex("#3c854a");
    private static readonly Color VialFill = Color.FromHex("#d8303a");
    private static readonly Color VialBg = Color.FromHex("#0a0607");
    private static readonly Color VialBorder = Color.FromHex("#b62124");

    private readonly IPrototypeManager _protoMan;
    private readonly VerticalGaugeControl _bloodVial;
    private readonly List<UpgradeRowEntry> _rows = new();

    /// <summary>Raised when the player clicks to evolve the next rank of an upgrade.</summary>
    public event Action<ProtoId<SpaceLeechUpgradePrototype>>? OnEvolve;

    public SpaceLeechUpgradeMenuWindow()
    {
        RobustXamlLoader.Load(this);

        _protoMan = IoCManager.Resolve<IPrototypeManager>();

        _bloodVial = new VerticalGaugeControl(VialFill, VialBg, VialBorder);
        BloodVialContainer.AddChild(_bloodVial);

        BuildRows();
    }

    private void BuildRows()
    {
        var upgrades = _protoMan.EnumeratePrototypes<SpaceLeechUpgradePrototype>().ToList();
        upgrades.Sort((a, b) => a.Order != b.Order
            ? a.Order.CompareTo(b.Order)
            : string.Compare(a.ID, b.ID, StringComparison.Ordinal));

        var suffix = Loc.GetString("space-leech-upgrade-unit");
        var verb = Loc.GetString("space-leech-upgrade-evolve-verb");

        foreach (var upgrade in upgrades)
        {
            var row = new RankedUpgradeRow(
                Loc.GetString(upgrade.Name),
                Loc.GetString(upgrade.Stat),
                upgrade.Effects.Select(effect => Loc.GetString(effect)).ToArray(),
                upgrade.Costs)
            {
                CurrencySuffix = suffix,
                PurchaseVerb = verb,
            };

            ProtoId<SpaceLeechUpgradePrototype> id = upgrade.ID;
            row.OnPurchase += () => OnEvolve?.Invoke(id);

            UpgradeRowContainer.AddChild(row);
            _rows.Add(new UpgradeRowEntry(id, upgrade.MaxRank, row));
        }
    }

    public void Update(SpaceLeechComponent comp)
    {
        var blood = comp.BloodPool.Float();
        var maxBlood = Math.Max(1f, comp.MaxBloodPool.Float());

        BloodAvailableLabel.Text = blood.ToString("0000.00");
        BloodFractionLabel.Text = Loc.GetString("space-leech-upgrade-blood-fraction",
            ("blood", $"{blood:F2}"),
            ("max", $"{comp.MaxBloodPool}"),
            ("percent", (int) (blood * 100f / maxBlood)));
        _bloodVial.SetFill(blood / maxBlood);

        var totalRanks = 0;
        var maxRanks = 0;

        foreach (var entry in _rows)
        {
            var rank = comp.UpgradeRanks.GetValueOrDefault(entry.Id);
            totalRanks += rank;
            maxRanks += entry.MaxRank;
            entry.Row.Refresh(rank, blood);
        }

        LifetimeLabel.Text = Loc.GetString("space-leech-upgrade-amount",
            ("amount", $"{comp.BloodConsumedTotal.Float():F2}"));
        MutationsLabel.Text = Loc.GetString("space-leech-upgrade-mutations-value",
            ("current", totalRanks),
            ("max", maxRanks));
        MutationsLabel.FontColorOverride = totalRanks >= maxRanks ? GreenGood : GoldAccent;
    }

    private sealed record UpgradeRowEntry(ProtoId<SpaceLeechUpgradePrototype> Id, int MaxRank, RankedUpgradeRow Row);
}
