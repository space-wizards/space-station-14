using System.Collections;
using System.Text;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio.Midi;
using Robust.Shared.Utility;

namespace Content.Client.Instruments.UI;

[GenerateTypedNameReferences]
public sealed partial class ChannelsControl : Control
{
    /// <summary>
    /// Raised when a channel is toggled.
    /// </summary>
    public event Action<int, bool>? SwitchFilteredChannel;

    /// <summary>
    /// Raised when a selector button is pressed in order to display different channel names.
    /// </summary>
    public event Action? ChannelsUpdateRequest;

    private readonly BitArray _usedChannels = new(RobustMidiEvent.MaxChannels, false);

    public ChannelsControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        DisplayUnusedSwitchButton.OnPressed += OnDisplayUnusedSwitchButtonPressed;
        DisplayTracksSwitchButton.OnPressed += OnDisplayTracksSwitchButtonPressed;

        var formatted = new FormattedMessage();
        formatted.AddMarkupOrThrow($"[bold]{Loc.GetString("instruments-component-menu-channels-label")}[/bold]");
        TitleLabel.SetMessage(formatted, Color.FromHex("#A88B5E"));

        InitChannels();
    }

    private void OnDisplayTracksSwitchButtonPressed(BaseButton.ButtonEventArgs obj)
    {
        foreach (var control in ChannelsContainer.Children)
        {
            if (control is not ChannelItem cItem)
                continue;

            cItem.ShowChannelInfo = DisplayTracksSwitchButton.Pressed;
        }
    }

    private void OnDisplayUnusedSwitchButtonPressed(BaseButton.ButtonEventArgs obj)
    {
        var i = 0;
        foreach (var cItem in ChannelsContainer.Children)
        {
            if (i >= _usedChannels.Length)
                continue;

            cItem.Visible = _usedChannels[i] || DisplayUnusedSwitchButton.Pressed;
            i++;
        }
    }

    protected override void VisibilityChanged(bool newVisible)
    {
        if (newVisible)
            ChannelsUpdateRequest?.Invoke();
    }

    private void OnChannelSwitched(int id, bool state)
    {
        SwitchFilteredChannel?.Invoke(id, state);
    }

    private void InitChannels()
    {
        for (var i = 0; i < RobustMidiEvent.MaxChannels; i++)
        {
            var item = new ChannelItem
            {
                ChannelId = i,
            };
            ChannelsContainer.AddChild(item);
            item.SwitchFilteredChannel += OnChannelSwitched;
        }
    }

    private void ClearChannels()
    {
        foreach (var child in ChannelsContainer.Children)
        {
            if (child is not ChannelItem cItem)
                return;

            cItem.ChannelLabel = "";
            cItem.ChannelState = false;
            cItem.Visible = false;
        }
    }

    /// <summary>
    /// Replaces the current list of channels with the passed one.
    /// </summary>
    /// <remarks>
    /// Calling this method overrides the toggle state of all channel items. Ensure to pass correct values.
    /// </remarks>
    /// <param name="channels">List of channels consisting of their index, display name and state.</param>
    public void SetChannels(MidiChannelInfo[] channels)
    {
        ClearChannels();

        foreach (var channel in channels)
        {
            if (channel.Id < 0 || channel.Id >= RobustMidiEvent.MaxChannels)
                continue;

            if (channel.Id >= ChannelsContainer.ChildCount)
                continue;

            if (ChannelsContainer.Children[channel.Id] is not ChannelItem cItem)
                continue;

            _usedChannels[channel.Id] = channel.ChannelUsed;

            cItem.ChannelLabel = channel.Label;
            cItem.ChannelState = channel.FilterState;
            if (channel.TracksOnChannel.Length > 0)
            {
                var builder = new StringBuilder();
                var i = 0;
                foreach (var track in channel.TracksOnChannel)
                {
                    builder.AppendLine($"Track {i}: {track.TrackName}");
                    i++;
                }
                cItem.ChannelInfo = builder.ToString().TrimEnd();
            }
            else
            {
                cItem.ChannelInfo = string.Empty;
            }

            cItem.Visible = channel.ChannelUsed || DisplayUnusedSwitchButton.Pressed;
        }
    }
}
