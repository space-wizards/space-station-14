using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio.Midi;

namespace Content.Client.Instruments.UI;

[GenerateTypedNameReferences]
public sealed partial class ChannelsControl : Control
{
    /// <summary>
    /// Raised when a channel is toggled.
    /// </summary>
    public event Action<int, bool>? SwitchFilteredChannel;

    /// <summary>
    /// Raised when a selector button is pressed in order to display different channel names.
    /// </summary>
    public event Action? ChannelsUpdateRequest;

    public ChannelsControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TrackSelectorButton.OnPressed += OnSelectorButtonPressed;
        InstrumentSelectorButton.OnPressed += OnSelectorButtonPressed;
        ProgramSelectorButton.OnPressed += OnSelectorButtonPressed;

        var group = new ButtonGroup();
        TrackSelectorButton.Group = group;
        InstrumentSelectorButton.Group = group;
        ProgramSelectorButton.Group = group;

        InitChannels();
    }

    protected override void VisibilityChanged(bool newVisible)
    {
        if (newVisible)
            ChannelsUpdateRequest?.Invoke();
    }

    private void OnSelectorButtonPressed(BaseButton.ButtonEventArgs obj)
    {
        ChannelsUpdateRequest?.Invoke();
    }

    private void OnChannelSwitched(int id, bool state)
    {
        SwitchFilteredChannel?.Invoke(id, state);
    }

    private void InitChannels()
    {
        for (var i = 0; i < RobustMidiEvent.MaxChannels; i++)
        {
            var item = new ChannelItem()
            {
                ChannelId = i,
            };
            ChannelsContainer.AddChild(item);
            item.SwitchFilteredChannel += OnChannelSwitched;
        }
    }

    /// <summary>
    /// Replaces the current list of channels with the passed one.
    /// </summary>
    /// <param name="channels">List of channels consisting of their index, display name and state.</param>
    public void SetChannels((int, string, string, string, bool)[] channels)
    {
        TrackSelectorButton.Disabled = true;
        InstrumentSelectorButton.Disabled = true;
        ProgramSelectorButton.Disabled = true;

        for (var i = 0; i < RobustMidiEvent.MaxChannels; i++)
        {
            if (i >= ChannelsContainer.ChildCount || i < 0)
                return;

            if (ChannelsContainer.Children[i] is not ChannelItem cItem)
                return;

            cItem.ChannelName = "";
            cItem.ChannelState = false;
            cItem.Visible = false;

            if (i >= channels.Length)
                continue;

            var channel = channels[i];

            if (channel.Item2.Length > 0)
                TrackSelectorButton.Disabled = false;
            if (channel.Item3.Length > 0)
                InstrumentSelectorButton.Disabled = false;
            if (channel.Item4.Length > 0)
                ProgramSelectorButton.Disabled = false;

            if (TrackSelectorButton.Pressed)
                cItem.ChannelName = channel.Item2;
            if (InstrumentSelectorButton.Pressed)
                cItem.ChannelName = channel.Item3;
            if (ProgramSelectorButton.Pressed)
                cItem.ChannelName = channel.Item4;

            cItem.ChannelState = channel.Item5;
            cItem.Visible = true;
        }
    }
}
