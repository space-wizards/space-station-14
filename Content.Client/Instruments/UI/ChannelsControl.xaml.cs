using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio.Midi;

namespace Content.Client.Instruments.UI;

[GenerateTypedNameReferences]
public sealed partial class ChannelsControl : Control
{
    /// <summary>
    /// Raised when a channel is toggled.
    /// </summary>
    public event Action<int, bool>? SwitchFilteredChannel;

    /// <summary>
    /// Raised when a selector button is pressed in order to display different channel names.
    /// </summary>
    public event Action? ChannelsUpdateRequest;

    public ChannelsControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        InitChannels();
    }

    protected override void VisibilityChanged(bool newVisible)
    {
        if (newVisible)
            ChannelsUpdateRequest?.Invoke();
    }

    private void OnChannelSwitched(int id, bool state)
    {
        SwitchFilteredChannel?.Invoke(id, state);
    }

    private void InitChannels()
    {
        for (var i = 0; i < RobustMidiEvent.MaxChannels; i++)
        {
            var item = new ChannelItem
            {
                ChannelId = i,
            };
            ChannelsContainer.AddChild(item);
            item.SwitchFilteredChannel += OnChannelSwitched;
        }
    }

    private void ClearChannels()
    {
        foreach (var child in ChannelsContainer.Children)
        {
            if (child is not ChannelItem cItem)
                return;

            cItem.ChannelLabel = "";
            cItem.ChannelState = false;
            cItem.Visible = false;
        }
    }

    /// <summary>
    /// Replaces the current list of channels with the passed one.
    /// </summary>
    /// <remarks>
    /// Calling this method overrides the toggle state of all channel items. Ensure to pass correct values.
    /// </remarks>
    /// <param name="channels">List of channels consisting of their index, display name and state.</param>
    public void SetChannels(MidiChannelInfo[] channels)
    {
        ClearChannels();

        foreach (var channel in channels)
        {
            if (channel.Id < 0 || channel.Id >= RobustMidiEvent.MaxChannels)
                continue;

            if (channel.Id >= ChannelsContainer.ChildCount)
                continue;

            if (ChannelsContainer.Children[channel.Id] is not ChannelItem cItem)
                continue;

            cItem.ChannelLabel = channel.Label;
            cItem.ChannelState = channel.FilterState;
            cItem.Visible = true;
        }
    }
}
