using Content.Client.Decals.UI;
using Content.Client.Stylesheets;
using Content.Shared.Decals;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using System.Linq;
using System.Numerics;

namespace Content.Client.SprayPainter.UI;

/// <summary>
/// Used to control decal painting parameters for the spray painter.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SprayPainterDecals : Control
{
    public const string StyleClassDecalButton = "decalbutton";

    private const int numDecalColumns = 7; // The number of columns we want to use to show decals

    public Action<ProtoId<DecalPrototype>>? OnDecalSelected;
    public Action<Color?>? OnColorChanged;
    public Action<int>? OnAngleChanged;
    public Action<bool>? OnSnapChanged;
    public Action<bool>? OnColorPickerToggled;

    private PaletteColorPicker? _palette;

    private SpriteSystem? _sprite;
    private string _selectedDecal = string.Empty;
    private BaseButton? _selectedDecalButton = null;
    private List<SprayPainterDecalEntry> _decals = [];

    public SprayPainterDecals()
    {
        RobustXamlLoader.Load(this);

        AddAngleButton.OnButtonUp += _ => AngleSpinBox.Value = (AngleSpinBox.Value + 90) % 360;
        SubAngleButton.OnButtonUp += _ => AngleSpinBox.Value = (AngleSpinBox.Value - 90) % 360;
        SetZeroAngleButton.OnButtonUp += _ => AngleSpinBox.Value = 0;
        AngleSpinBox.ValueChanged += args => OnAngleChanged?.Invoke(args.Value);

        UseCustomColorCheckBox.OnPressed += UseCustomColorCheckBoxOnOnPressed;
        SnapToTileCheckBox.OnPressed += SnapToTileCheckBoxOnOnPressed;
        ColorSelector.OnColorChanged += OnColorSelected;

        ColorPalette.OnPressed += ColorPaletteOnPressed;
        ColorPicker.OnPressed += args => OnColorPickerToggled?.Invoke(args.Button.Pressed);

        DecalsGrid.GenerateItem = GenerateDecalControls;
    }

    private void GenerateDecalControls(ListData data, ListContainerButton button)
    {
        if (data is not DecalRowData drd)
        {
            return;
        }

        // Populate button with our set of decals. If you change the
        // structure of the controls here, you must also change the code
        // in SetSelectedDecal which is searching for these buttons

        // Remove the (forced!) StyleBoxOverride added
        // by the ListContainer and setup our own style
        button.StyleBoxOverride = null;
        button.RemoveStyleClass(ContainerButton.StyleClassButton);

        var row = new BoxContainer();

        for (var i = drd.Start; i < drd.End; i++)
        {
            var decal = _decals[i];
            var decalButton = new Button()
            {
                Children = {
                    new TextureRect
                    {
                        Texture = _sprite!.Frame0(decal.Sprite),
                        TextureScale = new Vector2(2, 2),
                    }
                },
                Name = decal.Name,
                ToolTip = decal.Name,
            };
            decalButton.AddStyleClass(StyleClassDecalButton);
            decalButton.OnPressed += DecalButtonOnPressed;

            if (_selectedDecal == decal.Name)
            {
                _selectedDecalButton = decalButton;
                decalButton.Pressed = true;
            }

            row.AddChild(decalButton);
        }

        button.AddChild(row);
    }

    private void UseCustomColorCheckBoxOnOnPressed(BaseButton.ButtonEventArgs _)
    {
        OnColorChanged?.Invoke(UseCustomColorCheckBox.Pressed ? ColorSelector.Color : null);
        UpdateColorButtons(UseCustomColorCheckBox.Pressed);
    }

    private void SnapToTileCheckBoxOnOnPressed(BaseButton.ButtonEventArgs _)
    {
        OnSnapChanged?.Invoke(SnapToTileCheckBox.Pressed);
    }

    /// <summary>
    /// Updates the decal list.
    /// </summary>
    public void PopulateDecals(List<SprayPainterDecalEntry> decals, SpriteSystem sprite)
    {
        _sprite ??= sprite;

        _decals = decals;

        var decalRows = new List<DecalRowData>();
        for (var i = 0; i < decals.Count; i += numDecalColumns)
        {
            decalRows.Add(new DecalRowData(i, Math.Min(i + numDecalColumns, decals.Count())));
        }
        DecalsGrid.PopulateList(decalRows);
        return;
    }

    private void OnColorSelected(Color color)
    {
        if (!UseCustomColorCheckBox.Pressed)
            return;

        OnColorChanged?.Invoke(color);

        UpdateColorButtons(UseCustomColorCheckBox.Pressed);
    }

    private void UpdateColorButtons(bool apply)
    {
        var modulateColor = apply ? ColorSelector.Color : Color.White;
        DecalsGrid.Modulate = modulateColor;
    }

    private void DecalButtonOnPressed(BaseButton.ButtonEventArgs obj)
    {
        if (obj.Button.Name is not { } name)
            return;

        if (_selectedDecalButton != obj.Button)
        {
            _selectedDecalButton?.Pressed = false;
            _selectedDecalButton = obj.Button;
        }

        _selectedDecal = name;
        OnDecalSelected?.Invoke(_selectedDecal);
    }

    public void SetSelectedDecal(string name)
    {
        if (name == _selectedDecal)
        {
            return;
        }

        _selectedDecal = name;
        SelectedDecalName.Text = name;
        _selectedDecalButton?.Pressed = false;
        _selectedDecalButton = null;

        // See if the decal is visible, and ensure it appears as pressed
        // This is a little bit awkward, as the ListContainer creates
        // controls as they become visible, but we created this structure
        // in GenerateDecalControls
        foreach (var c in DecalsGrid.Children)
        {
            if (c is not ListContainerButton decalrow)
            {
                continue;
            }
            foreach (var rowElements in decalrow.Children)
            {
                if (rowElements is not BoxContainer row)
                {
                    continue;
                }
                foreach (var rowItem in row.Children)
                {
                    if (rowItem.Name == name && rowItem is Button btn)
                    {
                        _selectedDecalButton = btn;
                        btn.Pressed = true;
                    }
                }
            }
        }
    }

    public void SetAngle(int degrees)
    {
        AngleSpinBox.OverrideValue(degrees);
    }

    public void SetColor(Color? color)
    {
        UseCustomColorCheckBox.Pressed = color != null;
        if (color != null)
            ColorSelector.Color = color.Value;
        UpdateColorButtons(UseCustomColorCheckBox.Pressed);
    }

    public void SetSnap(bool snap)
    {
        SnapToTileCheckBox.Pressed = snap;
    }

    private void ColorPaletteOnPressed(BaseButton.ButtonEventArgs _)
    {
        // Code copied from other implementations of `PaletteColorPicker`.
        if (_palette is null)
        {
            _palette = new PaletteColorPicker();
            _palette.OpenCenteredLeft();
            _palette.PaletteList.OnItemSelected += args =>
            {
                var color = (args.ItemList.GetSelected().First().Metadata as Color?)!.Value;
                ColorSelector.Color = color;
                OnColorSelected(color);
            };
            return;
        }

        if (_palette.IsOpen)
        {
            _palette.Close();
        }
        else
        {
            _palette.Open();
        }
    }

    public void SetColorPicker(bool enabled)
    {
        ColorPicker.Pressed = enabled;
    }
}

public record DecalRowData(int Start, int End) : ListData;
