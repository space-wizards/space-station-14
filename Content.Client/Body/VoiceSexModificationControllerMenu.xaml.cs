using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.Body.Events;
using Content.Shared.Chat.Prototypes;
using Content.Shared.Humanoid;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.Body;

/// <summary>
/// Menu window for the voice/sex modification controller.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class VoiceSexModificationControllerMenu : FancyWindow
{
    /// <summary>
    /// Action to fire when the user's selection is confirmed.
    /// </summary>
    public Action<ProtoId<EmoteSoundsPrototype>?, Sex>? OnConfirmChange;

    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private List<EmoteSoundsPrototype> _voices = new();

    /// <summary>
    /// Menu window for the voice/sex modification controller.
    /// </summary>
    public VoiceSexModificationControllerMenu()
    {
        RobustXamlLoader.Load(this);

        SexButton.OnItemSelected += args =>
        {
            SexButton.SelectId(args.Id);
        };

        VoiceButton.OnItemSelected += args =>
        {
            VoiceButton.SelectId(args.Id);
        };

        ConfirmButton.OnPressed += ConfirmPressed;
        CancelButton.OnPressed += CancelPressed;
    }

    /// <summary>
    /// Update the state of the modification menu, setting available voices/sexes based on the user's species.
    /// </summary>
    /// <param name="state"></param>
    public void UpdateState(VoiceSexModificationControllerBuiState state)
    {
        SexButton.Clear();
        VoiceButton.Clear();
        _voices.Clear();

        var sexes = new List<Sex>();

        if (_prototypeManager.Resolve(state.Species, out var speciesProto))
        {
            foreach (var sex in speciesProto.Sexes)
            {
                sexes.Add(sex);
            }

            var availableVoices = speciesProto.Voices;
            _voices = System.Linq.Enumerable.Select(availableVoices, protoId => _prototypeManager.Index(protoId)).ToList();

            for (var i = 0; i < _voices.Count; i++)
            {
                var name = Loc.GetString(_voices[i].VoiceSelectorName);
                VoiceButton.AddItem(name, i);

                if (state.CurrentVoice != null)
                {
                    if (state.CurrentVoice.Value.Id.Equals(_voices[i].ID))
                    {
                        VoiceButton.SelectId(i);
                    }
                }
            }
        }
        else
        {
            sexes.Add(Sex.Unsexed);
            VoiceButton.AddItem(Loc.GetString($"humanoid-profile-editor-voice-none"), -1);
        }

        foreach (var sex in sexes)
        {
            SexButton.AddItem(Loc.GetString($"humanoid-profile-editor-sex-{sex.ToString().ToLower()}-text"), (int)sex);
        }

        if (state.CurrentSex != null && sexes.Contains(state.CurrentSex.Value))
            SexButton.SelectId((int)state.CurrentSex.Value);
        else
            SexButton.SelectId((int)sexes[0]);
    }

    private void ConfirmPressed(BaseButton.ButtonEventArgs obj)
    {
        var voice = VoiceButton.SelectedId == -1 ? null : new ProtoId<EmoteSoundsPrototype>?(_voices[VoiceButton.SelectedId].ID);
        OnConfirmChange?.Invoke(voice, (Sex)SexButton.SelectedId);
        Close();
    }

    private void CancelPressed(BaseButton.ButtonEventArgs obj)
    {
        Close();
    }
}
