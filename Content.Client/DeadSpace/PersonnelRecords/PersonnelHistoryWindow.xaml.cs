using Content.Shared.DeadSpace.PersonnelRecords;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.DeadSpace.PersonnelRecords;

/// <summary>
/// Window opened when the "Order history" button is pressed. Unlike the criminal records
/// console's crime history, this is read-only end to end - the design explicitly rules out manual
/// add/delete of history entries (§ "Ручного добавления и удаления записей истории нет").
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PersonnelHistoryWindow : FancyWindow
{
    public PersonnelHistoryWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateHistory(PersonnelRecord record)
    {
        History.Clear();

        NoHistory.Visible = record.History.Count == 0;

        foreach (var entry in record.History)
        {
            var time = entry.AddTime;
            var typeName = Loc.GetString($"personnel-records-history-type-{entry.Type.ToString().ToLower()}");
            var initiator = entry.InitiatorName ?? Loc.GetString("personnel-records-console-unknown-officer");
            var line = $"{time.Hours:00}:{time.Minutes:00}:{time.Seconds:00} - {typeName}: {entry.Text} ({initiator})";
            History.AddItem(line);
        }
    }
}
