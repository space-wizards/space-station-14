namespace Content.Client.DeadSpace.PersonnelRecords;

/// <summary>
/// Personnel Records console window - structure mirrors <c>CriminalRecordsConsoleWindow</c>.
///
/// Unlike the criminal records console, button availability here comes entirely from the
/// server-computed flags in <see cref="PersonnelRecordsConsoleState"/> (Can*), not from a
/// client-side access check: the department scope this console shows depends on whose ID card is
/// in play, something only the server can re-derive safely, so there's nothing meaningful for the
/// client to compute on its own here.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PersonnelRecordsConsoleWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    private readonly SpriteSystem _spriteSystem;
    private readonly SharedJobSystem _jobSystem;

    private readonly uint _maxLength;
    private uint? _selectedKey;
    private PersonnelRecord? _selectedRecord;

    private DialogWindow? _reasonDialog;

    private StationRecordFilterType _currentFilterType;
    private EmploymentStatus _currentCrewListFilter;

    public Action<uint?>? OnKeySelected;
    public Action<StationRecordFilterType, string>? OnFiltersChanged;
    public Action<EmploymentStatus>? OnStatusFilterPressed;
    public Action<EmploymentStatus, string>? OnIssueOrder;
    public Action<string>? OnAnnulOrder;
    public Action<string>? OnDeclareWanted;
    public Action? OnPrintOrder;
    public Action<PersonnelRecord, bool>? OnHistoryUpdated;
    public Action? OnHistoryClosed;

    public PersonnelRecordsConsoleWindow(uint maxLength)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _spriteSystem = _entManager.System<SpriteSystem>();
        _jobSystem = _entManager.System<SharedJobSystem>();

        _maxLength = maxLength;
        _currentFilterType = StationRecordFilterType.Name;
        _currentCrewListFilter = EmploymentStatus.None;

        OpenCentered();

        foreach (var item in Enum.GetValues<StationRecordFilterType>())
        {
            FilterType.AddItem(GetTypeFilterLocals(item), (int)item);
        }

        foreach (var item in Enum.GetValues<EmploymentStatus>())
        {
            CrewListFilter.AddItem(GetCrewListFilterLocals(item), (int)item);
        }

        OnClose += () => _reasonDialog?.Close();

        RecordListing.OnItemSelected += args =>
        {
            if (RecordListing[args.ItemIndex].Metadata is not uint cast)
                return;

            OnKeySelected?.Invoke(cast);
        };

        RecordListing.OnItemDeselected += _ =>
        {
            OnKeySelected?.Invoke(null);
        };

        FilterType.OnItemSelected += eventArgs =>
        {
            var type = (StationRecordFilterType)eventArgs.Id;

            if (_currentFilterType != type)
            {
                _currentFilterType = type;
                FilterListingOfRecords(FilterText.Text);
            }
        };

        CrewListFilter.OnItemSelected += eventArgs =>
        {
            var type = (EmploymentStatus)eventArgs.Id;

            if (_currentCrewListFilter != type)
            {
                _currentCrewListFilter = type;
                OnStatusFilterPressed?.Invoke(type);
            }
        };

        FilterText.OnTextEntered += args =>
        {
            FilterListingOfRecords(args.Text);
        };

        ReprimandButton.OnPressed += _ =>
            OpenReasonDialog(Loc.GetString("personnel-records-console-reprimand-button"), "personnel-records-console-reason-placeholder",
                reason => OnIssueOrder?.Invoke(EmploymentStatus.Reprimand, reason));

        DemoteButton.OnPressed += _ =>
            OpenReasonDialog(Loc.GetString("personnel-records-console-demote-button"), "personnel-records-console-reason-placeholder",
                reason => OnIssueOrder?.Invoke(EmploymentStatus.Demotion, reason));

        DismissButton.OnPressed += _ =>
            OpenReasonDialog(Loc.GetString("personnel-records-console-dismiss-button"), "personnel-records-console-reason-placeholder",
                reason => OnIssueOrder?.Invoke(EmploymentStatus.Dismissal, reason));

        AnnulButton.OnPressed += _ =>
            OpenReasonDialog(Loc.GetString("personnel-records-console-annul-button"), "personnel-records-console-annul-reason-placeholder",
                reason => OnAnnulOrder?.Invoke(reason));

        DeclareWantedButton.OnPressed += _ =>
            OpenReasonDialog(Loc.GetString("personnel-records-console-declare-wanted-button"), "personnel-records-console-wanted-reason-placeholder",
                reason => OnDeclareWanted?.Invoke(reason));

        PrintButton.OnPressed += _ => OnPrintOrder?.Invoke();

        HistoryButton.OnPressed += _ =>
        {
            if (_selectedRecord is { } record)
                OnHistoryUpdated?.Invoke(record, true);
        };
    }

    /// <summary>
    /// Every order/annul/wanted action needs a mandatory typed reason - one dialog field reused
    /// for all of them, same pattern as the criminal records console's status-change dialog.
    /// </summary>
    private void OpenReasonDialog(string title, string placeholderLocKey, Action<string> onConfirmed)
    {
        if (_reasonDialog != null)
        {
            _reasonDialog.MoveToFront();
            return;
        }

        var field = "reason";
        var prompt = Loc.GetString("personnel-records-console-reason");
        var placeholder = Loc.GetString(placeholderLocKey);
        var entry = new QuickDialogEntry(field, QuickDialogEntryType.LongText, prompt, placeholder);
        _reasonDialog = new DialogWindow(title, new List<QuickDialogEntry> { entry });

        _reasonDialog.OnConfirmed += responses =>
        {
            var reason = responses[field];
            if (reason.Length < 1 || reason.Length > _maxLength)
                return;

            onConfirmed(reason);
        };

        _reasonDialog.OnClose += () => { _reasonDialog = null; };
    }

    public void UpdateState(PersonnelRecordsConsoleState state)
    {
        if (state.Filter != null)
        {
            if (state.Filter.Type != _currentFilterType)
                _currentFilterType = state.Filter.Type;

            if (state.Filter.Value != FilterText.Text)
                FilterText.Text = state.Filter.Value;
        }

        if (state.FilterStatus != _currentCrewListFilter)
            _currentCrewListFilter = state.FilterStatus;

        _selectedKey = state.SelectedKey;
        FilterType.SelectId((int)_currentFilterType);
        CrewListFilter.SelectId((int)_currentCrewListFilter);

        var hasListing = state.RecordListing is { Count: > 0 };
        NoDepartmentLabel.Visible = state.NoDepartment;
        NoRecords.Visible = !state.NoDepartment && !hasListing;
        PopulateRecordListing(state.RecordListing);

        var selected = _selectedKey != null;
        PersonContainer.Visible = selected;
        RecordUnselected.Visible = !selected && !state.NoDepartment;

        if (state is { StationRecord: not null, PersonnelRecord: not null })
        {
            PopulateRecordContainer(state.StationRecord, state.PersonnelRecord, state.CriminalRecord);
            OnHistoryUpdated?.Invoke(state.PersonnelRecord, false);
            _selectedRecord = state.PersonnelRecord;
        }
        else
        {
            _selectedRecord = null;
            OnHistoryClosed?.Invoke();
        }

        ReprimandButton.Disabled = !state.CanReprimand;
        DemoteButton.Disabled = !state.CanDemote;
        DismissButton.Disabled = !state.CanDismiss;
        AnnulButton.Disabled = !state.CanAnnul;
        PrintButton.Disabled = !state.CanPrint;
        DeclareWantedButton.Disabled = !state.CanDeclareWanted;
        DeclareWantedButton.Visible = state.CanDeclareWanted;
    }

    private void PopulateRecordListing(Dictionary<uint, string>? listing)
    {
        if (listing == null)
        {
            RecordListing.Clear();
            return;
        }

        var entries = listing.Select(i => new ItemList.Item(RecordListing)
        {
            Text = i.Value,
            Metadata = i.Key,
        }).ToList();
        entries.Sort((a, b) => string.Compare(a.Text, b.Text, StringComparison.Ordinal));
        RecordListing.SetItems(entries, (a, b) => string.Compare(a.Text, b.Text));
    }

    private void PopulateRecordContainer(GeneralStationRecord stationRecord, PersonnelRecord personnelRecord, CriminalRecord? criminalRecord)
    {
        var na = Loc.GetString("generic-not-available-shorthand");

        PersonName.Text = stationRecord.Name;
        PersonJob.Text = stationRecord.JobTitle ?? na;

        if (_proto.TryIndex<JobIconPrototype>(stationRecord.JobIcon, out var jobIcon))
            PersonJobIcon.Texture = _spriteSystem.Frame0(jobIcon.Icon);

        var department = _jobSystem.TryGetPrimaryDepartment(stationRecord.JobPrototype, out var dept)
            ? Loc.GetString(dept.Name)
            : na;
        PersonDepartment.Text = Loc.GetString("personnel-records-console-record-department", ("department", department));

        PersonAge.Text = Loc.GetString("general-station-record-console-record-age", ("age", stationRecord.Age));
        PersonSpecies.Text = Loc.GetString("general-station-record-console-record-species", ("species", stationRecord.Species));

        PersonStatus.Text = Loc.GetString($"personnel-records-status-{personnelRecord.Status.ToString().ToLower()}");

        if (personnelRecord.Reason is { } reason)
        {
            var message = FormattedMessage.FromMarkupOrThrow(Loc.GetString("personnel-records-console-reason-label"));
            message.AddText($": {reason}");
            PersonReason.SetMessage(message);
            PersonReason.Visible = true;
        }
        else
        {
            PersonReason.Visible = false;
        }

        if (personnelRecord.InitiatorName is { } initiator)
        {
            var message = FormattedMessage.FromMarkupOrThrow(Loc.GetString("personnel-records-console-initiator-label"));
            message.AddText($": {initiator}");
            PersonInitiator.SetMessage(message);
            PersonInitiator.Visible = true;
        }
        else
        {
            PersonInitiator.Visible = false;
        }

        // Reuses the criminal records feature's own status-name keys (criminal-records-status-*)
        // rather than duplicating every SecurityStatus name here - this is a read-only display of
        // the same enum, not a second copy of it.
        PersonCriminalStatus.Text = criminalRecord != null
            ? Loc.GetString($"criminal-records-status-{criminalRecord.Status.ToString().ToLower()}")
            : Loc.GetString("criminal-records-status-none");
    }

    private void FilterListingOfRecords(string text = "")
    {
        OnFiltersChanged?.Invoke(_currentFilterType, text);
    }

    private string GetTypeFilterLocals(StationRecordFilterType type)
    {
        return Loc.GetString($"personnel-records-{type.ToString().ToLower()}-filter");
    }

    private string GetCrewListFilterLocals(EmploymentStatus type)
    {
        return type == EmploymentStatus.None
            ? Loc.GetString("personnel-records-console-show-all")
            : Loc.GetString($"personnel-records-status-{type.ToString().ToLower()}");
    }
}
