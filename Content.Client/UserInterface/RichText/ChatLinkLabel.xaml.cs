using Content.Client.Chat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.UserInterface.RichText;

[GenerateTypedNameReferences]
public sealed partial class ChatLinkLabel : Label
{
    [Dependency] private IEntityManager _entity = default!;

    private ChatSystem? _Chat;
    private bool _inVisibilityChanged;

    public ChatLinkLabel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    protected override void VisibilityChanged(bool newVisible)
    {
        // RichTextEntry force sets visible after visible has already been set in frame update
        // So we need to do this to override it
        // Tremendous!
        if (_inVisibilityChanged)
            return;

        try
        {
            _inVisibilityChanged = true;
            base.VisibilityChanged(newVisible);
            UpdateVisibility();
        }
        finally
        {
            _inVisibilityChanged = false;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateVisibility();
    }

    private void UpdateVisibility()
    {
        _Chat ??= _entity.System<ChatSystem>();
        var canClick = _Chat.CanClickMessageSender(null);
        Visible = canClick;
    }
}
