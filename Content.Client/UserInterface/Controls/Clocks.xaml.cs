using System.Globalization;
using Content.Client.Playtime;
using Content.Shared.CCVar;
using Content.Shared.Players.PlayTimeTracking;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Timing;

namespace Content.Client.UserInterface.Controls;

[GenerateTypedNameReferences]
public sealed partial class Clocks : Control
{
    [Dependency] private IConfigurationManager _configurationManager = default!;
    [Dependency] private ClientsidePlaytimeTrackingManager _playtimeTracking = default!;

    /// <summary>
    /// Toggles when player pressed on button, when true, shows how huch minutes they have played today
    /// </summary>
    private bool _playerTime = false;

    public Clocks()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TimeButton.OnPressed += _ => _playerTime = !_playerTime;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        if (!_configurationManager.GetCVar(CCVars.ClocksEnabled))
        {
            Visible = false;
            return;
        }
        Visible = true;

        if (_playerTime)
        {
            var minutesToday = _playtimeTracking.PlaytimeMinutesToday;

            if (minutesToday < 60)
            {
                TimeButton.Text = Loc.GetString("clocks-playtime-minutes", ("minutes", (int)minutesToday));
                return;
            }

            var hoursToday = Math.Round(minutesToday / 60f, 1);
            var msg = Loc.GetString("clocks-playtime-hours", ("hours", hoursToday));
            TimeButton.Text = msg;
            return;
        }

        var format = "h:mm tt";
        if (_configurationManager.GetCVar(CCVars.Clocks24HoursFormat))
            format = "H:mm";

        TimeButton.Text = DateTime.Now.ToString(format);
    }
}
