using Content.Client.UserInterface.Controls;
using Content.Shared.Maps;
using Content.Shared.SpaceArena;
using Content.Shared.SpaceArena.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.SpaceArena.UI;

[GenerateTypedNameReferences]
public sealed partial class SpaceArenaLobbyMenu : FancyWindow
{
    [Dependency] private IPlayerManager _players = default!;

    public event Action<EntProtoId, ProtoId<GameMapPrototype>>? OnCreateLobby;
    public event Action<NetEntity>? OnJoinLobby;
    public event Action<NetEntity>? OnStartLobby;
    public event Action<NetEntity>? OnSpectateLobby;
    public event Action? OnLeaveLobby;

    private readonly List<SpaceArenaLobbyArenaOption> _visibleArenas = [];
    private SpaceArenaLobbyBoundUserInterfaceState? _state;
    private NetEntity? _currentLobby;
    private NetEntity? _spectatedMatch;
    private bool _canManageLobbies = true;
    private int _selectedMode;
    private int _selectedArena;

    public SpaceArenaLobbyMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ModeOption.OnItemSelected += args =>
        {
            args.Button.SelectId(args.Id);
            _selectedMode = args.Id;
            RebuildArenaOptions();
            UpdateCreateButton();
        };
        ArenaOption.OnItemSelected += args =>
        {
            args.Button.SelectId(args.Id);
            _selectedArena = args.Id;
            UpdateArenaPreview();
            UpdateCreateButton();
        };
        CreateButton.OnPressed += _ => CreateLobby();
        LeaveButton.OnPressed += _ => OnLeaveLobby?.Invoke();
    }

    public void UpdateState(SpaceArenaLobbyBoundUserInterfaceState state)
    {
        UpdateState(state.Modes, state.Arenas, state.Rooms);
    }

    public void UpdateState(
        List<SpaceArenaLobbyModeOption> modes,
        List<SpaceArenaLobbyArenaOption> arenas,
        List<SpaceArenaLobbyRoom> rooms)
    {
        _state = new SpaceArenaLobbyBoundUserInterfaceState(modes, arenas, rooms);
        RebuildModeOptions();
        RebuildRooms();
    }

    public void UpdateUserStatus(
        NetEntity? currentLobby,
        NetEntity? spectatedMatch,
        bool canManageLobbies)
    {
        _currentLobby = currentLobby;
        _spectatedMatch = spectatedMatch;
        _canManageLobbies = canManageLobbies;
        MembershipLabel.Text = Loc.GetString(spectatedMatch != null
            ? "space-arena-lobby-membership-spectating"
            : !canManageLobbies
                ? "space-arena-lobby-membership-active"
            : currentLobby == null
                ? "space-arena-lobby-membership-none"
                : "space-arena-lobby-membership-joined");
        LeaveButton.Visible = currentLobby != null;
        ModeOption.Disabled = !canManageLobbies;
        ArenaOption.Disabled = !canManageLobbies;
        RebuildRooms();
        UpdateCreateButton();
    }

    private void RebuildModeOptions()
    {
        ModeOption.Clear();
        if (_state == null)
            return;

        for (var i = 0; i < _state.Modes.Count; i++)
            ModeOption.AddItem(Loc.GetString(_state.Modes[i].Name), i);

        _selectedMode = Math.Clamp(_selectedMode, 0, Math.Max(0, _state.Modes.Count - 1));
        if (_state.Modes.Count > 0)
            ModeOption.SelectId(_selectedMode);

        RebuildArenaOptions();
        UpdateCreateButton();
    }

    private void RebuildArenaOptions()
    {
        ArenaOption.Clear();
        _visibleArenas.Clear();
        if (_state == null || _state.Modes.Count == 0)
            return;

        var mode = _state.Modes[_selectedMode].Id;
        foreach (var arena in _state.Arenas)
        {
            if (!arena.Modes.Contains(mode))
                continue;

            var index = _visibleArenas.Count;
            _visibleArenas.Add(arena);
            ArenaOption.AddItem(
                Loc.GetString(
                    "space-arena-lobby-arena-option",
                    ("arena", arena.Name),
                    ("format", arena.Format)),
                index);
        }

        _selectedArena = Math.Clamp(_selectedArena, 0, Math.Max(0, _visibleArenas.Count - 1));
        if (_visibleArenas.Count > 0)
            ArenaOption.SelectId(_selectedArena);

        UpdateArenaPreview();
    }

    private void UpdateArenaPreview()
    {
        var weapon = _visibleArenas.Count > _selectedArena
            ? _visibleArenas[_selectedArena].PreviewWeapon
            : null;
        WeaponPreview.SetPrototype(weapon);
        WeaponPreviewPanel.Visible = weapon != null;
    }

    private void RebuildRooms()
    {
        RoomContainer.Children.Clear();
        if (_state == null)
            return;

        if (_state.Rooms.Count == 0)
        {
            RoomContainer.AddChild(new Label
            {
                Text = Loc.GetString("space-arena-lobby-list-empty"),
                StyleClasses = { "LabelSubText" },
                Margin = new Thickness(8),
            });
            return;
        }

        foreach (var room in _state.Rooms)
            RoomContainer.AddChild(CreateRoomEntry(room));
    }

    private Control CreateRoomEntry(SpaceArenaLobbyRoom room)
    {
        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(10, 8),
        };

        var details = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        details.AddChild(new Label
        {
            Text = Loc.GetString(
                "space-arena-lobby-room-title",
                ("host", room.HostName),
                ("mode", Loc.GetString(room.ModeName))),
            StyleClasses = { "LabelHeading" },
        });
        details.AddChild(new Label
        {
            Text = Loc.GetString(
                "space-arena-lobby-room-details",
                ("arena", room.ArenaName),
                ("players", room.PlayerCount),
                ("min", room.MinPlayers),
                ("max", room.MaxPlayers),
                ("state", Loc.GetString(StateLocId(room.State)))),
            StyleClasses = { "LabelSubText" },
        });
        content.AddChild(details);

        if (room.State != SpaceArenaMatchState.Waiting)
        {
            if (_spectatedMatch == room.Lobby)
            {
                content.AddChild(new Label
                {
                    Text = Loc.GetString("space-arena-lobby-you-spectate"),
                    VerticalAlignment = VAlignment.Center,
                });
            }
            else
            {
                var spectate = new Button
                {
                    Text = Loc.GetString("space-arena-lobby-spectate-button"),
                    Disabled = !_canManageLobbies,
                    MinWidth = 110,
                };
                spectate.OnPressed += _ => OnSpectateLobby?.Invoke(room.Lobby);
                content.AddChild(spectate);
            }

            return CreateRoomPanel(content);
        }

        var isMember = _currentLobby == room.Lobby;
        var isHost = isMember && _players.LocalSession?.UserId == room.Host;
        if (isHost)
        {
            var start = new Button
            {
                Text = Loc.GetString("space-arena-lobby-start-button"),
                Disabled = room.PlayerCount < room.MinPlayers,
                ToolTip = room.PlayerCount < room.MinPlayers
                    ? Loc.GetString("space-arena-lobby-start-disabled", ("min", room.MinPlayers))
                    : null,
                MinWidth = 110,
            };
            start.OnPressed += _ => OnStartLobby?.Invoke(room.Lobby);
            content.AddChild(start);
        }
        else if (isMember)
        {
            content.AddChild(new Label
            {
                Text = Loc.GetString("space-arena-lobby-you-joined"),
                VerticalAlignment = VAlignment.Center,
            });
        }
        else
        {
            var join = new Button
            {
                Text = Loc.GetString("space-arena-lobby-join-button"),
                Disabled = !_canManageLobbies ||
                           _currentLobby != null ||
                           room.PlayerCount >= room.MaxPlayers,
                MinWidth = 110,
            };
            join.OnPressed += _ => OnJoinLobby?.Invoke(room.Lobby);
            content.AddChild(join);
        }

        return CreateRoomPanel(content);
    }

    private static PanelContainer CreateRoomPanel(Control content)
    {
        return new PanelContainer
        {
            StyleClasses = { "PanelInsetDark" },
            Margin = new Thickness(0, 0, 0, 6),
            Children = { content },
        };
    }

    private static string StateLocId(SpaceArenaMatchState state)
    {
        return state switch
        {
            SpaceArenaMatchState.Waiting => "space-arena-lobby-state-waiting",
            SpaceArenaMatchState.Preparing => "space-arena-lobby-state-preparing",
            SpaceArenaMatchState.Countdown => "space-arena-lobby-state-countdown",
            SpaceArenaMatchState.Active => "space-arena-lobby-state-active",
            _ => "space-arena-lobby-state-finishing",
        };
    }

    private void CreateLobby()
    {
        if (_state == null ||
            _currentLobby != null ||
            _state.Modes.Count == 0 ||
            _visibleArenas.Count == 0)
        {
            return;
        }

        OnCreateLobby?.Invoke(_state.Modes[_selectedMode].Id, _visibleArenas[_selectedArena].Id);
    }

    private void UpdateCreateButton()
    {
        CreateButton.Disabled = _currentLobby != null ||
                                !_canManageLobbies ||
                                _state == null ||
                                _state.Modes.Count == 0 ||
                                _visibleArenas.Count == 0;
    }
}
