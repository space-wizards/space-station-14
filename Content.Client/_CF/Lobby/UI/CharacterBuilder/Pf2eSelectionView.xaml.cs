using System.Linq;
using Content.Shared.CF.Character;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CF.Lobby.UI.CharacterBuilder;

[GenerateTypedNameReferences]
public sealed partial class Pf2eSelectionView : BoxContainer
{
    public event Action? OnClosed;
    public event Action? OnAccept;
    public event Action<string>? OnEntrySelected;
    public event Action? OnPrdPressed;

    private readonly List<Pf2eListEntry> _entries = new();
    private ButtonGroup _listGroup = new();
    private CFRarity? _filter = CFRarity.Common;
    private string? _selectedId;
    private bool _suppress;

    public Pf2eSelectionView()
    {
        RobustXamlLoader.Load(this);

        var filters = new ButtonGroup(isNoneSetAllowed: false);
        TabCommon.Group = filters;
        TabUncommon.Group = filters;
        TabRare.Group = filters;
        TabAll.Group = filters;
        TabCommon.Pressed = true;

        TabCommon.OnPressed += _ => SetFilter(CFRarity.Common);
        TabUncommon.OnPressed += _ => SetFilter(CFRarity.Uncommon);
        TabRare.OnPressed += _ => SetFilter(CFRarity.Rare);
        TabAll.OnPressed += _ => SetFilter(null);

        CloseButton.OnPressed += _ => OnClosed?.Invoke();
        CancelButton.OnPressed += _ => OnClosed?.Invoke();
        AcceptButton.OnPressed += _ => OnAccept?.Invoke();
        PrdButton.OnPressed += _ => OnPrdPressed?.Invoke();
    }

    public void Show(string title, string allLabel, IReadOnlyList<Pf2eListEntry> entries, string? selectedId)
    {
        TitleLabel.Text = title;
        TabAll.Text = allLabel;
        _entries.Clear();
        _entries.AddRange(entries);
        _selectedId = selectedId;

        var selected = entries.FirstOrDefault(entry => entry.Id == selectedId);
        _suppress = true;
        if (selected != null && selected.Rarity != CFRarity.Common)
        {
            _filter = null;
            TabAll.Pressed = true;
        }
        else
        {
            _filter = CFRarity.Common;
            TabCommon.Pressed = true;
        }

        _suppress = false;
        RebuildList();
    }

    private void SetFilter(CFRarity? rarity)
    {
        if (_suppress)
            return;

        _filter = rarity;
        RebuildList();
    }

    private void RebuildList()
    {
        foreach (var child in OptionList.Children)
        {
            if (child is Button button)
                button.Group = null;
        }

        OptionList.RemoveAllChildren();
        _listGroup = new ButtonGroup();

        var shown = 0;
        foreach (var entry in _entries)
        {
            if (_filter != null && entry.Rarity != _filter)
                continue;

            shown++;
            var itemButton = new Button
            {
                Text = entry.Name,
                ToggleMode = true,
                HorizontalExpand = true,
                Group = _listGroup,
            };

            var captured = entry;
            itemButton.OnPressed += _ =>
            {
                itemButton.Pressed = true;
                Select(captured);
            };

            if (entry.Id == _selectedId)
                itemButton.Pressed = true;

            OptionList.AddChild(itemButton);
        }

        if (shown == 0)
        {
            OptionList.AddChild(new Label
            {
                Text = Loc.GetString("cf-character-builder-filter-empty"),
            });
        }

        var selected = _entries.FirstOrDefault(entry => entry.Id == _selectedId);
        ShowDetails(selected);
        AcceptButton.Disabled = selected == null;
    }

    private void Select(Pf2eListEntry entry)
    {
        _selectedId = entry.Id;
        ShowDetails(entry);
        AcceptButton.Disabled = false;
        OnEntrySelected?.Invoke(entry.Id);
    }

    private void ShowDetails(Pf2eListEntry? entry)
    {
        if (entry == null)
        {
            NameLabel.Text = Loc.GetString("cf-character-builder-select-prompt");
            SetLine(TraitsLabel, null);
            DescriptionLabel.Visible = false;
            SetLine(HpLabel, null);
            SetLine(SizeLabel, null);
            SetLine(SpeedLabel, null);
            SetLine(BoostsLabel, null);
            SetLine(FlawsLabel, null);
            SetLine(LanguagesLabel, null);
            RulesLabel.Visible = false;
            return;
        }

        NameLabel.Text = entry.Name;
        SetLine(TraitsLabel, entry.Traits);
        var hasDescription = !string.IsNullOrWhiteSpace(entry.Description);
        DescriptionLabel.Visible = hasDescription;
        if (hasDescription)
            DescriptionLabel.SetMessage(entry.Description);

        SetLine(HpLabel, entry.HitPoints);
        SetLine(SizeLabel, entry.Size);
        SetLine(SpeedLabel, entry.Speed);
        SetLine(BoostsLabel, entry.Boosts);
        SetLine(FlawsLabel, entry.Flaws);
        SetLine(LanguagesLabel, entry.Languages);

        var rules = entry.Rules;
        RulesLabel.Visible = !string.IsNullOrWhiteSpace(rules);
        if (RulesLabel.Visible)
            RulesLabel.SetMessage(rules ?? string.Empty);
    }

    private static void SetLine(Label label, string? text)
    {
        var visible = !string.IsNullOrWhiteSpace(text);
        label.Visible = visible;
        label.Text = visible ? text : string.Empty;
    }
}

public sealed class Pf2eListEntry
{
    public required string Id { get; init; }
    public required string Name { get; init; }
    public CFRarity Rarity { get; init; }
    public string? Traits { get; init; }
    public string Description { get; init; } = "";
    public string? HitPoints { get; init; }
    public string? Size { get; init; }
    public string? Speed { get; init; }
    public string? Boosts { get; init; }
    public string? Flaws { get; init; }
    public string? Languages { get; init; }
    public string? Rules { get; init; }
}
