using System.Linq;
using System.Numerics;
using System.Text;
using Content.Shared.CF.Character;
using Content.Shared.CF.Preferences;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.CF.Lobby.UI.CharacterBuilder;

[GenerateTypedNameReferences]
public sealed partial class SpellsTab : BoxContainer
{
    private const int SlotColumnWidth = 280;

    private HumanoidCharacterProfile? _profile;
    private IPrototypeManager? _prototypes;
    private Action<CFCharacterBuildData>? _onChanged;

    public SpellsTab()
    {
        RobustXamlLoader.Load(this);
        BonusSpellsButton.OnPressed += _ => AddBonusSpell();
        PrintButton.OnPressed += _ => PrintSpells();
    }

    public void Rebuild(
        HumanoidCharacterProfile? profile,
        IPrototypeManager prototypes,
        Action<CFCharacterBuildData> onChanged)
    {
        _profile = profile;
        _prototypes = prototypes;
        _onChanged = onChanged;

        var build = profile?.CFBuild ?? new CFCharacterBuildData();
        CFClassPrototype? cls = null;
        if (build.Class != null)
            prototypes.TryIndex(build.Class.Value, out cls);

        FillSummary(profile, prototypes, build, cls);
        SpellRanks.RemoveAllChildren();

        foreach (var rank in CFSpellSlots.ForClass(cls))
            SpellRanks.AddChild(BuildRank(build, rank.Rank, rank.Count));

        var bonus = build.Spells
            .Where(spell => spell.Rank == CFSpellSlots.BonusRank)
            .OrderBy(spell => spell.Index)
            .ToList();
        if (bonus.Count > 0)
            SpellRanks.AddChild(BuildBonus(bonus));
    }

    private void FillSummary(
        HumanoidCharacterProfile? profile,
        IPrototypeManager prototypes,
        CFCharacterBuildData build,
        CFClassPrototype? cls)
    {
        var casting = cls?.Spellcasting;
        if (profile == null || casting == null)
        {
            DcLabel.Text = Loc.GetString("cf-spell-dc", ("dc", "—"), ("attack", "—"));
            AbilityLabel.Text = Loc.GetString("cf-spell-ability-line", ("ability", "—"), ("mod", "—"));
            ProfLabel.Text = Loc.GetString("cf-spell-prof", ("prof", "—"));
            ItemLabel.Text = Loc.GetString("cf-spell-item", ("item", "—"));
            FillFocus(0);
            return;
        }

        var sheet = CFAttributeMath.Snapshot(prototypes, profile);
        var mod = sheet.Modifiers[casting.Ability];
        var prof = CFAttributeMath.ProficiencyBonus(sheet.Level, trained: true);
        const int item = 0;
        DcLabel.Text = Loc.GetString("cf-spell-dc",
            ("dc", (10 + mod + prof + item).ToString()),
            ("attack", CFAbilityScores.FormatModifier(mod + prof + item)));
        AbilityLabel.Text = Loc.GetString("cf-spell-ability-line",
            ("ability", Loc.GetString($"cf-ability-short-{casting.Ability.ToString().ToLowerInvariant()}")),
            ("mod", CFAbilityScores.FormatModifier(mod)));
        ProfLabel.Text = Loc.GetString("cf-spell-prof", ("prof", CFAbilityScores.FormatModifier(prof)));
        ItemLabel.Text = Loc.GetString("cf-spell-item", ("item", CFAbilityScores.FormatModifier(item)));
        FillFocus(casting.FocusPoints);
    }

    private void FillFocus(int points)
    {
        FocusPips.RemoveAllChildren();
        for (var i = 0; i < 3; i++)
        {
            FocusPips.AddChild(new Label
            {
                Text = i < points ? "●" : "○",
                FontColorOverride = i < points ? Color.FromHex("#e6e6e6") : Color.FromHex("#5c6270"),
                Margin = new Thickness(1, 0),
            });
        }
    }

    private Control BuildRank(CFCharacterBuildData build, int rank, int count)
    {
        var block = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };

        block.AddChild(ColumnHeader());
        block.AddChild(RankTitle(rank));

        for (var index = 0; index < count; index++)
        {
            var pick = Find(build, rank, index);
            block.AddChild(SlotRow(rank, index, pick));
        }

        return block;
    }

    private Control BuildBonus(List<CFSpellPick> picks)
    {
        var block = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };

        block.AddChild(ColumnHeader());
        block.AddChild(RankTitle(CFSpellSlots.BonusRank));
        foreach (var pick in picks)
            block.AddChild(SlotRow(pick.Rank, pick.Index, pick));
        return block;
    }

    private BoxContainer ColumnHeader()
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };
        row.AddChild(new Control { MinWidth = SlotColumnWidth });
        row.AddChild(Rule());
        row.AddChild(HeaderLabel(Loc.GetString("cf-spell-col-duration")));
        row.AddChild(Rule());
        row.AddChild(HeaderLabel(Loc.GetString("cf-spell-col-range")));
        row.AddChild(Rule());
        row.AddChild(HeaderLabel(Loc.GetString("cf-spell-col-save")));
        row.AddChild(Rule());
        row.AddChild(HeaderLabel(Loc.GetString("cf-spell-col-area")));
        return row;
    }

    private static Control RankTitle(int rank)
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };
        row.AddChild(new Control { MinWidth = SlotColumnWidth });
        var title = rank switch
        {
            0 => Loc.GetString("cf-spell-rank-cantrips"),
            CFSpellSlots.BonusRank => Loc.GetString("cf-spell-rank-bonus"),
            _ => Loc.GetString("cf-spell-rank", ("rank", rank)),
        };
        row.AddChild(new Label
        {
            Text = title,
            HorizontalExpand = true,
            Align = Label.AlignMode.Center,
            StyleClasses = { "LabelHeading" },
            Margin = new Thickness(0, 2, 0, 4),
        });
        return row;
    }

    private Control SlotRow(int rank, int index, CFSpellPick? pick)
    {
        CFSpellPrototype? spell = null;
        if (pick != null && pick.HasSpell && _prototypes != null)
            _prototypes.TryIndex(pick.Spell, out spell);

        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        var slots = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            MinWidth = SlotColumnWidth,
            MaxWidth = SlotColumnWidth,
            SeparationOverride = 4,
        };

        var slot = new Button
        {
            Text = spell?.Name ?? Loc.GetString("cf-spell-not-selected"),
            HorizontalExpand = true,
            ClipText = true,
        };
        var openRank = rank;
        var openIndex = index;
        slot.OnPressed += _ => OpenPicker(openRank, openIndex);
        slots.AddChild(slot);
        row.AddChild(slots);

        row.AddChild(Rule());
        row.AddChild(StatLabel(spell?.Duration));
        row.AddChild(Rule());
        row.AddChild(StatLabel(spell?.Range));
        row.AddChild(Rule());
        row.AddChild(StatLabel(spell?.Defense));
        row.AddChild(Rule());
        row.AddChild(StatLabel(AreaText(spell)));
        return row;
    }

    private void OpenPicker(int rank, int index)
    {
        if (_prototypes == null || _onChanged == null || _profile == null)
            return;

        var build = _profile.CFBuild;
        var pick = Find(build, rank, index);
        var tradition = CFSpellTradition.Arcane;
        if (build.Class != null
            && _prototypes.TryIndex(build.Class.Value, out CFClassPrototype? cls)
            && cls.Spellcasting != null)
            tradition = cls.Spellcasting.Tradition;

        if (pick != null && pick.HasSpell && _prototypes.TryIndex(pick.Spell, out CFSpellPrototype? current) && current.Traditions.Count > 0)
            tradition = current.Traditions[0];

        var selected = pick != null && pick.HasSpell ? pick.Spell.Id : null;
        var popup = new SpellSelectionPopup(rank, tradition, _prototypes, selected);
        var capturedRank = rank;
        var capturedIndex = index;
        popup.OnSpellAccepted += id =>
        {
            var next = _profile.CFBuild.Clone();
            Upsert(next, capturedRank, capturedIndex, id, pick?.Expended ?? false);
            _onChanged(next);
        };
        popup.OnSpellCleared += () =>
        {
            var next = _profile.CFBuild.Clone();
            next.Spells.RemoveAll(spell => spell.Rank == capturedRank && spell.Index == capturedIndex);
            _onChanged(next);
        };
        popup.OpenCentered();
    }

    private void AddBonusSpell()
    {
        if (_profile == null)
            return;

        var nextIndex = 0;
        foreach (var spell in _profile.CFBuild.Spells)
        {
            if (spell.Rank == CFSpellSlots.BonusRank && spell.Index >= nextIndex)
                nextIndex = spell.Index + 1;
        }

        OpenPicker(CFSpellSlots.BonusRank, nextIndex);
    }

    private void PrintSpells()
    {
        if (_profile == null || _prototypes == null)
            return;

        var text = new StringBuilder();
        foreach (var pick in _profile.CFBuild.Spells.OrderBy(spell => spell.Rank).ThenBy(spell => spell.Index))
        {
            if (!pick.HasSpell || !_prototypes.TryIndex(pick.Spell, out CFSpellPrototype? spell))
                continue;

            var rank = pick.Rank == 0
                ? Loc.GetString("cf-spell-rank-cantrips")
                : pick.Rank < 0
                    ? Loc.GetString("cf-spell-rank-bonus")
                    : Loc.GetString("cf-spell-rank", ("rank", pick.Rank));
            text.Append(rank).Append(": ").AppendLine(spell.Name);
        }

        if (text.Length == 0)
            text.Append(Loc.GetString("cf-spell-print-empty"));

        IoCManager.Resolve<IClipboardManager>().SetText(text.ToString().TrimEnd());
    }

    private static CFSpellPick? Find(CFCharacterBuildData build, int rank, int index)
    {
        foreach (var spell in build.Spells)
        {
            if (spell.Rank == rank && spell.Index == index)
                return spell;
        }

        return null;
    }

    private static void Upsert(CFCharacterBuildData build, int rank, int index, string spellId, bool expended)
    {
        var pick = Find(build, rank, index);
        if (pick == null)
        {
            build.Spells.Add(new CFSpellPick
            {
                Rank = rank,
                Index = index,
                Spell = spellId,
                Expended = expended,
            });
            return;
        }

        pick.Spell = spellId;
        pick.Expended = expended;
    }

    private static string? AreaText(CFSpellPrototype? spell)
    {
        if (spell == null)
            return null;

        if (string.IsNullOrWhiteSpace(spell.Area))
            return string.IsNullOrWhiteSpace(spell.Targets) ? null : spell.Targets;

        if (string.IsNullOrWhiteSpace(spell.Targets))
            return spell.Area;

        return $"{spell.Area}; {spell.Targets}";
    }

    private static Label HeaderLabel(string text)
    {
        return new Label
        {
            Text = text,
            HorizontalExpand = true,
            Align = Label.AlignMode.Center,
            FontColorOverride = Color.FromHex("#9aa0aa"),
        };
    }

    private static Label StatLabel(string? text)
    {
        return new Label
        {
            Text = text ?? string.Empty,
            HorizontalExpand = true,
            ClipText = true,
            Align = Label.AlignMode.Center,
            VerticalAlignment = VAlignment.Center,
        };
    }

    private static Control Rule()
    {
        return new PanelContainer
        {
            MinSize = new Vector2(1, 16),
            VerticalExpand = true,
            Margin = new Thickness(2, 2),
            PanelOverride = new StyleBoxFlat(Color.FromHex("#3a4050")),
        };
    }
}
