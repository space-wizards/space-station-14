using System.Linq;
using System.Numerics;
using System.Text;
using Content.Shared.CF.Character;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;
using static Robust.Client.UserInterface.Controls.BoxContainer;

namespace Content.Client.CF.Lobby.UI.CharacterBuilder;

[GenerateTypedNameReferences]
public sealed partial class SpellSelectionPopup : DefaultWindow
{
    public event Action<string>? OnSpellAccepted;
    public event Action? OnSpellCleared;

    private readonly int? _rank;
    private readonly IPrototypeManager _prototypes;
    private readonly List<CFSpellPrototype> _spells = new();
    private CFSpellTradition _tradition;
    private string? _selectedId;
    private bool _suppress;
    private ButtonGroup _listGroup = new();

    public SpellSelectionPopup(int? rank, CFSpellTradition tradition, IPrototypeManager prototypes, string? selectedId)
    {
        RobustXamlLoader.Load(this);
        _rank = rank;
        _tradition = tradition;
        _prototypes = prototypes;
        _selectedId = selectedId;

        Title = rank switch
        {
            0 => Loc.GetString("cf-spell-select-cantrip"),
            null or CFSpellSlots.BonusRank => Loc.GetString("cf-spell-select-any"),
            _ => Loc.GetString("cf-spell-select-rank", ("rank", rank)),
        };

        foreach (var spell in prototypes.EnumeratePrototypes<CFSpellPrototype>())
            _spells.Add(spell);
        _spells.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));

        var filters = new ButtonGroup(isNoneSetAllowed: false);
        TabArcane.Group = filters;
        TabDivine.Group = filters;
        TabOccult.Group = filters;
        TabPrimal.Group = filters;

        TabArcane.OnPressed += _ => SetTradition(CFSpellTradition.Arcane);
        TabDivine.OnPressed += _ => SetTradition(CFSpellTradition.Divine);
        TabOccult.OnPressed += _ => SetTradition(CFSpellTradition.Occult);
        TabPrimal.OnPressed += _ => SetTradition(CFSpellTradition.Primal);

        AcceptButton.OnPressed += _ => Accept();
        CancelButton.OnPressed += _ => Close();
        ClearButton.OnPressed += _ =>
        {
            OnSpellCleared?.Invoke();
            Close();
        };
        PrdButton.OnPressed += _ => OpenPrd();

        _suppress = true;
        PressTradition(tradition);
        _suppress = false;
        RebuildList();
    }

    private void SetTradition(CFSpellTradition tradition)
    {
        if (_suppress)
            return;

        _tradition = tradition;
        RebuildList();
    }

    private void PressTradition(CFSpellTradition tradition)
    {
        // The group does not allow every tab to be off. Pressing the chosen tab
        // clears the others. Setting Pressed = false on the current tab throws.
        var tab = tradition switch
        {
            CFSpellTradition.Divine => TabDivine,
            CFSpellTradition.Occult => TabOccult,
            CFSpellTradition.Primal => TabPrimal,
            _ => TabArcane,
        };
        tab.Pressed = true;
    }

    private void RebuildList()
    {
        foreach (var child in SpellList.Children)
        {
            if (child is Button button)
                button.Group = null;
        }

        SpellList.RemoveAllChildren();
        _listGroup = new ButtonGroup();

        var shown = 0;
        foreach (var spell in _spells)
        {
            if (!Matches(spell))
                continue;

            shown++;
            SpellList.AddChild(SpellRow(spell));
        }

        if (shown == 0)
        {
            SpellList.AddChild(new Label
            {
                Text = Loc.GetString("cf-character-builder-filter-empty"),
                Margin = new Thickness(4),
            });
        }

        CFSpellPrototype? selected = null;
        if (_selectedId != null)
        {
            foreach (var spell in _spells)
            {
                if (spell.ID == _selectedId && Matches(spell))
                {
                    selected = spell;
                    break;
                }
            }
        }

        if (selected == null)
            _selectedId = null;

        ShowDetails(selected);
        AcceptButton.Disabled = selected == null;
    }

    private bool Matches(CFSpellPrototype spell)
    {
        if (!spell.HasTradition(_tradition))
            return false;

        if (_rank is null or CFSpellSlots.BonusRank)
            return true;

        if (_rank == 0)
            return spell.Rank == 0;

        return spell.Rank > 0 && spell.Rank <= _rank.Value;
    }

    private Button SpellRow(CFSpellPrototype spell)
    {
        var button = new Button
        {
            ToggleMode = true,
            HorizontalExpand = true,
            Group = _listGroup,
            MinHeight = 32,
        };
        button.Label.Visible = false;

        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
            Margin = new Thickness(6, 2),
        };

        var icon = new PanelContainer
        {
            MinSize = new Vector2(22, 22),
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat(Color.FromHex("#2a3140")),
        };
        icon.AddChild(new Label
        {
            Text = "✦",
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
        });
        row.AddChild(icon);

        row.AddChild(new Label
        {
            Text = spell.Name,
            HorizontalExpand = true,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
        });
        row.AddChild(new Label
        {
            Text = CFSpellSlots.ActionSymbols(spell.ActionCost),
            VerticalAlignment = VAlignment.Center,
            MinWidth = 52,
        });

        var badge = new PanelContainer
        {
            MinSize = new Vector2(28, 22),
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat(Color.FromHex("#2a3140")),
        };
        badge.AddChild(new Label
        {
            Text = spell.Rank.ToString(),
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
        });
        row.AddChild(badge);
        IgnoreMouse(row);
        button.AddChild(row);

        if (spell.ID == _selectedId)
            button.Pressed = true;

        button.OnPressed += _ =>
        {
            button.Pressed = true;
            _selectedId = spell.ID;
            ShowDetails(spell);
            AcceptButton.Disabled = false;
        };
        return button;
    }

    private void ShowDetails(CFSpellPrototype? spell)
    {
        TraitRow.RemoveAllChildren();
        if (spell == null)
        {
            DetailName.Text = Loc.GetString("cf-character-builder-select-prompt");
            DetailRank.Text = string.Empty;
            DetailBody.Text = string.Empty;
            return;
        }

        DetailName.Text = $"{spell.Name}  {CFSpellSlots.ActionSymbols(spell.ActionCost)}";
        DetailRank.Text = spell.Rank == 0
            ? Loc.GetString("cf-spell-rank-cantrips")
            : Loc.GetString("cf-spell-rank", ("rank", spell.Rank));

        if (spell.Rarity != CFRarity.Common)
            TraitRow.AddChild(Chip(Loc.GetString(spell.Rarity == CFRarity.Uncommon
                ? "cf-character-builder-filter-uncommon"
                : "cf-character-builder-filter-rare"), Color.FromHex("#6a5a32")));

        if (spell.Rank == 0)
            TraitRow.AddChild(Chip(Loc.GetString("cf-spell-trait-cantrip"), Color.FromHex("#3d5270")));

        foreach (var trait in spell.Traits)
        {
            if (spell.Rank == 0 && trait.Id == "Cantrip")
                continue;
            TraitRow.AddChild(Chip(trait.Id, Color.FromHex("#3d5270")));
        }

        var body = new StringBuilder();
        Line(body, "cf-spell-detail-cast", spell.Components);
        Line(body, "cf-spell-detail-range", spell.Range);
        Line(body, "cf-spell-detail-area", spell.Area);
        Line(body, "cf-spell-detail-targets", spell.Targets);
        Line(body, "cf-spell-detail-duration", spell.Duration);
        Line(body, "cf-spell-detail-defense", spell.Defense);
        if (!string.IsNullOrWhiteSpace(spell.Summary))
        {
            body.AppendLine();
            body.AppendLine(FormattedMessage.EscapeText(spell.Summary));
        }

        Degree(body, "cf-spell-detail-crit-success", spell.CriticalSuccess);
        Degree(body, "cf-spell-detail-success", spell.Success);
        Degree(body, "cf-spell-detail-failure", spell.Failure);
        Degree(body, "cf-spell-detail-crit-failure", spell.CriticalFailure);
        if (!string.IsNullOrWhiteSpace(spell.Heightened))
        {
            body.AppendLine();
            body.Append("[bold]").Append(FormattedMessage.EscapeText(Loc.GetString("cf-spell-detail-heightened"))).Append("[/bold] ");
            body.AppendLine(FormattedMessage.EscapeText(spell.Heightened));
        }

        if (_rank is > 0 && spell.Rank < _rank)
        {
            body.AppendLine();
            body.Append(FormattedMessage.EscapeText(Loc.GetString("cf-spell-detail-heightened-slot", ("rank", _rank))));
        }

        // Text parses markup. SetMessage(string) stores the tags as literal text.
        DetailBody.Text = body.ToString().Trim();
    }

    private static void Line(StringBuilder body, string label, string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return;

        body.Append("[bold]").Append(FormattedMessage.EscapeText(Loc.GetString(label))).Append("[/bold] ");
        body.AppendLine(FormattedMessage.EscapeText(value));
    }

    private static void Degree(StringBuilder body, string label, string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return;

        body.Append("[bold]").Append(FormattedMessage.EscapeText(Loc.GetString(label))).Append("[/bold] ");
        body.AppendLine(FormattedMessage.EscapeText(value));
    }

    private static Control Chip(string text, Color color)
    {
        var panel = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(color),
            Margin = new Thickness(0, 0, 0, 2),
        };
        panel.AddChild(new Label
        {
            Text = text,
            Margin = new Thickness(6, 1, 6, 1),
        });
        return panel;
    }

    private static void IgnoreMouse(Control control)
    {
        control.MouseFilter = Control.MouseFilterMode.Ignore;
        foreach (var child in control.Children)
            IgnoreMouse(child);
    }

    private void Accept()
    {
        if (_selectedId == null)
            return;

        OnSpellAccepted?.Invoke(_selectedId);
        Close();
    }

    private void OpenPrd()
    {
        string? name = null;
        if (_selectedId != null && _prototypes.TryIndex<CFSpellPrototype>(_selectedId, out var spell))
            name = spell.Name;

        var url = string.IsNullOrWhiteSpace(name)
            ? "https://2e.aonprd.com/Spells.aspx"
            : "https://2e.aonprd.com/Search.aspx?q=" + Uri.EscapeDataString(name);
        IoCManager.Resolve<IUriOpener>().OpenUri(new Uri(url));
    }
}
