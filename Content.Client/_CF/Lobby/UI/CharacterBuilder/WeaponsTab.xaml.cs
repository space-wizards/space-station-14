using Content.Shared.Preferences;
using Content.Shared.Preferences.Loadouts;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Player;
using Robust.Shared.Prototypes;

namespace Content.Client.CF.Lobby.UI.CharacterBuilder;

[GenerateTypedNameReferences]
public sealed partial class WeaponsTab : BoxContainer
{
    private readonly LoadoutCategoryTabController _controller;

    public WeaponsTab()
    {
        RobustXamlLoader.Load(this);
        _controller = new LoadoutCategoryTabController(WeaponsGroups, LoadoutEditorTabs.Weapons);
    }

    public void Rebuild(
        HumanoidCharacterProfile? profile,
        JobPrototype? jobOverride,
        ICommonSession? session,
        IDependencyCollection? collection,
        IPrototypeManager prototypes,
        Func<HumanoidCharacterProfile?> getProfile,
        Action<HumanoidCharacterProfile> onChanged)
    {
        _controller.Rebuild(profile, jobOverride, session, collection, prototypes, getProfile, onChanged);
    }

    public void Apply(HumanoidCharacterProfile profile)
    {
        _controller.Apply(profile);
    }
}
