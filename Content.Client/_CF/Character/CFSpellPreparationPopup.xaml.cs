using Content.Shared.CF.Character;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;

namespace Content.Client.CF.Character;

[GenerateTypedNameReferences]
public sealed partial class CFSpellPreparationPopup : DefaultWindow
{
    public event Action<string>? OnAdd;
    public event Action<string>? OnDragSpell;

    private List<CFSheetSpell> _spells = new();
    private Func<int, bool>? _hasRoom;

    public CFSpellPreparationPopup()
    {
        RobustXamlLoader.Load(this);
        SearchInput.OnTextChanged += _ => BuildRows();
    }

    public void SetRoom(Func<int, bool> hasRoom)
    {
        _hasRoom = hasRoom;
    }

    public void SetSpells(List<CFSheetSpell> spells)
    {
        _spells = spells;
        BuildRows();
    }

    public void RoomsChanged()
    {
        BuildRows();
    }

    private void BuildRows()
    {
        SpellRows.RemoveAllChildren();
        var search = SearchInput.Text.Trim();
        var any = false;
        for (var rank = 0; rank <= 10; rank++)
        {
            var listed = false;
            foreach (var spell in _spells)
            {
                if (spell.Rank != rank)
                    continue;

                if (search.Length > 0 && spell.Name.IndexOf(search, StringComparison.CurrentCultureIgnoreCase) < 0)
                    continue;

                if (!listed)
                {
                    listed = true;
                    any = true;
                    SpellRows.AddChild(new Label
                    {
                        Text = CFSpellsTab.RankTitle(rank),
                        FontColorOverride = Color.FromHex("#E6C15A"),
                        Margin = new Thickness(0, 6, 0, 2),
                    });
                }

                SpellRows.AddChild(Row(spell));
            }
        }

        if (!any)
        {
            SpellRows.AddChild(new Label
            {
                Text = Loc.GetString("cf-sheet-spells-empty-category"),
            });
        }
    }

    private Control Row(CFSheetSpell spell)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        var handle = new PanelContainer
        {
            MinWidth = 36,
            MouseFilter = Control.MouseFilterMode.Stop,
            ToolTip = Loc.GetString("cf-sheet-spells-drag"),
        };
        handle.AddChild(new Label
        {
            Text = "⋮⋮",
            HorizontalAlignment = Control.HAlignment.Center,
            VerticalAlignment = Control.VAlignment.Center,
        });
        var spellId = spell.Id;
        handle.OnKeyBindDown += args =>
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            args.Handle();
            OnDragSpell?.Invoke(spellId);
        };
        row.AddChild(handle);

        row.AddChild(new Label
        {
            Text = CFSpellSlots.ActionSymbols(spell.ActionCost) + "  " + spell.Name,
            HorizontalExpand = true,
            ClipText = true,
        });

        var add = new Button
        {
            Text = Loc.GetString("cf-sheet-spells-add"),
            MinWidth = 64,
            Disabled = _hasRoom != null && !_hasRoom(spell.Rank),
        };
        add.OnPressed += _ => OnAdd?.Invoke(spellId);
        row.AddChild(add);
        return row;
    }
}
