[GenerateTypedNameReferences]
public sealed partial class CFSpellsTab : BoxContainer
{
    public event Action? OnCast;

    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IUserInterfaceManager _ui = default!;
    [Dependency] private IInputManager _input = default!;

    private readonly List<CFSheetSpell> _known = new();
    private readonly Dictionary<int, List<string?>> _slots = new();

    private EntityUid _entity = EntityUid.Invalid;
    private SheetSpellCategory _category = SheetSpellCategory.Known;
    private bool _prepared;
    private bool _slotsReady;
    private string _signature = "";
    private CFSpellPreparationPopup? _popup;
    private string? _dragSpell;
    private Label? _ghost;
    private CFSpellSlotTarget? _hot;

    public CFSpellsTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var group = new ButtonGroup();
        KnownButton.Group = group;
        RitualsButton.Group = group;
        ActivationsButton.Group = group;
        KnownButton.Pressed = true;

        KnownButton.OnPressed += args =>
        {
            if (args.Button.Pressed)
                Show(SheetSpellCategory.Known);
        };
        RitualsButton.OnPressed += args =>
        {
            if (args.Button.Pressed)
                Show(SheetSpellCategory.Rituals);
        };
        ActivationsButton.OnPressed += args =>
        {
            if (args.Button.Pressed)
                Show(SheetSpellCategory.Activations);
        };
        PrepareButton.OnPressed += _ => TogglePreparation();
    }

    public void Update(EntityUid entity)
    {
        if (entity != _entity)
        {
            CancelDrag();
            _popup?.Close();
            _entity = entity;
            _slotsReady = false;
            _slots.Clear();
        }

        if (!_entities.EntityExists(entity))
            return;

        Collect(entity);
        ReadCaster(entity);
        if (_prepared && !_slotsReady)
        {
            SeedSlots();
            _slotsReady = true;
        }

        Rebuild();
        _signature = Signature();
        _popup?.RoomsChanged();
    }

    public void FrameUpdate()
    {
        if (_dragSpell != null)
        {
            MoveGhost();
            if (!_input.IsKeyDown(Keyboard.Key.MouseLeft))
                FinishDrag();
            return;
        }

        if (_entity == EntityUid.Invalid || !_entities.EntityExists(_entity))
            return;

        var signature = Signature();
        if (signature != _signature)
            Update(_entity);
    }

    public void CancelDrag()
    {
        _dragSpell = null;
        ClearHot();
        if (_ghost == null)
            return;

        _ghost.Orphan();
        _ghost = null;
    }

    public static string RankTitle(int rank)
    {
        if (rank <= 0)
            return Loc.GetString("cf-spell-rank-cantrips");

        var suffix = rank % 10 == 1 && rank % 100 != 11 ? "st"
            : rank % 10 == 2 && rank % 100 != 12 ? "nd"
            : rank % 10 == 3 && rank % 100 != 13 ? "rd"
            : "th";
        return Loc.GetString("cf-sheet-spells-rank", ("rank", rank), ("suffix", suffix));
    }

    private void Show(SheetSpellCategory category)
    {
        _category = category;
        Rebuild();
    }

    private void TogglePreparation()
    {
        if (_popup != null && _popup.IsOpen)
        {
            _popup.Close();
            return;
        }

        _popup = new CFSpellPreparationPopup();
        _popup.SetRoom(HasRoom);
        _popup.SetSpells(_known);
        _popup.OnAdd += TryPrepare;
        _popup.OnDragSpell += BeginDrag;
        _popup.OnClose += () => _popup = null;
        _popup.OpenCentered();
    }

    private void BeginDrag(string spellId)
    {
        CancelDrag();
        if (Find(spellId) == null)
            return;

        _dragSpell = spellId;
        _ghost = new Label
        {
            Text = Find(spellId)!.Name,
            FontColorOverride = Color.FromHex("#E6C15A"),
            MouseFilter = Control.MouseFilterMode.Ignore,
        };
        _ui.PopupRoot.AddChild(_ghost);
        MoveGhost();
    }

    private void MoveGhost()
    {
        if (_ghost == null)
            return;

        LayoutContainer.SetPosition(_ghost, _ui.MousePositionScaled.Position);
        var spell = Find(_dragSpell);
        var slot = FindSlot(_ui.MouseGetControl(_input.MouseScreenPosition));
        var valid = spell != null && slot != null && slot.DropEnabled && slot.Rank == spell.Rank;
        if (_hot == slot)
            return;

        ClearHot();
        if (!valid || slot == null)
            return;

        _hot = slot;
        _hot.Modulate = new Color(90, 150, 210);
    }

    private void FinishDrag()
    {
        var spell = Find(_dragSpell);
        var slot = _hot;
        CancelDrag();
        if (spell == null || slot == null || !slot.DropEnabled || slot.Rank != spell.Rank)
            return;

        if (!_slots.TryGetValue(slot.Rank, out var row) || slot.Index < 0 || slot.Index >= row.Count)
            return;

        row[slot.Index] = spell.Id;
        Rebuild();
        _popup?.RoomsChanged();
    }

    private void TryPrepare(string spellId)
    {
        var spell = Find(spellId);
        if (spell == null || !_slots.TryGetValue(spell.Rank, out var row))
            return;

        for (var i = 0; i < row.Count; i++)
        {
            if (row[i] != null)
                continue;

            row[i] = spellId;
            Rebuild();
            _popup?.RoomsChanged();
            return;
        }
    }

    private bool HasRoom(int rank)
    {
        if (!_prepared || !_slots.TryGetValue(rank, out var row))
            return false;

        foreach (var id in row)
        {
            if (id == null)
                return true;
        }

        return false;
    }

    private void Cast(CFSheetSpell spell)
    {
        if (!_entities.TryGetComponent<ActionComponent>(spell.Action, out var action))
            return;

        _ui.GetUIController<ActionUIController>().UseAction((spell.Action, action));
        OnCast?.Invoke();
    }

    private void Rebuild()
    {
        _hot = null;
        RankRows.RemoveAllChildren();

        if (_category == SheetSpellCategory.Known && _prepared)
        {
            var any = false;
            foreach (var pair in _slots)
            {
                any = true;
                RankRows.AddChild(RankSection(pair.Key, pair.Value));
            }

            if (!any)
                RankRows.AddChild(EmptyLabel("cf-sheet-spells-none"));
            return;
        }

        var shown = new List<CFSheetSpell>();
        foreach (var spell in _known)
        {
            if (_category == SheetSpellCategory.Rituals && !spell.Ritual)
                continue;
            if (_category == SheetSpellCategory.Activations && !spell.Activation)
                continue;
            shown.Add(spell);
        }

        if (shown.Count == 0)
        {
            var key = _known.Count == 0 ? "cf-sheet-spells-none" : "cf-sheet-spells-empty-category";
            RankRows.AddChild(EmptyLabel(key));
            return;
        }

        var rank = int.MinValue;
        List<CFSheetSpell>? group = null;
        foreach (var spell in shown)
        {
            if (group == null || spell.Rank != rank)
            {
                if (group != null)
                    RankRows.AddChild(KnownSection(rank, group));

                rank = spell.Rank;
                group = new List<CFSheetSpell>();
            }

            group.Add(spell);
        }

        if (group != null)
            RankRows.AddChild(KnownSection(rank, group));
    }

    private Control RankSection(int rank, List<string?> slots)
    {
        var body = Section(rank, slots.Count);
        for (var i = 0; i < slots.Count; i++)
        {
            var slot = new CFSpellSlotTarget
            {
                Rank = rank,
                Index = i,
                DropEnabled = true,
                HorizontalExpand = true,
            };
            var id = slots[i];
            var spell = id == null ? null : Find(id);
            if (spell == null)
                slot.AddChild(EmptyRow());
            else
                slot.AddChild(SpellRow(spell, CanCast(rank)));
            body.AddChild(slot);
        }

        return Wrap(body);
    }

    private Control KnownSection(int rank, List<CFSheetSpell> spells)
    {
        var max = SlotCount(rank);
        var body = Section(rank, max > 0 ? max : spells.Count);
        var canCast = CanCast(rank);
        foreach (var spell in spells)
            body.AddChild(SpellRow(spell, canCast));
        return Wrap(body);
    }

    private BoxContainer Section(int rank, int max)
    {
        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(4, 2),
        };
        header.AddChild(new Label
        {
            Text = RankTitle(rank),
            FontColorOverride = Color.FromHex("#E6C15A"),
            HorizontalExpand = true,
        });
        header.AddChild(new Label
        {
            Text = Loc.GetString("cf-sheet-spells-slots", ("remaining", Math.Max(0, max - Spent(rank))), ("max", max)),
        });
        body.AddChild(header);
        body.AddChild(ColumnHeader());
        return body;
    }

    private static Control Wrap(Control body)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
        };
        panel.StyleClasses.Add("BackgroundDark");
        panel.AddChild(body);
        return panel;
    }

    private Control SpellRow(CFSheetSpell spell, bool canCast)
    {
        var row = Row();
        row.AddChild(FlexLabel(CFSpellSlots.ActionSymbols(spell.ActionCost) + "  " + spell.Name, gold: true));
        row.AddChild(FixedLabel(string.IsNullOrEmpty(spell.Defense) ? "—" : spell.Defense, 120));
        row.AddChild(FixedLabel(string.IsNullOrEmpty(spell.Range) ? "—" : spell.Range, 140));
        var cast = new Button
        {
            Text = Loc.GetString("cf-sheet-spells-cast"),
            SetWidth = 72,
            MinWidth = 72,
            MaxWidth = 72,
            HorizontalExpand = false,
            Disabled = !canCast,
        };
        var captured = spell;
        cast.OnPressed += _ => Cast(captured);
        row.AddChild(cast);
        return row;
    }

    private Control EmptyRow()
    {
        var row = Row();
        row.AddChild(FlexLabel(Loc.GetString("cf-sheet-spells-empty-slot"), gold: false));
        row.AddChild(FixedLabel("—", 120));
        row.AddChild(FixedLabel("—", 140));
        row.AddChild(new Button
        {
            Text = Loc.GetString("cf-sheet-spells-cast"),
            SetWidth = 72,
            MinWidth = 72,
            MaxWidth = 72,
            HorizontalExpand = false,
            Disabled = true,
        });
        return row;
    }

    private static BoxContainer Row()
    {
        return new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            RectClipContent = true,
            Margin = new Thickness(4),
            SeparationOverride = 8,
        };
    }

    private static Control ColumnHeader()
    {
        var row = Row();
        row.AddChild(FlexLabel(Loc.GetString("cf-sheet-spells-col-name"), gold: false));
        row.AddChild(FixedLabel(Loc.GetString("cf-sheet-spells-col-defense"), 120));
        row.AddChild(FixedLabel(Loc.GetString("cf-sheet-spells-col-range"), 140));
        row.AddChild(FixedLabel("", 72));
        return row;
    }

    private static Label FlexLabel(string text, bool gold)
    {
        return new Label
        {
            Text = text,
            MinWidth = 160,
            HorizontalExpand = true,
            ClipText = true,
            FontColorOverride = gold ? Color.FromHex("#E6C15A") : null,
        };
    }

    private static Label FixedLabel(string text, float width)
    {
        return new Label
        {
            Text = text,
            SetWidth = width,
            MinWidth = width,
            MaxWidth = width,
            HorizontalExpand = false,
            ClipText = true,
        };
    }

    private static Label EmptyLabel(string loc)
    {
        return new Label { Text = Loc.GetString(loc), Margin = new Thickness(4) };
    }

    private void Collect(EntityUid entity)
    {
        _known.Clear();
        if (!_entities.TryGetComponent<ActionsComponent>(entity, out var actions))
            return;

        var seen = new HashSet<string>();
        foreach (var action in _entities.System<SharedActionsSystem>().GetActions(entity, actions))
        {
            if (!_entities.TryGetComponent<CFSpellComponent>(action, out var data))
                continue;

            if (!_prototypes.TryIndex(data.Spell, out CFSpellPrototype? proto))
                continue;

            if (!seen.Add(proto.ID))
                continue;

            _known.Add(new CFSheetSpell
            {
                Id = proto.ID,
                Name = proto.Name,
                Rank = data.Rank,
                Defense = proto.Defense,
                Range = proto.Range,
                ActionCost = proto.ActionCost,
                Action = action.Owner,
                Ritual = HasTrait(proto, "Ritual"),
                Activation = HasTrait(proto, "Focus"),
            });
        }

        _known.Sort(CompareSpells);
    }

    private void ReadCaster(EntityUid entity)
    {
        _prepared = false;
        PrepareButton.Visible = false;
        DcLabel.Text = Loc.GetString("cf-sheet-spells-dc", ("dc", "—"));
        TraditionLabel.Text = "—";
        ProficiencyLabel.Text = "—";

        if (!_entities.TryGetComponent<CFCombatantComponent>(entity, out var combatant))
            return;

        if (combatant.ClassId == null || !_prototypes.TryIndex(combatant.ClassId, out CFClassPrototype? cls) || cls.Spellcasting == null)
            return;

        var casting = cls.Spellcasting;
        _prepared = casting.Prepared;
        PrepareButton.Visible = _prepared;

        var abilityMod = 0;
        if (_entities.TryGetComponent<CFAbilityScoreComponent>(entity, out var abilities))
            abilities.AbilityModifiers.TryGetValue(casting.Ability, out abilityMod);

        var proficiency = CFAttributeMath.ProficiencyBonus(combatant.Level, trained: true);
        DcLabel.Text = Loc.GetString("cf-sheet-spells-dc", ("dc", 10 + abilityMod + proficiency));
        TraditionLabel.Text = Loc.GetString("cf-sheet-spells-tradition", ("tradition", casting.Tradition.ToString()));
        ProficiencyLabel.Text = Loc.GetString("cf-sheet-spells-proficiency", ("rank", Loc.GetString("cf-sheet-spells-trained")));
    }

    private void SeedSlots()
    {
        _slots.Clear();
        foreach (var rank in RankCounts())
        {
            var row = new List<string?>();
            for (var i = 0; i < rank.Value; i++)
                row.Add(null);

            var used = 0;
            foreach (var spell in _known)
            {
                if (spell.Rank != rank.Key || used >= row.Count)
                    continue;

                row[used] = spell.Id;
                used++;
            }

            _slots[rank.Key] = row;
        }
    }

    private List<KeyValuePair<int, int>> RankCounts()
    {
        var ranks = new List<KeyValuePair<int, int>>();
        if (_entities.TryGetComponent<CFSpellbookComponent>(_entity, out var book))
        {
            for (var rank = 0; rank < book.Slots.Count; rank++)
            {
                if (book.Slots[rank] > 0)
                    ranks.Add(new KeyValuePair<int, int>(rank, book.Slots[rank]));
            }

            return ranks;
        }

        return ranks;
    }

    private int SlotCount(int rank)
    {
        if (!_entities.TryGetComponent<CFSpellbookComponent>(_entity, out var book))
            return 0;

        if (rank < 0 || rank >= book.Slots.Count)
            return 0;

        return book.Slots[rank];
    }

    private int Spent(int rank)
    {
        if (rank <= 0 || !_entities.TryGetComponent<CFSpellbookComponent>(_entity, out var book))
            return 0;

        if (rank >= book.Expended.Count)
            return 0;

        return book.Expended[rank];
    }

    private bool CanCast(int rank)
    {
        if (rank <= 0)
            return true;

        var max = SlotCount(rank);
        if (max <= 0)
            return true;

        return Spent(rank) < max;
    }

    private string Signature()
    {
        var spent = "0";
        if (_entities.TryGetComponent<CFSpellbookComponent>(_entity, out var book))
        {
            var parts = new List<string>();
            foreach (var value in book.Expended)
                parts.Add(value.ToString());
            spent = string.Join(",", parts);
        }

        return _entity + ":" + _known.Count + ":" + spent;
    }

    private CFSheetSpell? Find(string? id)
    {
        if (id == null)
            return null;

        foreach (var spell in _known)
        {
            if (spell.Id == id)
                return spell;
        }

        return null;
    }

    private static int CompareSpells(CFSheetSpell left, CFSheetSpell right)
    {
        var rank = left.Rank.CompareTo(right.Rank);
        if (rank != 0)
            return rank;

        return string.Compare(left.Name, right.Name, StringComparison.CurrentCultureIgnoreCase);
    }

    private static bool HasTrait(CFSpellPrototype spell, string id)
    {
        foreach (var trait in spell.Traits)
        {
            if (string.Equals(trait.Id, id, StringComparison.OrdinalIgnoreCase))
                return true;
        }

        return false;
    }

    private static CFSpellSlotTarget? FindSlot(Control? control)
    {
        while (control != null)
        {
            if (control is CFSpellSlotTarget slot)
                return slot;

            control = control.Parent;
        }

        return null;
    }

    private void ClearHot()
    {
        if (_hot != null)
            _hot.Modulate = Color.White;
        _hot = null;
    }

    private enum SheetSpellCategory
    {
        Known,
        Rituals,
        Activations,
    }
}

/// <summary>Drop target for a prepared spell slot. The drag walks up from the control under the cursor.</summary>
public sealed class CFSpellSlotTarget : PanelContainer
{
    public int Rank;
    public int Index;
    public bool DropEnabled;
}
