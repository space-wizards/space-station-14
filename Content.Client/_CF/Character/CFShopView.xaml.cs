[GenerateTypedNameReferences]
public sealed partial class CFShopView : BoxContainer
{
    public event Action? OnAccept;
    public event Action? OnCancel;

    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IPlayerManager _player = default!;

    private IReadOnlyList<CFShopListing> _listings = new List<CFShopListing>();
    private readonly HashSet<string> _cart = new();
    private readonly Dictionary<string, int> _qty = new();
    private readonly List<string> _traits = new();
    private bool _ascending = true;
    private bool _matchAllTraits = true;

    public CFShopView()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _listings = ScanItems();

        SortDropdown.AddItem(Loc.GetString("cf-shop-sort-level"));
        SortDropdown.AddItem(Loc.GetString("cf-shop-sort-name"));
        SortDropdown.AddItem(Loc.GetString("cf-shop-sort-cost"));
        SortDropdown.AddItem(Loc.GetString("cf-shop-sort-rarity"));
        SortDropdown.SelectId(0);
        SortDropdown.OnItemSelected += args =>
        {
            SortDropdown.SelectId(args.Id);
            Refresh();
        };

        SortToggle.Text = Loc.GetString("cf-shop-sort-asc");
        SortToggle.OnPressed += _ =>
        {
            _ascending = !_ascending;
            SortToggle.Text = Loc.GetString(_ascending ? "cf-shop-sort-asc" : "cf-shop-sort-desc");
            Refresh();
        };

        SearchInput.OnTextChanged += _ => Refresh();
        TraitInput.OnTextEntered += args => AddTrait(args.Text);
        ClearFilters.OnPressed += _ => ClearAll();

        TraitAll.OnPressed += _ => SetTraitMatch(true);
        TraitAny.OnPressed += _ => SetTraitMatch(false);

        foreach (var box in AllChecks())
            box.OnPressed += _ => Refresh();

        AcceptButton.OnPressed += _ =>
        {
            var lines = PurchaseLines();
            if (lines.Count == 0)
            {
                OnAccept?.Invoke();
                return;
            }

            if (CartCost() > ReadPurse())
            {
                UpdatePurse();
                return;
            }

            _entities.RaisePredictiveEvent(new CFShopPurchaseEvent { Lines = lines });
            _cart.Clear();
            Refresh();
            OnAccept?.Invoke();
        };
        CancelButton.OnPressed += _ => OnCancel?.Invoke();

        Refresh();
    }

    public void SetListings(IReadOnlyList<CFShopListing> listings)
    {
        _listings = listings;
        _cart.Clear();
        Refresh();
    }

    public IReadOnlyList<CFShopListing> Cart()
    {
        return _listings.Where(listing => _cart.Contains(listing.Id)).ToList();
    }

    private void SetTraitMatch(bool all)
    {
        _matchAllTraits = all;
        TraitAll.Pressed = all;
        TraitAny.Pressed = !all;
        Refresh();
    }

    private void AddTrait(string text)
    {
        var trait = text.Trim();
        TraitInput.Text = "";
        if (trait.Length == 0 || _traits.Contains(trait, StringComparer.OrdinalIgnoreCase))
            return;

        _traits.Add(trait);
        var chip = new Button { Text = trait };
        chip.OnPressed += _ =>
        {
            _traits.Remove(trait);
            TraitChips.RemoveChild(chip);
            Refresh();
        };
        TraitChips.AddChild(chip);
        Refresh();
    }

    private void ClearAll()
    {
        SearchInput.Text = "";
        TraitInput.Text = "";
        _traits.Clear();
        TraitChips.RemoveAllChildren();
        _matchAllTraits = true;
        TraitAll.Pressed = true;
        TraitAny.Pressed = false;
        foreach (var box in AllChecks())
            box.Pressed = false;

        _ascending = true;
        SortToggle.Text = Loc.GetString("cf-shop-sort-asc");
        SortDropdown.SelectId(0);
        Refresh();
    }

    private IEnumerable<CheckBox> AllChecks()
    {
        yield return ChkAmmunition;
        yield return ChkArmor;
        yield return ChkConsumable;
        yield return ChkContainer;
        yield return ChkEquipment;
        yield return ChkKit;
        yield return ChkShield;
        yield return ChkTreasure;
        yield return ChkWeapon;
        yield return ChkCommon;
        yield return ChkUncommon;
        yield return ChkRare;
        yield return ChkLight;
        yield return ChkMedium;
        yield return ChkHeavy;
        yield return ChkBulwark;
        yield return ChkFlexible;
        yield return ChkNoisy;
        yield return ChkComfort;
    }

    private void Refresh()
    {
        var rows = Filter(_listings).ToList();
        rows.Sort(Compare);
        ItemRows.RemoveAllChildren();
        foreach (var listing in rows)
            ItemRows.AddChild(BuildRow(listing));

        var count = CartCount();
        AcceptButton.Text = count == 0
            ? Loc.GetString("cf-shop-accept")
            : Loc.GetString("cf-shop-accept-count", ("count", count));
        UpdatePurse();
    }

    private void UpdatePurse()
    {
        var left = ReadPurse() - CartCost();
        PurseLabel.Text = CFCoins.FormatWallet(left);
        PurseLabel.FontColorOverride = left < 0 ? Color.FromHex("#E07070") : Color.FromHex("#E6C15A");
    }

    private int ReadPurse()
    {
        if (_player.LocalEntity is not { } uid)
            return CFCoins.StartingCopper(1);

        if (_entities.TryGetComponent<CFPurseComponent>(uid, out var purse) && purse.Seeded)
            return purse.Copper;

        if (_entities.TryGetComponent<CFCombatantComponent>(uid, out var combatant))
            return CFCoins.StartingCopper(combatant.Level);

        return CFCoins.StartingCopper(1);
    }

    private int CartCost()
    {
        var total = 0;
        foreach (var id in _cart)
        {
            foreach (var listing in _listings)
            {
                if (listing.Id != id)
                    continue;

                total += listing.CostCopper * Quantity(id);
                break;
            }
        }

        return total;
    }

    private IEnumerable<CFShopListing> Filter(IReadOnlyList<CFShopListing> source)
    {
        var search = SearchInput.Text.Trim();
        var categories = SelectedCategories();
        var rarities = SelectedRarities();
        var armor = SelectedArmor();

        foreach (var listing in source)
        {
            if (search.Length > 0
                && listing.Name.Contains(search, StringComparison.OrdinalIgnoreCase) == false
                && listing.Description.Contains(search, StringComparison.OrdinalIgnoreCase) == false)
                continue;

            if (categories.Count > 0 && !categories.Contains(listing.Category))
                continue;

            if (rarities.Count > 0 && !rarities.Contains(listing.Rarity))
                continue;

            if (armor.Count > 0 && !armor.All(tag => listing.Armor.Contains(tag, StringComparer.OrdinalIgnoreCase)))
                continue;

            if (_traits.Count > 0 && !TraitsMatch(listing))
                continue;

            yield return listing;
        }
    }

    private bool TraitsMatch(CFShopListing listing)
    {
        bool Hit(string wanted)
        {
            foreach (var trait in listing.Traits)
            {
                if (trait.Contains(wanted, StringComparison.OrdinalIgnoreCase))
                    return true;
            }

            return false;
        }

        return _matchAllTraits ? _traits.All(Hit) : _traits.Any(Hit);
    }

    private HashSet<CFShopCategory> SelectedCategories()
    {
        var set = new HashSet<CFShopCategory>();
        if (ChkAmmunition.Pressed) set.Add(CFShopCategory.Ammunition);
        if (ChkArmor.Pressed) set.Add(CFShopCategory.Armor);
        if (ChkConsumable.Pressed) set.Add(CFShopCategory.Consumable);
        if (ChkContainer.Pressed) set.Add(CFShopCategory.Container);
        if (ChkEquipment.Pressed) set.Add(CFShopCategory.Equipment);
        if (ChkKit.Pressed) set.Add(CFShopCategory.Kit);
        if (ChkShield.Pressed) set.Add(CFShopCategory.Shield);
        if (ChkTreasure.Pressed) set.Add(CFShopCategory.Treasure);
        if (ChkWeapon.Pressed) set.Add(CFShopCategory.Weapon);
        return set;
    }

    private HashSet<CFRarity> SelectedRarities()
    {
        var set = new HashSet<CFRarity>();
        if (ChkCommon.Pressed) set.Add(CFRarity.Common);
        if (ChkUncommon.Pressed) set.Add(CFRarity.Uncommon);
        if (ChkRare.Pressed) set.Add(CFRarity.Rare);
        return set;
    }

    private HashSet<string> SelectedArmor()
    {
        var set = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        if (ChkLight.Pressed) set.Add("Light");
        if (ChkMedium.Pressed) set.Add("Medium");
        if (ChkHeavy.Pressed) set.Add("Heavy");
        if (ChkBulwark.Pressed) set.Add("Bulwark");
        if (ChkFlexible.Pressed) set.Add("Flexible");
        if (ChkNoisy.Pressed) set.Add("Noisy");
        if (ChkComfort.Pressed) set.Add("Comfort");
        return set;
    }

    private int Compare(CFShopListing left, CFShopListing right)
    {
        var order = SortDropdown.SelectedId switch
        {
            1 => string.Compare(left.Name, right.Name, StringComparison.CurrentCultureIgnoreCase),
            2 => left.CostCopper.CompareTo(right.CostCopper),
            3 => left.Rarity.CompareTo(right.Rarity),
            _ => left.Level.CompareTo(right.Level),
        };

        if (order == 0)
            order = string.Compare(left.Name, right.Name, StringComparison.CurrentCultureIgnoreCase);

        return _ascending ? order : -order;
    }

    private int Quantity(string id)
    {
        return _qty.TryGetValue(id, out var count) ? Math.Clamp(count, 1, 99) : 1;
    }

    private int CartCount()
    {
        var count = 0;
        foreach (var id in _cart)
            count += Quantity(id);
        return count;
    }

    private List<CFShopPurchaseLine> PurchaseLines()
    {
        var lines = new List<CFShopPurchaseLine>();
        foreach (var id in _cart)
        {
            lines.Add(new CFShopPurchaseLine
            {
                Prototype = id,
                Quantity = Quantity(id),
            });
        }

        return lines;
    }

    private Control BuildRow(CFShopListing listing)
    {
        var icon = new EntityPrototypeView
        {
            MinSize = new System.Numerics.Vector2(32, 32),
            SetWidth = 40,
            MinWidth = 40,
            MaxWidth = 40,
            HorizontalExpand = false,
            Stretch = SpriteView.StretchMode.Fit,
        };
        icon.SetPrototype(listing.Id);

        var name = new Label
        {
            Text = listing.Name,
            MinWidth = 120,
            HorizontalExpand = true,
            ClipText = true,
            FontColorOverride = Color.FromHex("#E6C15A"),
        };

        var description = new Label
        {
            Text = listing.Description,
            HorizontalExpand = true,
            ClipText = true,
            SizeFlagsStretchRatio = 2,
        };

        var cost = new Label
        {
            Text = CFCoins.FormatPrice(listing.CostCopper),
            SetWidth = 80,
            MinWidth = 80,
            MaxWidth = 80,
            HorizontalExpand = false,
            ClipText = true,
            Align = Label.AlignMode.Right,
        };

        var qty = new LineEdit
        {
            Text = Quantity(listing.Id).ToString(),
            SetWidth = 60,
            MinWidth = 60,
            MaxWidth = 60,
            HorizontalExpand = false,
            HorizontalAlignment = Control.HAlignment.Center,
        };
        qty.OnTextChanged += args =>
        {
            if (int.TryParse(args.Text, out var count))
                _qty[listing.Id] = Math.Clamp(count, 1, 99);
            UpdatePurse();
        };

        var bought = _cart.Contains(listing.Id);
        var buy = new Button
        {
            Text = Loc.GetString(bought ? "cf-shop-added" : "cf-shop-buy"),
            SetWidth = 70,
            MinWidth = 70,
            MaxWidth = 70,
            HorizontalExpand = false,
            ClipText = true,
            Disabled = listing.CostCopper <= 0,
        };
        buy.OnPressed += _ =>
        {
            if (!_cart.Add(listing.Id))
            {
                _cart.Remove(listing.Id);
            }
            else if (listing.CostCopper <= 0 || CartCost() > ReadPurse())
            {
                _cart.Remove(listing.Id);
            }

            Refresh();
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            RectClipContent = true,
            Margin = new Thickness(4),
            SeparationOverride = 8,
        };
        row.AddChild(icon);
        row.AddChild(name);
        row.AddChild(description);
        row.AddChild(cost);
        row.AddChild(qty);
        row.AddChild(buy);

        var panel = new PanelContainer { HorizontalExpand = true, RectClipContent = true };
        panel.AddChild(row);
        return panel;
    }

    /// <summary>
    /// Every non-abstract CF entity that can be held. New item YAML shows up here without a shop edit.
    /// </summary>
    private List<CFShopListing> ScanItems()
    {
        var catalog = new List<CFShopListing>();
        foreach (var proto in _prototypes.EnumeratePrototypes<EntityPrototype>())
        {
            if (proto.Abstract || !proto.ID.StartsWith("CF", StringComparison.Ordinal))
                continue;

            if (!proto.TryGetComponent<ItemComponent>(out _))
                continue;

            catalog.Add(ToListing(proto));
        }

        return catalog;
    }

    private static CFShopListing ToListing(EntityPrototype proto)
    {
        var traits = new List<string>();
        if (proto.TryGetComponent<CFTraitComponent>(out var traitComp))
        {
            foreach (var trait in traitComp.Traits)
                traits.Add(trait.Id);
        }

        var armor = new List<string>();
        var level = 0;
        if (proto.TryGetComponent<CFArmorComponent>(out var armorComp))
            AddArmorTag(armor, armorComp.Proficiency);

        if (proto.TryGetComponent<CFAlchemicalItemComponent>(out var brew))
            level = brew.ItemLevel;

        var cost = CFCoins.EntityPrice(proto);

        return new CFShopListing
        {
            Id = proto.ID,
            Name = proto.Name,
            Description = proto.Description,
            Level = level,
            Category = Category(proto),
            CostCopper = cost,
            Traits = traits.ToArray(),
            Armor = armor.ToArray(),
        };
    }

    private static void AddArmorTag(List<string> armor, string proficiency)
    {
        switch (proficiency)
        {
            case "LightArmor":
                armor.Add("Light");
                break;
            case "MediumArmor":
                armor.Add("Medium");
                break;
            case "HeavyArmor":
                armor.Add("Heavy");
                break;
        }
    }

    private static CFShopCategory Category(EntityPrototype proto)
    {
        if (proto.TryGetComponent<ProjectileComponent>(out _))
            return CFShopCategory.Ammunition;

        if (proto.TryGetComponent<CFArmorComponent>(out _))
            return CFShopCategory.Armor;

        if (proto.TryGetComponent<CFMeleeWeaponComponent>(out _) || proto.TryGetComponent<CFRangedWeaponComponent>(out _))
            return CFShopCategory.Weapon;

        if (proto.TryGetComponent<CFAlchemicalItemComponent>(out var brew) && brew.Consumable)
            return CFShopCategory.Consumable;

        if (proto.ID.Contains("Shield", StringComparison.OrdinalIgnoreCase))
            return CFShopCategory.Shield;

        if (proto.TryGetComponent<StorageComponent>(out _))
            return CFShopCategory.Container;

        if (proto.Components.ContainsKey("Clothing"))
            return CFShopCategory.Equipment;

        return CFShopCategory.Equipment;
    }
}

