using System.Linq;
using Content.Client.Chat.Managers;
using Content.Shared.CF.Character;
using Content.Shared.CF.Combat;
using Content.Shared.CF.Preferences;
using Content.Shared.Chat;
using Content.Shared.Humanoid;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Prototypes;
using Robust.Shared.Random;

namespace Content.Client.CF.Character;

[GenerateTypedNameReferences]
public sealed partial class CFCharacterSheetTab : BoxContainer
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IChatManager _chat = default!;
    [Dependency] private IRobustRandom _random = default!;

    private readonly Dictionary<string, CFSheetSkillRow> _skills = new();
    private readonly Dictionary<CFAbility, int> _abilityMods = new();
    private int _fortMod;
    private int _refMod;
    private int _willMod;
    private EntityUid _entity = EntityUid.Invalid;

    public CFCharacterSheetTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        BuildSkillColumns();
        WireAbilityRolls();
        WireSaveRolls();
    }

    public void Update(EntityUid entity)
    {
        _entity = entity;
        if (!_entities.EntityExists(entity))
            return;

        NameLabel.Text = _entities.GetComponent<MetaDataComponent>(entity).EntityName;

        if (!_entities.TryGetComponent(entity, out CFAbilityScoreComponent? abilities))
            abilities = new CFAbilityScoreComponent();

        if (!_entities.TryGetComponent(entity, out CFCombatantComponent? combatant))
            combatant = new CFCombatantComponent();

        CFClassPrototype? cls = null;
        if (combatant.ClassId != null)
            _prototypes.TryIndex(combatant.ClassId, out cls);

        CFBackgroundPrototype? background = null;
        if (combatant.BackgroundId != null)
            _prototypes.TryIndex(combatant.BackgroundId, out background);

        CFAncestryPrototype? ancestry = null;
        if (_entities.TryGetComponent(entity, out HumanoidProfileComponent? profile))
            ancestry = CFAttributeMath.FindAncestry(_prototypes, profile.Species);

        AncestryLabel.Text = ancestry != null ? Loc.GetString(ancestry.Name) : "—";
        BackgroundLabel.Text = background != null ? Loc.GetString(background.Name) : "—";
        ClassLabel.Text = cls != null
            ? Loc.GetString("cf-sheet-class-level", ("class", Loc.GetString(cls.Name)), ("level", combatant.Level))
            : Loc.GetString("cf-sheet-level-only", ("level", combatant.Level));

        SetAbility(CFAbility.Strength, StrScoreLabel, StrModLabel, abilities);
        SetAbility(CFAbility.Dexterity, DexScoreLabel, DexModLabel, abilities);
        SetAbility(CFAbility.Constitution, ConScoreLabel, ConModLabel, abilities);
        SetAbility(CFAbility.Intelligence, IntScoreLabel, IntModLabel, abilities);
        SetAbility(CFAbility.Wisdom, WisScoreLabel, WisModLabel, abilities);
        SetAbility(CFAbility.Charisma, ChaScoreLabel, ChaModLabel, abilities);

        ArmorClassLabel.Text = combatant.ArmorClass.ToString();
        CurrentHpLabel.Text = combatant.CurrentHp.ToString();
        MaxHpLabel.Text = combatant.MaxHp.ToString();
        TempHpLabel.Text = Loc.GetString("cf-sheet-temp-hp", ("hp", combatant.TemporaryHp));
        DyingLabel.Text = combatant.Dying.ToString();
        WoundedLabel.Text = combatant.Wounded.ToString();
        AilmentsLabel.Text = _entities.TryGetComponent(entity, out CFOffGuardComponent? offGuard) && offGuard.Active
            ? Loc.GetString("cf-combat-off-guard-name")
            : "—";
        SpeedLabel.Text = Loc.GetString("cf-sheet-speed-value", ("feet", ancestry?.Speed ?? 25));

        if (ancestry is { Traits.Count: > 0 })
        {
            TraitsLabel.Text = string.Join(", ", ancestry.Traits.Select(t => Loc.GetString(t)));
        }
        else
        {
            TraitsLabel.Text = "—";
        }

        var fortRank = CFSkills.GetSaveRank(cls, "Fortitude");
        var refRank = CFSkills.GetSaveRank(cls, "Reflex");
        var willRank = CFSkills.GetSaveRank(cls, "Will");
        _fortMod = CFSkills.SkillModifier(abilities.AbilityModifiers, CFAbility.Constitution, combatant.Level, fortRank);
        _refMod = CFSkills.SkillModifier(abilities.AbilityModifiers, CFAbility.Dexterity, combatant.Level, refRank);
        _willMod = CFSkills.SkillModifier(abilities.AbilityModifiers, CFAbility.Wisdom, combatant.Level, willRank);
        FortRankLabel.Text = CFSheetSkillRow.RankLetter(fortRank);
        RefRankLabel.Text = CFSheetSkillRow.RankLetter(refRank);
        WillRankLabel.Text = CFSheetSkillRow.RankLetter(willRank);
        FortModLabel.Text = CFSkills.FormatSigned(_fortMod);
        RefModLabel.Text = CFSkills.FormatSigned(_refMod);
        WillModLabel.Text = CFSkills.FormatSigned(_willMod);

        foreach (var (skillId, row) in _skills)
        {
            if (!_prototypes.TryIndex(skillId, out CFAbilitySkillPrototype? skill))
                continue;

            var rank = CFSkills.GetSkillRank(cls, background, skillId, combatant.TrainedSkills);
            var mod = CFSkills.SkillModifier(abilities.AbilityModifiers, skill.Ability, combatant.Level, rank);
            var skillName = Loc.GetString(skill.Name);
            if (skillId == "Lore" && combatant.LoreNames.Count > 0)
                skillName = Loc.GetString("cf-sheet-lore-named", ("lores", string.Join(", ", combatant.LoreNames)));
            row.Set(
                skillId,
                skillName,
                AbilityAbbr(skill.Ability),
                rank,
                mod);
        }
    }

    private void BuildSkillColumns()
    {
        AddSkills(SkillColumn1, CFSkills.Column1);
        AddSkills(SkillColumn2, CFSkills.Column2);
        AddSkills(SkillColumn3, CFSkills.Column3);
    }

    private void AddSkills(BoxContainer column, IReadOnlyList<string> ids)
    {
        foreach (var id in ids)
        {
            var row = new CFSheetSkillRow();
            var skillId = id;
            row.Pressed += () => RollSkill(skillId);
            _skills[id] = row;
            column.AddChild(row);
        }
    }

    private void WireAbilityRolls()
    {
        BindAbility(StrDiceLabel, StrNameLabel, StrModLabel, CFAbility.Strength);
        BindAbility(DexDiceLabel, DexNameLabel, DexModLabel, CFAbility.Dexterity);
        BindAbility(ConDiceLabel, ConNameLabel, ConModLabel, CFAbility.Constitution);
        BindAbility(IntDiceLabel, IntNameLabel, IntModLabel, CFAbility.Intelligence);
        BindAbility(WisDiceLabel, WisNameLabel, WisModLabel, CFAbility.Wisdom);
        BindAbility(ChaDiceLabel, ChaNameLabel, ChaModLabel, CFAbility.Charisma);
    }

    private void BindAbility(Label diceLabel, Label nameLabel, Label modLabel, CFAbility ability)
    {
        BindRoll(diceLabel, () => RollAbility(ability));
        BindRoll(nameLabel, () => RollAbility(ability));
        BindRoll(modLabel, () => RollAbility(ability));
    }

    private void WireSaveRolls()
    {
        BindRoll(FortDiceLabel, () => RollCheck(Loc.GetString("cf-sheet-fortitude"), _fortMod));
        BindRoll(FortNameLabel, () => RollCheck(Loc.GetString("cf-sheet-fortitude"), _fortMod));
        BindRoll(RefDiceLabel, () => RollCheck(Loc.GetString("cf-sheet-reflex"), _refMod));
        BindRoll(RefNameLabel, () => RollCheck(Loc.GetString("cf-sheet-reflex"), _refMod));
        BindRoll(WillDiceLabel, () => RollCheck(Loc.GetString("cf-sheet-will"), _willMod));
        BindRoll(WillNameLabel, () => RollCheck(Loc.GetString("cf-sheet-will"), _willMod));
    }

    private static void BindRoll(Label label, Action roll)
    {
        label.MouseFilter = Control.MouseFilterMode.Stop;
        label.DefaultCursorShape = Control.CursorShape.Hand;
        label.OnKeyBindDown += args =>
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            args.Handle();
            roll();
        };
    }

    private void SetAbility(CFAbility ability, Label scoreLabel, Label modLabel, CFAbilityScoreComponent abilities)
    {
        var mod = abilities.GetModifier(ability);
        _abilityMods[ability] = mod;
        scoreLabel.Text = CFSkills.AbilityScoreFromModifier(mod).ToString();
        modLabel.Text = CFSkills.FormatSigned(mod);
    }

    private void RollAbility(CFAbility ability)
    {
        var mod = _abilityMods.GetValueOrDefault(ability);
        var name = Loc.GetString($"cf-ability-{ability.ToString().ToLowerInvariant()}");
        RollCheck(name, mod);
    }

    private void RollSkill(string skillId)
    {
        if (!_skills.TryGetValue(skillId, out var row))
            return;

        var name = _prototypes.TryIndex(skillId, out CFAbilitySkillPrototype? skill)
            ? Loc.GetString(skill.Name)
            : skillId;
        RollCheck(name, row.ModifierValue);
    }

    private void RollCheck(string label, int modifier)
    {
        var d20 = _random.Next(1, 21);
        var total = d20 + modifier;
        _chat.SendMessage(
            Loc.GetString("cf-sheet-roll",
                ("check", label),
                ("d20", d20),
                ("mod", CFSkills.FormatSigned(modifier)),
                ("total", total)),
            ChatSelectChannel.Emotes);
    }

    private static string AbilityAbbr(CFAbility ability) => ability switch
    {
        CFAbility.Strength => "Str",
        CFAbility.Dexterity => "Dex",
        CFAbility.Constitution => "Con",
        CFAbility.Intelligence => "Int",
        CFAbility.Wisdom => "Wis",
        CFAbility.Charisma => "Cha",
        _ => "?",
    };
}
