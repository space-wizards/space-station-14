using Content.Client.Stylesheets;
using Content.Shared.CCVar;
using Content.Shared.Dataset;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Timing;
using Robust.Shared.Network;
using Robust.Shared.Prototypes;
using Robust.Shared.Random;

namespace Content.Client.Launcher
{
    [GenerateTypedNameReferences]
    public sealed partial class LauncherConnectingGui : Control
    {
        private const float RedialWaitTimeSeconds = 15f;
        private readonly LauncherConnecting _state;
        private float _waitTime;

        // Pressing reconnect will redial instead of simply reconnecting.
        private bool _redial;

        private readonly IRobustRandom _random;
        private readonly IPrototypeManager _prototype;
        private readonly IConfigurationManager _cfg;
        private readonly IClipboardManager _clipboard;

        /// <summary>
        /// The server redirect controls that have been created on the GUI
        /// </summary>
        /// <remarks>
        /// The dictionary keys are the server urls, so the same server can't be added twice
        /// </remarks>
        private Dictionary<string, FallbackControl> _fallbackControls = new ();

        /// <summary>
        /// An easy-to-access list of the visibility status for each Fallback control on the GUI
        /// </summary>
        private Dictionary<string, bool> _visibleFallbacks = new();

        public LauncherConnectingGui(
            LauncherConnecting state,
            IRobustRandom random,
            IPrototypeManager prototype,
            IConfigurationManager config,
            IClipboardManager clipboard)
        {
            _state = state;
            _random = random;
            _prototype = prototype;
            _cfg = config;
            _clipboard = clipboard;

            RobustXamlLoader.Load(this);

            LayoutContainer.SetAnchorPreset(this, LayoutContainer.LayoutPreset.Wide);

            Stylesheet = IoCManager.Resolve<IStylesheetManager>().SheetSystem;

            ChangeLoginTip();
            RetryButton.OnPressed += ReconnectButtonPressed;
            ReconnectButton.OnPressed += ReconnectButtonPressed;

            CopyButton.OnPressed += CopyButtonPressed;
            CopyButtonDisconnected.OnPressed += CopyButtonDisconnectedPressed;
            ExitButton.OnPressed += _ => _state.Exit();

            var addr = state.Address;
            if (addr != null)
                ConnectingAddress.Text = addr;

            state.PageChanged += OnPageChanged;
            state.ConnectFailReasonChanged += ConnectFailReasonChanged;
            state.ConnectionStateChanged += ConnectionStateChanged;
            state.ConnectFailed += HandleDisconnectReason;

            ConnectionStateChanged(state.ConnectionState);

            // Redial flag setup
            var edim = IoCManager.Resolve<ExtendedDisconnectInformationManager>();
            edim.LastNetDisconnectedArgsChanged += LastNetDisconnectedArgsChanged;
            LastNetDisconnectedArgsChanged(edim.LastNetDisconnectedArgs);
        }

        /// <summary>
        /// Creates a server fallback button, along with its related GUI elements
        /// </summary>
        private void CreateFallbackGui(string name, string url, int players, int maxPlayers, bool visible)
        {
            var option = new FallbackControl(name, url);
            option.ServerName.Text = name;
            option.FallbackButton.OnButtonDown += args => OnFallbackButtonPressed(args, url);
            FallbackBox.AddChild(option);
            _fallbackControls.Add(url, option);
            _visibleFallbacks.Add(url, visible);

            option.PlayersLabel.Text = Loc.GetString("connecting-fallback-players",("players", players),("maxPlayers", maxPlayers));
            option.Visible = visible;
        }

        /// <summary>
        /// Checks if any Fallback buttons are visible after the last update, and adjusts FallbackLabel as appropriate
        /// (Buttons can be hidden after updates, if their player count exceeds their capacity)
        /// </summary>
        private void UpdateFallbackLabel()
        {
            var loc = _visibleFallbacks.ContainsValue(true) ? "connecting-fallback-label" : "connecting-fallback-label-full";
            FallbackLabel.Text = Loc.GetString(loc);
        }

        // Just button, there's only one at once anyways :)
        private void ReconnectButtonPressed(BaseButton.ButtonEventArgs args)
        {
            if (_redial)
            {
                // Redial shouldn't fail, but if it does, try a reconnect (maybe we're being run from debug)
                if (_state.Redial())
                    return;
            }

            _state.RetryConnect();
        }

        /// <summary>
        /// Connects the client to a different server
        /// </summary>
        private void OnFallbackButtonPressed(BaseButton.ButtonEventArgs args, string target)
        {
            _state.Redial(target, Loc.GetString("connecting-switching",("target",target)));
        }

        private void CopyButtonPressed(BaseButton.ButtonEventArgs args)
        {
            CopyText(ConnectFailReason.Text);
        }

        private void CopyButtonDisconnectedPressed(BaseButton.ButtonEventArgs args)
        {
            CopyText(DisconnectReason.Text);
        }

        private void CopyText(string? text)
        {
            if (!string.IsNullOrEmpty(text))
            {
                _clipboard.SetText(text);
            }
        }

        private void ConnectFailReasonChanged(string? reason)
        {
            ConnectFailReason.SetMessage(reason == null
                ? ""
                : Loc.GetString("connecting-fail-reason", ("reason", reason)));
        }

        private void LastNetDisconnectedArgsChanged(NetDisconnectedArgs? args)
        {
            HandleDisconnectReason(args);
        }

        private void HandleDisconnectReason(INetStructuredReason? reason)
        {
            if (reason == null)
            {
                _waitTime = 0;
                _redial = false;
            }
            else
            {
                _redial = reason.RedialFlag;

                if (reason.Message.Int32Of("delay") is { } delay)
                {
                    _waitTime = delay;
                }
                else if (_redial)
                {
                    _waitTime = RedialWaitTimeSeconds;
                }

                HandleFallbacks(reason);
            }
        }

        /// <summary>
        /// Reads the fallback string sent by the server, and creates or updates fallback buttons on the GUI
        /// </summary>
        private void HandleFallbacks(INetStructuredReason reason)
        {
            // List of fallback servers sent by the current server
            if (reason.Message.StringOf("fallbackServers") is not { } fallback)
                return;

            // The string separates servers by ; and data fields about each server by ,
            foreach (var server in fallback.Split(";", StringSplitOptions.RemoveEmptyEntries))
            {
                // Each server must have a name, url, playercount and max playercount
                var members = server.Split(",", StringSplitOptions.RemoveEmptyEntries);
                if (members.Length != 4)
                {
                    Log.Warning($"Fallback server info contained malformed element: '{server}'");
                    continue;
                }

                var name = members[0].Trim();
                var url = members[1].Trim();

                if (!int.TryParse(members[2].Trim(), out var players) || !int.TryParse(members[3].Trim(), out var max))
                {
                    Log.Info($"Fallback server info contained invalid player count data: '{server}'");
                    continue;
                }

                // Since the list is sent by the server on every reconnect attempt, we must check that
                // we are not adding the same servers multiple times
                if (_fallbackControls.TryGetValue(url, out var control))
                {
                    control.PlayersLabel.Text = Loc.GetString("connecting-fallback-players",("players", players),("maxPlayers", max));
                    control.Visible = players < max;
                    _visibleFallbacks[url]= players < max;
                }
                else
                {
                    FallbackBox.Visible = true;
                    CreateFallbackGui(name, url, players, max, players < max);
                }
            }

            UpdateFallbackLabel();
        }

        private void ChangeLoginTip()
        {
            var tipsDataset = _cfg.GetCVar(CCVars.LoginTipsDataset);
            var loginTipsEnabled = _prototype.TryIndex<LocalizedDatasetPrototype>(tipsDataset, out var tips);

            LoginTips.Visible = loginTipsEnabled;
            if (!loginTipsEnabled)
            {
                return;
            }

            var tipList = tips!.Values;

            if (tipList.Count == 0)
                return;

            var randomIndex = _random.Next(tipList.Count);
            var tip = tipList[randomIndex];
            LoginTip.SetMessage(Loc.GetString(tip));

            LoginTipTitle.Text = Loc.GetString("connecting-window-tip", ("numberTip", randomIndex + 1));
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            var button = _state.CurrentPage == LauncherConnecting.Page.ConnectFailed
                ? RetryButton
                : ReconnectButton;

            _waitTime -= args.DeltaSeconds;
            if (_waitTime <= 0)
            {
                button.Disabled = false;
                var key = _redial
                    ? "connecting-redial"
                    : _state.CurrentPage == LauncherConnecting.Page.ConnectFailed
                        ? "connecting-reconnect"
                        : "connecting-retry";

                button.Text = Loc.GetString(key);
            }
            else
            {
                button.Disabled = true;
                button.Text = Loc.GetString("connecting-redial-wait", ("time", _waitTime.ToString("00")));
            }
        }

        private void OnPageChanged(LauncherConnecting.Page page)
        {
            ConnectingStatus.Visible = page == LauncherConnecting.Page.Connecting;
            ConnectFail.Visible = page == LauncherConnecting.Page.ConnectFailed;
            Disconnected.Visible = page == LauncherConnecting.Page.Disconnected;

            if (page == LauncherConnecting.Page.Disconnected)
                DisconnectReason.Text = _state.LastDisconnectReason;
        }

        private void ConnectionStateChanged(ClientConnectionState state)
        {
            ConnectStatus.Text = Loc.GetString($"connecting-state-{state}");
        }
    }
}
