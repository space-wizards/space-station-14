using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.Info;

/// <summary>
/// Displays compact information about the current round.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class RoundInfo : PanelContainer
{
    [Dependency] private IGameTiming _gameTiming = default!;

    private TimeSpan _roundStartTime;
    private bool _isRoundStarted;

    public RoundInfo()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    /// <summary>
    /// Updates the displayed round information.
    /// </summary>
    public void SetRoundInfo(int playerCount, string mapName, string gamemodeTitle, TimeSpan roundStartTime, bool isRoundStarted)
    {
        Visible = true;
        PlayerCountLabel.Text = playerCount.ToString();
        MapNameLabel.Text = mapName;
        GamemodeLabel.Text = gamemodeTitle;
        _roundStartTime = roundStartTime;
        _isRoundStarted = isRoundStarted;
        UpdateRoundTime();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateRoundTime();
    }

    private void UpdateRoundTime()
    {
        RoundTimeLabel.Text = !_isRoundStarted
            ? Loc.GetString("ui-escape-round-not-started")
            : FormatRoundTime(_gameTiming.CurTime.Subtract(_roundStartTime));
    }

    private static string FormatRoundTime(TimeSpan time)
    {
        return $"{(int) time.TotalHours:D2}:{time.Minutes:D2}:{time.Seconds:D2}";
    }
}
