using Content.Client.Pinpointer.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared.SurveillanceCamera;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.SurveillanceCamera.UI;

[GenerateTypedNameReferences]
public sealed partial class CameraPlaybackWindow : FancyWindow
{
    [Dependency] private IEntityManager _entManager = default!;
    private readonly Texture? _blipTexture;
    public event Action<TimeSpan>? OnTargetChanged;

    private bool _updating;

    public CameraPlaybackWindow(EntityUid console)
    {
        RobustXamlLoader.Load(this);

        IoCManager.InjectDependencies(this);

        var spriteSystem = _entManager.System<SpriteSystem>();
        _blipTexture = spriteSystem.Frame0(new SpriteSpecifier.Texture(new ResPath("/Textures/Interface/NavMap/beveled_circle.png")));

        if (_entManager.TryGetComponent<TransformComponent>(console, out var xform))
            NavMap.MapUid = xform.GridUid;
        else
            NavMap.Visible = false;

        NavMap.ForceNavMapUpdate();

        TimeSlider.OnValueChanged += _ =>
        {
            if (!_updating)
                TimeLabel.Text = FormatTime(TimeSpan.FromSeconds(TimeSlider.Value));
        };

        TimeSlider.OnReleased += _ =>
        {
            if (!_updating)
                OnTargetChanged?.Invoke(TimeSpan.FromSeconds(TimeSlider.Value));
        };
    }

    public void UpdateState(CameraPlaybackConsoleState state)
    {
        _updating = true;
        TimeSlider.MinValue = (float) state.OldestTime.TotalSeconds;
        TimeSlider.MaxValue = (float) state.NewestTime.TotalSeconds;
        TimeSlider.Value = (float) state.Target.TotalSeconds;
        _updating = false;

        TimeLabel.Text = FormatTime(state.Target);

        NavMap.TrackedEntities.Clear();
        RecordsList.RemoveAllChildren();

        if (_blipTexture == null)
            return;

        var i = 0;
        foreach (var record in state.Records)
        {
            i++;
            var key = new NetEntity(-i);
            var coords = _entManager.GetCoordinates(record.Position);
            NavMap.TrackedEntities[key] = new NavMapBlip(coords, _blipTexture, Color.Orange, false, false);

            var row = new Label
            {
                Text = $"{FormatTime(record.Time)}  {record.PerceivedName} — {record.CameraName}",
                MouseFilter = MouseFilterMode.Stop,
                HorizontalExpand = true,
                ClipText = true,
            };
            row.OnMouseEntered += _ => HighlightBlip(key);
            row.OnMouseExited += _ => HighlightBlip(null);
            RecordsList.AddChild(row);
        }
    }

    private void HighlightBlip(NetEntity? focus)
    {
        foreach (var (key, blip) in NavMap.TrackedEntities.ToArray())
        {
            var color = focus == null
                ? Color.Orange
                : key == focus ? Color.Cyan : Color.Orange * Color.DimGray;
            NavMap.TrackedEntities[key] = new NavMapBlip(blip.Coordinates, blip.Texture, color, false, false);
        }
    }

    private static string FormatTime(TimeSpan time)
    {
        return $"{(int) time.TotalMinutes:00}:{time.Seconds:00}";
    }
}
