using System.Diagnostics.CodeAnalysis;
using System.Numerics;
using Content.Client.Gameplay;
using Content.Client.Verbs.UI;
using Content.Shared.Tabletop.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.State;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Graphics;
using Robust.Shared.Input;
using Robust.Shared.Map;

namespace Content.Client.Tabletop.UI;

/// <summary>
/// A window for a board game.  Has a viewport into the board game, and a button to rotate the camera.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TabletopWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IStateManager _stateMan = default!;
    [Dependency] private IUserInterfaceManager _uiMan = default!;
    private SharedEyeSystem _eye;
    private SharedTransformSystem _xform;

    /// <summary>
    /// An action invoked when the player starts dragging a piece.
    /// </summary>
    public Action<EntityUid>? DragStarted;

    /// <summary>
    /// An action invoked when the player drags the piece to a new position.
    /// </summary>
    public Action<EntityUid, EntityCoordinates>? DragMoved;
    /// <summary>
    /// An action invoked when the player lets go of a piece.
    /// </summary>
    public Action<EntityUid>? DragFinished;

    // Is the mouse currently inside the window?
    private bool _mouseInWindow;

    // Is a piece currently getting dragged?
    private EntityUid? _draggedPiece;

    // The board being played on.
    private EntityUid? _board;

    // The last drag position.
    private Vector2 _lastPosition;

    // The dimensions of a quarter of the board (total dimensions from -boardBounds to boardBounds)
    private Vector2 _boardBounds;

    /// <summary>
    /// The minimum distance, in pixels, required to move before sending an update to another player.
    /// </summary>
    public const float MinDragUpdateDistance = 2f / EyeManager.PixelsPerMeter;
    public const float MinDragUpdateSquaredDistance = MinDragUpdateDistance * MinDragUpdateDistance;

    /// <inheritdoc cref="TabletopWindow"/>
    public TabletopWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _eye = _entMan.System<SharedEyeSystem>();
        _xform = _entMan.System<SharedTransformSystem>();

        ScalingVp.OnMouseEntered += OnViewportMouseEnter;
        ScalingVp.OnMouseExited += OnViewportMouseExit;
        ScalingVp.OnKeyBindDown += OnViewportKeyBindDown;
        ScalingVp.OnKeyBindUp += OnViewportKeyBindUp;

        FlipButton.OnButtonUp += _ => FlipCamera();
    }

    /// <summary>
    /// Sets the board entity (on the tabletop map) for this window.
    /// All piece movement and drag coordinates will be taken with respect to this piece.
    /// </summary>
    public void SetBoard(EntityUid? board)
    {
        _board = board;
    }

    /// <summary>
    /// Sets up the parameters of the viewport, hides loading controls and shows tabletop controls.
    /// </summary>
    public void SetPosition(IEye? eye, Vector2i size)
    {
        ScalingVp.Visible = true;
        ScalingVp.Eye = eye;
        ScalingVp.ViewportSize = size;

        FlipButton.Visible = true;

        LoadingLabel.Visible = false;

        _boardBounds = new(size.X / 2.0f, size.Y / 2.0f);
    }

    // Mouse hover events: ignore dragging outside of the window.
    private void OnViewportMouseEnter(GUIMouseHoverEventArgs args)
    {
        _mouseInWindow = true;
    }

    private void OnViewportMouseExit(GUIMouseHoverEventArgs args)
    {
        _mouseInWindow = false;
    }

    // Key down/up events: try to drag pieces if we can.
    private void OnViewportKeyBindDown(GUIBoundKeyEventArgs args)
    {
        if (!_mouseInWindow || _draggedPiece != null)
            return;

        if (args.Function == EngineKeyFunctions.UIClick)
        {
            // Check if piece under cursor, if true, set dragged piece to that.
            if (!TryGetClickedPiece(args.PointerLocation.Position, out var uid))
                return;

            _draggedPiece = uid;
            _lastPosition = GetBoardPosition(args.PointerLocation.Position).Position;
            DragStarted?.Invoke(_draggedPiece.Value);
        }
        else if (args.Function == EngineKeyFunctions.UIRightClick)
        {
            // Spawn a context menu on the piece we're looking at.
            if (!TryGetClickedPiece(args.PointerLocation.Position, out var uid, checkDraggable: false))
                return;

            _uiMan.GetUIController<VerbMenuUIController>().OpenVerbMenu(uid.Value, force: true);
        }
    }

    private void OnViewportKeyBindUp(GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        if (_draggedPiece is null)
            return;

        if (_mouseInWindow
            && _board != null
            && DragMoved != null)
        {
            var boardCoords = GetBoardPosition(args.PointerLocation.Position);
            DragMoved.Invoke(_draggedPiece.Value, boardCoords);
        }

        DragFinished?.Invoke(_draggedPiece.Value);

        _draggedPiece = null;
    }

    // Move event
    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        if (!_mouseInWindow
            || _draggedPiece == null
            || _board == null
            || DragMoved == null)
            return;

        // Get coordinates with respect to the board.
        var boardCoords = GetBoardPosition(args.GlobalPixelPosition.Position);

        // Only send an update if we've moved enough.
        if (Vector2.DistanceSquared(boardCoords.Position, _lastPosition) >= MinDragUpdateSquaredDistance)
        {
            _lastPosition = boardCoords.Position;
            DragMoved.Invoke(_draggedPiece.Value, boardCoords);
        }
    }

    /// <summary>
    /// Convenience function to convert screen coordinates into board-local coordinates.
    /// </summary>
    private EntityCoordinates GetBoardPosition(Vector2 screenPosition)
    {
        var mapCoords = ScalingVp.ScreenToMap(screenPosition);
        var coords = _xform.ToCoordinates(_board!.Value, mapCoords);

        // Clamp to the board's dimensions.
        var clampedX = Math.Clamp(coords.Position.X, -_boardBounds.X, _boardBounds.X);
        var clampedY = Math.Clamp(coords.Position.Y, -_boardBounds.Y, _boardBounds.Y);

        return new(coords.EntityId, new(clampedX, clampedY));
    }

    /// <summary>
    /// Attempts to find a piece at a given set of screen coordinates.
    /// </summary>
    /// <param name="screenPosition">The position, in screen coordinates, to look for entities.</param>
    /// <param name="uid">An output parameter for the entity clicked.  Set to null if nothing was found.</param>
    /// <param name="checkDraggable">Whether or not to check for draggable pieces.</param>
    /// <returns>Whether or not an piece was found under the cursor.</returns>
    private bool TryGetClickedPiece(Vector2 screenPosition, [NotNullWhen(true)] out EntityUid? uid, bool checkDraggable = true)
    {
        uid = null;

        if (_stateMan.CurrentState is not GameplayStateBase screen)
            return false;

        // Find piece under cursor - both left/right click functions depend on it.
        var mapCoords = ScalingVp.ScreenToMap(screenPosition);

        var clicked = screen.GetClickedEntity(mapCoords);

        if (clicked is not { } clickedUid)
            return false;

        if (checkDraggable && !_entMan.HasComponent<TabletopDraggableComponent>(clickedUid))
            return false;

        uid = clickedUid;
        return true;
    }

    // NOTE: if eye rotation ever gets networked, this must change.
    private void FlipCamera()
    {
        if (!_entMan.TryGetComponent<EyeComponent>(_board, out var eye))
            return;

        var newAngle = (eye.Rotation + Angle.FromDegrees(180)).Reduced();
        _eye.SetRotation(_board.Value, newAngle, eye);
    }
}
