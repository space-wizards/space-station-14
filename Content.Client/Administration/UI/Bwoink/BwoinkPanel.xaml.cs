using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.RichText;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.Administration.UI.Bwoink
{
    [GenerateTypedNameReferences]
    public sealed partial class BwoinkPanel : BoxContainer
    {
        [Dependency] private IClipboardManager _clipboard = default!;

        private static readonly Type[] AllowedTags = new Type[]
        {
            typeof(CommandLinkTag),
            typeof(BoldItalicTag),
            typeof(BoldTag),
            typeof(BulletTag),
            typeof(ColorTag),
            typeof(HeadingTag),
            typeof(ItalicTag),
        };

        private readonly Action<string> _messageSender;

        public int Unread { get; private set; } = 0;
        public DateTime LastMessage { get; private set; } = DateTime.MinValue;
        private List<string> PeopleTyping { get; set; } = new();
        public event Action<string>? InputTextChanged;

        public BwoinkPanel(Action<string> messageSender)
        {
            IoCManager.InjectDependencies(this);

            RobustXamlLoader.Load(this);

            var msg = new FormattedMessage();
            msg.PushColor(Color.LightGray);
            msg.AddText(Loc.GetString("bwoink-system-messages-being-relayed-to-discord"));
            msg.Pop();
            RelayedToDiscordLabel.SetMessage(msg);

            _messageSender = messageSender;

            OnVisibilityChanged += c =>
            {
                if (c.Visible)
                    Unread = 0;
            };
            SenderLineEdit.OnTextEntered += Input_OnTextEntered;
            SenderLineEdit.OnTextChanged += Input_OnTextChanged;
            UpdateTypingIndicator();

            CopyLog.OnPressed += _ => CopyMessages();
        }

        private void Input_OnTextEntered(LineEdit.LineEditEventArgs args)
        {
            if (string.IsNullOrWhiteSpace(args.Text))
                return;

            _messageSender.Invoke(args.Text);
            SenderLineEdit.Clear();
        }

        private void Input_OnTextChanged(LineEdit.LineEditEventArgs args)
        {
            InputTextChanged?.Invoke(args.Text);
        }

        public void ReceiveLine(SharedBwoinkSystem.BwoinkTextMessage message)
        {
            if (!Visible)
                Unread++;

            var formatted = new FormattedMessage(1);
            formatted.AddMarkupOrThrow($"[color=gray]{message.SentAt.ToShortTimeString()}[/color] {message.Text}");
            TextOutput.AddMessage(formatted, AllowedTags);
            LastMessage = message.SentAt;
        }

        private void UpdateTypingIndicator()
        {
            var msg = new FormattedMessage();
            msg.PushColor(Color.LightGray);

            var text = PeopleTyping.Count == 0
                ? string.Empty
                : Loc.GetString("bwoink-system-typing-indicator",
                    ("players", string.Join(", ", PeopleTyping)),
                    ("count", PeopleTyping.Count));

            msg.AddText(text);
            msg.Pop();

            TypingIndicator.SetMessage(msg);
        }

        public void UpdatePlayerTyping(string name, bool typing)
        {
            if (typing)
            {
                if (PeopleTyping.Contains(name))
                    return;

                PeopleTyping.Add(name);
                Timer.Spawn(TimeSpan.FromSeconds(10), () =>
                {
                    if (Disposed)
                        return;

                    PeopleTyping.Remove(name);
                    UpdateTypingIndicator();
                });
            }
            else
            {
                PeopleTyping.Remove(name);
            }

            UpdateTypingIndicator();
        }

        /// <summary>
        /// Copies the ahelp text buffer into the user's clipboard.
        /// </summary>
        public void CopyMessages()
        {
            var count = TextOutput.EntryCount;
            if (count == 0)
                return;

            var messages = new List<FormattedMessage>(count);
            for (var i = 0; i < count; i++)
                messages.Add(TextOutput.GetMessage(i));

            var messagesText = messages.ConvertAll(m => m.ToString()).ToArray();

            if (Anonymize.Pressed)
                _AnonymizeNames(messages, messagesText);

            _clipboard.SetText(string.Join("\n", messagesText));
        }

        /// <summary>
        /// Anonymizes the names of players and admins, to avoid leaking personal details.
        /// Does not remove usernames in the body of messages.
        /// </summary>
        /// <param name="messages">The formatted messages in the window.</param>
        /// <param name="messagesText">The text value, which will be edited.</param>
        private void _AnonymizeNames(List<FormattedMessage> messages, string[] messagesText)
        {
            var messagesMarkup = messages.ConvertAll(m => m.ToMarkup());

            var index = 1;
            var participants = new Dictionary<string, (int index, bool isAdmin)>();
            for (var i = 0; i < messages.Count; i++)
            {
                var markupParts = messagesMarkup[i].Split(": ", 2);
                if (markupParts.Length < 2)
                    continue;

                var isAdmin =  markupParts[0].Contains("[color=red]");

                var parts = messagesText[i].Split(": ", 2);
                var name =  parts[0].Split(" ")[^1];

                if (!participants.ContainsKey(name))
                {
                    participants.Add(name, (index, isAdmin));
                    index++;
                }

                if (participants.TryGetValue(name, out var participant))
                    parts[0] = Loc.GetString("admin-ahelp-anonymous-player-name") +
                               $" {participant.index}"
                               + (participant.isAdmin
                                   ? " " + Loc.GetString("admin-ahelp-anonymous-admin-decorator")
                                   : "");

                messagesText[i] = string.Join(": ", parts);
            }
        }

        protected override void Dispose(bool disposing)
        {
            base.Dispose(disposing);

            InputTextChanged = null;
        }
    }
}
