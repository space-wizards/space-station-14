using Content.Client.Administration.Managers;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.Permissions;

[GenerateTypedNameReferences]
public sealed partial class EditAdminWindow : FancyWindow
{
    [Dependency] private IClientAdminManager _adminManager = null!;

    public event Action<int, string?, string, bool>? OnSavePressed;
    public event Action? OnRemovePressed;

    public PermissionsEuiState.AdminData? SourceData;
    public readonly Dictionary<AdminFlags, (Button inherit, Button sub, Button plus)> FlagButtons
        = new();

    public EditAdminWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SaveButton.OnPressed += _ =>
            OnSavePressed?.Invoke(RankOption.SelectedId, TitleEdit.Text, NameEdit.Text, SuspendedCheckbox.Pressed);
        RemoveButton.OnPressed += _ => OnRemovePressed?.Invoke();
    }

    public void SetAdminData(PermissionsEuiState.AdminData? maybeAdminData, Dictionary<int, PermissionsEuiState.AdminRankData> ranks)
    {
        SourceData = maybeAdminData;

        if (maybeAdminData is { } adminData)
        {
            var name = adminData.UserName ?? adminData.UserId.ToString();
            Title = Loc.GetString("permissions-eui-edit-admin-window-edit-admin-label",
                ("admin", name));

            NameEdit.Editable = false;
            NameEdit.Text = name;

            if (adminData.Title != null)
                TitleEdit.Text = adminData.Title;

            if (adminData.Suspended)
                adminData.Suspended = true;
        }

        RankOption.AddItem(Loc.GetString("permissions-eui-edit-admin-window-no-rank-button"), PermissionsEui.NoRank);
        foreach (var (rId, rank) in ranks)
        {
            RankOption.AddItem(rank.Name, rId);
        }

        RankOption.SelectId(maybeAdminData?.RankId ?? PermissionsEui.NoRank);
        RankOption.OnItemSelected += OnRankSelected;

        foreach (var flag in AdminFlagsHelper.AllFlags)
        {
            // Can only grant out perms you also have yourself.
            // Primarily intended to prevent people giving themselves +HOST with +PERMISSIONS but generalized.
            var disable = !_adminManager.HasFlag(flag);
            var flagName = flag.ToString().ToUpper();

            var group = new ButtonGroup();

            var inherit = new Button
            {
                Text = "I",
                StyleClasses = { StyleClass.ButtonOpenRight },
                Disabled = disable,
                Group = group,
            };
            var sub = new Button
            {
                Text = "-",
                StyleClasses = { StyleClass.ButtonOpenBoth },
                Disabled = disable,
                Group = group
            };
            var plus = new Button
            {
                Text = "+",
                StyleClasses = { StyleClass.ButtonOpenLeft },
                Disabled = disable,
                Group = group
            };

            if (maybeAdminData is { } d)
            {
                if ((d.NegFlags & flag) != 0)
                {
                    sub.Pressed = true;
                }
                else if ((d.PosFlags & flag) != 0)
                {
                    plus.Pressed = true;
                }
                else
                {
                    inherit.Pressed = true;
                }
            }
            else
            {
                inherit.Pressed = true;
            }

            FlagGrid.AddChild(new Label { Text = flagName });
            FlagGrid.AddChild(inherit);
            FlagGrid.AddChild(sub);
            FlagGrid.AddChild(plus);

            FlagButtons.Add(flag, (inherit, sub, plus));
        }
    }

    public void CollectSetFlags(out AdminFlags pos, out AdminFlags neg)
    {
        pos = default;
        neg = default;

        foreach (var (flag, (_, s, p)) in FlagButtons)
        {
            if (s.Pressed)
            {
                neg |= flag;
            }
            else if (p.Pressed)
            {
                pos |= flag;
            }
        }
    }

    public int GetSelectedId()
    {
        return RankOption.SelectedId;
    }

    private void OnRankSelected(OptionButton.ItemSelectedEventArgs args)
    {
        RankOption.SelectId(args.Id);
    }
}

