using Content.Client.Administration.Managers;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.Permissions;

[GenerateTypedNameReferences]
public sealed partial class EditAdminRankWindow : FancyWindow
{
    [Dependency] private IClientAdminManager _adminManager = null!;

    public int? SourceId { get; private set; }

    public event Action? OnSavePressed;
    public event Action? OnRemovePressed;

    private readonly Dictionary<AdminFlags, CheckBox> _flagCheckBoxes = new();

    public EditAdminRankWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SaveButton.OnPressed += _ => OnSavePressed?.Invoke();
    }

    public void SetRankData(KeyValuePair<int, PermissionsEuiState.AdminRankData>? data)
    {
        SourceId = data?.Key;

        if (SourceId != null)
        {
            NameEdit.Text = data?.Value.Name ?? string.Empty;
            RemoveButton.Disabled = false;
            RemoveButton.OnPressed += _ => OnRemovePressed?.Invoke();
        }

        foreach (var flag in AdminFlagsHelper.AllFlags)
        {
            // Can only grant out perms you also have yourself.
            // Primarily intended to prevent people giving themselves +HOST with +PERMISSIONS but generalized.
            var disable = !_adminManager.HasFlag(flag);
            var flagName = flag.ToString().ToUpper();

            var checkBox = new CheckBox
            {
                Disabled = disable,
                Text = flagName
            };

            if (data != null && (data.Value.Value.Flags & flag) != 0)
            {
                checkBox.Pressed = true;
            }

            _flagCheckBoxes.Add(flag, checkBox);
            FlagsContainer.AddChild(checkBox);
        }
    }

    public AdminFlags CollectSetFlags()
    {
        AdminFlags flags = default;
        foreach (var (flag, chk) in _flagCheckBoxes)
        {
            if (chk.Pressed)
            {
                flags |= flag;
            }
        }

        return flags;
    }
}

