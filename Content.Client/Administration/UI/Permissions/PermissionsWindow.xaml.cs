using System.Linq;
using System.Numerics;
using Content.Client.Administration.Managers;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.Permissions;

[GenerateTypedNameReferences]
public sealed partial class PermissionsWindow : FancyWindow
{
    [Dependency] private IClientAdminManager _adminManager = null!;

    public event Action? OnAddAdminPressed;
    public event Action? OnAddAdminRankPressed;
    public event Action<PermissionsEuiState.AdminData>? OnEditAdminPressed;
    public event Action<KeyValuePair<int, PermissionsEuiState.AdminRankData>>? OnEditAdminRankPressed;

    public PermissionsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PermissionTabs.SetTabTitle(0, Loc.GetString("permissions-eui-menu-admins-tab-title"));
        PermissionTabs.SetTabTitle(1, Loc.GetString("permissions-eui-menu-admin-ranks-tab-title"));

        AddAdminButton.OnPressed += _ => OnAddAdminPressed?.Invoke();
        AddAdminRankButton.OnPressed += _ => OnAddAdminRankPressed?.Invoke();
    }

    public void UpdateAdmins(IOrderedEnumerable<PermissionsEuiState.AdminData> adminData,
        Dictionary<int, PermissionsEuiState.AdminRankData> ranks)
    {
        AdminsList.RemoveAllChildren();
        foreach (var admin in adminData)
        {
            var name = admin.UserName ?? admin.UserId.ToString();

            AdminsList.AddChild(new Label { Text = name });

            var titleControl = new Label
            {
                Text = admin.Title ?? Loc.GetString("permissions-eui-edit-admin-title-control-text").ToLowerInvariant()
            };
            if (admin.Title == null) // none
            {
                titleControl.StyleClasses.Add(StyleClass.Italic);
            }

            AdminsList.AddChild(titleControl);

            bool italic;
            string rank;
            var combinedFlags = admin.PosFlags;
            if (admin.RankId is { } rankId)
            {
                italic = false;
                var rankData = ranks[rankId];
                rank = rankData.Name;
                combinedFlags |= rankData.Flags;
            }
            else
            {
                italic = true;
                rank = Loc.GetString("permissions-eui-edit-no-rank-text").ToLowerInvariant();
            }

            var rankControl = new Label { Text = rank, HorizontalExpand = true };
            if (italic)
            {
                rankControl.StyleClasses.Add(StyleClass.Italic);
            }

            AdminsList.AddChild(rankControl);

            var flagsText = AdminFlagsHelper.PosNegFlagsText(admin.PosFlags, admin.NegFlags);

            AdminsList.AddChild(new Label
            {
                Text = flagsText,
                HorizontalExpand = true,
                HorizontalAlignment = Control.HAlignment.Center,
            });

            var editButton = new Button { Text = Loc.GetString("permissions-eui-edit-title-button") };
            editButton.OnPressed += _ => OnEditAdminPressed?.Invoke(admin);
            AdminsList.AddChild(editButton);

            if (!_adminManager.HasFlag(combinedFlags))
            {
                editButton.Disabled = true;
                editButton.ToolTip = Loc.GetString("permissions-eui-do-not-have-required-flags-to-edit-admin-tooltip");
            }
        }
    }

    public void UpdateAdminRanks(Dictionary<int, PermissionsEuiState.AdminRankData> ranks)
    {
        AdminRanksList.RemoveAllChildren();

        foreach (var adminRankPair in ranks)
        {
            var rank = adminRankPair.Value;
            var count = BitOperations.PopCount((uint)rank.Flags);

            string flagsText;

            // readability
            // ReSharper disable once ConvertIfStatementToConditionalTernaryExpression
            if (rank.Flags == AdminFlagsHelper.Everything)
                flagsText = Loc.GetString("permissions-eui-edit-admin-window-permission-all");
            else
                flagsText = Loc.GetString("permissions-eui-edit-admin-window-permission-count", ("count", count));

            AdminRanksList.AddChild(new Label { Text = rank.Name});
            AdminRanksList.AddChild(new Label
            {
                Text = flagsText,
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Center,
            });

            var editButton = new Button { Text = Loc.GetString("permissions-eui-edit-admin-rank-button") };
            editButton.OnPressed += _ => OnEditAdminRankPressed?.Invoke(adminRankPair);
            AdminRanksList.AddChild(editButton);

            if (_adminManager.HasFlag(rank.Flags))
                continue;

            editButton.Disabled = true;
            editButton.ToolTip = Loc.GetString("permissions-eui-do-not-have-required-flags-to-edit-rank-tooltip");
        }
    }
}

