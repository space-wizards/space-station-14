using Content.Shared.Administration.AdminAnnounce;
using Content.Shared.Chat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio.Systems;
using Robust.Shared.Configuration;
using Robust.Shared.Map;
using Robust.Shared.Map.Components;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.Administration.UI.AdminAnnounce;

[GenerateTypedNameReferences]
public sealed partial class AdminAnnounceWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<AdminAnnounceEuiMsg.DoAnnounce>? OnAnnounce;

    private static readonly ProtoId<AdminAnnouncementPresetPrototype> DefaultStationPreset = "CentralCommand";
    private static readonly Color ServerColor = ChatChannel.Server.TextColor();

    private AdminAnnounceColorPalette? _paletteWindow;
    private AdminAnnouncePresetWindow? _presetWindow;
    private readonly SharedAudioSystem _audio;
    private EntityUid? _previewStream;

    public AdminAnnounceWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _audio = _entityManager.System<SharedAudioSystem>();

        Announcement.Placeholder = new Rope.Leaf(Loc.GetString("admin-announce-announcement-placeholder"));

        InitAnnounceMethods();
        InitScopeOptions();

        PlayAudio.OnPressed += _ => PlayPreview();
        StopAudio.OnPressed += _ => StopPreview();
        ColorPreview.OnPressed += _ => OpenPalette();
        OpenPresetsButton.OnPressed += _ => OpenPresets();
        SoundPath.OnTextChanged += _ => UpdateControls();
        Announcement.OnTextChanged += _ => UpdateControls();
        AnnounceButton.OnPressed += _ => Announce();
    }

    private void InitAnnounceMethods()
    {
        AnnounceMethod.AddItem(
            Loc.GetString("admin-announce-type-station"),
            (int) AdminAnnounceType.Station);
        AnnounceMethod.AddItem(
            Loc.GetString("admin-announce-type-server"),
            (int) AdminAnnounceType.Server);

        AnnounceMethod.OnItemSelected += args =>
        {
            AnnounceMethod.SelectId(args.Id);
            UpdateFields();
        };

        AnnounceMethod.SelectId((int) AdminAnnounceType.Station);
        UpdateFields();
    }

    private void InitScopeOptions()
    {
        ScopeOption.OnItemSelected += args => ScopeOption.SelectId(args.Id);
        ScopeOption.AddItem(Loc.GetString("admin-announce-scope-global"), (int) MapId.Nullspace);

        var query = _entityManager.AllEntityQueryEnumerator<MapComponent, MetaDataComponent>();

        while (query.MoveNext(out _, out var map, out var metadata))
        {
            ScopeOption.AddItem($"{metadata.EntityName} ({map.MapId})", (int) map.MapId);
        }

        ScopeOption.SelectId((int) MapId.Nullspace);
    }

    private void UpdateFields()
    {
        var isStation = SelectedAnnounceType == AdminAnnounceType.Station;

        Announcer.Editable = isStation;
        SoundPath.Editable = isStation;
        ScopeOption.Visible = isStation;
        OpenPresetsButton.Visible = isStation;

        if (isStation)
        {
            ApplyPreset(_prototypes.Index(DefaultStationPreset));
            return;
        }

        SetColor(ServerColor);
        Announcer.Text = string.Empty;
        Signature.Text = string.Empty;
        SoundPath.Text = string.Empty;

        StopPreview();
        _presetWindow?.Close();

        UpdateControls();
    }

    private void Announce()
    {
        var announcement = Rope.Collapse(Announcement.TextRope);
        if (string.IsNullOrWhiteSpace(announcement))
            return;

        StopPreview();

        OnAnnounce?.Invoke(new AdminAnnounceEuiMsg.DoAnnounce(
            announcement,
            Announcer.Text,
            Signature.Text,
            _announcementColor,
            GetSound(),
            SelectedAnnounceType,
            SelectedMap,
            !KeepWindowOpen.Pressed));
    }

    private AdminAnnounceType SelectedAnnounceType => (AdminAnnounceType) AnnounceMethod.SelectedId;

    private MapId? SelectedMap => ScopeOption.SelectedId == (int) MapId.Nullspace
        ? null
        : new MapId(ScopeOption.SelectedId);

    public override void Close()
    {
        base.Close();

        _paletteWindow?.Close();
        _presetWindow?.Close();
        StopPreview();
    }
}
