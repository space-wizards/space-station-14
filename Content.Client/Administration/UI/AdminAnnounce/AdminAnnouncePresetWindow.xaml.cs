using System.Linq;
using System.Numerics;
using Content.Shared.Administration.AdminAnnounce;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.Administration.UI.AdminAnnounce;

[GenerateTypedNameReferences]
public sealed partial class AdminAnnouncePresetWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<AdminAnnouncementPresetPrototype>? OnPresetSelected;

    public AdminAnnouncePresetWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PopulatePresets();
    }

    private void PopulatePresets()
    {
        PresetContainer.RemoveAllChildren();

        foreach (var preset in _prototypes
                     .EnumeratePrototypes<AdminAnnouncementPresetPrototype>()
                     .OrderBy(preset => preset.ID))
        {
            AddPreset(preset);
        }
    }

    private void AddPreset(AdminAnnouncementPresetPrototype preset)
    {
        var button = new Button
        {
            HorizontalExpand = true
        };

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            HorizontalExpand = true
        };

        var color = new PanelContainer
        {
            MinSize = new Vector2(24, 24),
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = preset.Color
            }
        };

        var label = new Label
        {
            Text = Loc.GetString(preset.Name),
            VerticalAlignment = VAlignment.Center
        };

        content.AddChild(color);
        content.AddChild(label);

        button.AddChild(content);
        button.OnPressed += _ => OnPresetSelected?.Invoke(preset);

        PresetContainer.AddChild(button);
    }
}
