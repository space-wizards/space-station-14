using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.AdminAnnounce;

[GenerateTypedNameReferences]
public sealed partial class AdminAnnounceColorPalette : DefaultWindow
{
    public event Action<Color>? OnColorChanged;

    public AdminAnnounceColorPalette()
    {
        RobustXamlLoader.Load(this);

        Picker.OnColorChanged += color => OnColorChanged?.Invoke(color);
    }

    public void UpdateDisplay(Color color) => Picker.Color = color;
}
