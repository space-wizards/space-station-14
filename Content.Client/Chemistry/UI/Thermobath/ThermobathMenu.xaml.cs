using Content.Client.UserInterface.Controls;
using Content.Shared.Temperature.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Chemistry.UI.Thermobath;

[GenerateTypedNameReferences]
public sealed partial class ThermobathMenu : FancyWindow
{
    private static readonly Color PowerOnColor = Color.FromHex("#00FF00");
    private static readonly Color HeatingColor = Color.FromHex("#FF6A00");
    private static readonly Color CoolingColor = Color.FromHex("#00AAFF");
    private static readonly Color DisabledColor = Color.FromHex("#444444");

    private readonly StyleBoxFlat _powerIndicatorStyle;
    private readonly StyleBoxFlat _heatingIndicatorStyle;
    private readonly StyleBoxFlat _coolingIndicatorStyle;
    private readonly FloatSpinBox _setpointInput;

    private bool _powered;
    private float _minTemperature;
    private float _maxTemperature;
    private float _currentTemperature;
    private float _setpoint;
    private ThermoregulatorActiveMode _activeMode;

    public event Action<bool>? OnPowerChanged;
    public event Action<float>? OnSetpointChanged;
    public event Action<ThermoregulatorMode>? OnModeChanged;

    public ThermobathMenu()
    {
        RobustXamlLoader.Load(this);

        _setpointInput = new FloatSpinBox(1f, 1)
        {
            SetWidth = 145,
            HorizontalExpand = true
        };
        SetpointInputContainer.AddChild(_setpointInput);

        _powerIndicatorStyle = new StyleBoxFlat
        {
            BackgroundColor = DisabledColor,
        };
        PowerIndicator.PanelOverride = _powerIndicatorStyle;

        _heatingIndicatorStyle = new StyleBoxFlat
        {
            BackgroundColor = DisabledColor,
        };
        HeatingIndicator.PanelOverride = _heatingIndicatorStyle;

        _coolingIndicatorStyle = new StyleBoxFlat
        {
            BackgroundColor = DisabledColor,
        };
        CoolingIndicator.PanelOverride = _coolingIndicatorStyle;

        PowerButton.StateChanged += enabled => OnPowerChanged?.Invoke(enabled);

        _setpointInput.IsValid = float.IsFinite;
        _setpointInput.OnValueChanged += OnSetpointInputChanged;

        ModeSlider.OnValueChanged += value => OnModeChanged?.Invoke((ThermoregulatorMode) value.Value);

        UpdateTemperatureDisplay();
        UpdateSetpointDisplay();
        UpdateSolutionTemperatureDisplay(null);
        UpdateStatusIndicators();
    }

    public void SetPowered(bool powered)
    {
        if (_powered == powered)
            return;

        _powered = powered;
        UpdateStatusIndicators();
    }

    public void SetPowerSwitchState(bool enabled) => PowerButton.IsOn = enabled;

    public void SetTemperatureLimits(float min, float max)
    {
        _minTemperature = MathF.Ceiling(min * 10) / 10;
        _maxTemperature = MathF.Floor(max * 10) / 10;
    }

    public void SetSolutionTemperature(float? temperature) => UpdateSolutionTemperatureDisplay(temperature);

    public void SetCurrentTemperature(float temperature)
    {
        if (MathHelper.CloseTo(_currentTemperature, temperature))
            return;

        _currentTemperature = temperature;
        UpdateTemperatureDisplay();
    }

    public void SetSetpoint(float setpoint)
    {
        if (MathHelper.CloseTo(_setpoint, setpoint))
            return;

        _setpoint = setpoint;
        UpdateSetpointDisplay();
    }

    public void SetMode(ThermoregulatorMode mode)
    {
        if ((int) mode == (int) Math.Round(ModeSlider.Value))
            return;

        ModeSlider.SetValueWithoutEvent((int) mode);
    }

    public void SetActiveMode(ThermoregulatorActiveMode mode)
    {
        if (_activeMode == mode)
            return;

        _activeMode = mode;
        UpdateStatusIndicators();
    }

    public void SetBeakerPresent(bool hasBeaker) => BeakerStatusLabel.Visible = !hasBeaker;

    private void OnSetpointInputChanged(FloatSpinBox.FloatSpinBoxEventArgs args)
    {
        var setpoint = Math.Clamp(MathF.Round(args.Value, 1), _minTemperature, _maxTemperature);
        _setpointInput.Value = setpoint;
        if (MathHelper.CloseTo(_setpoint, setpoint))
            return;

        SetSetpoint(setpoint);
        OnSetpointChanged?.Invoke(setpoint);
    }

    private void UpdateTemperatureDisplay() => SetTemperatureDisplay(TemperatureVfd, _currentTemperature);

    private void UpdateSetpointDisplay()
    {
        SetTemperatureDisplay(SetpointVfd, _setpoint);
        if (!_setpointInput.HasKeyboardFocus())
            _setpointInput.Value = _setpoint;
    }

    private void UpdateSolutionTemperatureDisplay(float? temperature)
    {
        if (temperature is not null)
        {
            SetTemperatureDisplay(SolutionTemperatureVfd, temperature.Value);
            SolutionTemperatureVfd.ClearAllBitmaskOverrides();
        }
        else
        {
            SolutionTemperatureVfd.SetGlobalBitmaskOverride(0b1000000);
            SolutionTemperatureVfd.ShowDecimalPoint = false;
        }
    }

    private static void SetTemperatureDisplay(SegmentDisplay display, float temperature)
    {
        display.Value = (int) MathF.Round(temperature * 10);
        display.ShowDecimalPoint = true;
        display.DecimalPosition = 1;
    }

    private void UpdateStatusIndicators()
    {
        _powerIndicatorStyle.BackgroundColor = _powered ? PowerOnColor : DisabledColor;
        _coolingIndicatorStyle.BackgroundColor = _powered && _activeMode == ThermoregulatorActiveMode.Cooling
            ? CoolingColor
            : DisabledColor;
        _heatingIndicatorStyle.BackgroundColor = _powered && _activeMode == ThermoregulatorActiveMode.Heating
            ? HeatingColor
            : DisabledColor;
    }
}
