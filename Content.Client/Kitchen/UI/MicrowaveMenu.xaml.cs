using Content.Client.Stylesheets;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client.Kitchen.UI;

[GenerateTypedNameReferences]
public sealed partial class MicrowaveMenu : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    private const int CookTimeButtonCount = 6;
    private const int CookTimeStepSeconds = 5;
    private const int StyleBreakButtonIndex = 4;

    public event Action? OnStartCook;
    public event Action? OnEjectAll;
    public event Action<int, uint>? OnCookTimeSelected;
    public event Action<EntityUid>? OnEjectSolid;

    private ButtonGroup CookTimeButtonGroup { get; }

    private bool _isBusy;
    private TimeSpan _currentCookTimeEnd;
    private uint? _lastSecondsUpdate;

    public MicrowaveMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        StartButton.OnPressed += _ => OnStartCook?.Invoke();
        EjectButton.OnPressed += _ => OnEjectAll?.Invoke();

        CookTimeButtonGroup = new ButtonGroup();
        InstantCookButton.Group = CookTimeButtonGroup;
        InstantCookButton.OnPressed += _ => OnCookTimeSelected?.Invoke(0, 0);

        for (var i = 1; i <= CookTimeButtonCount; i++)
        {
            var newButton = CreateCookTimeButton(i);
            CookTimeButtonGrid.AddChild(newButton);
        }

        UpdateTimerDisplay(0);
    }

    public void UpdateUi(IReadOnlyList<EntityUid> contents, bool isBusy, TimeSpan cookTimeEnd,
        uint currentCookTime, int activeButtonIndex)
    {
        _isBusy = isBusy;
        _currentCookTimeEnd = cookTimeEnd;

        IngredientGridHelper.PopulateIngredientsGrid(
            IngredientsGrid,
            _entityManager,
            contents,
            entity => OnEjectSolid?.Invoke(entity));

        var hasIngredients = IngredientsGrid.ChildCount > 0;
        var controlsDisabled = _isBusy || !hasIngredients;

        DisableCookingPanelOverlay.Visible = _isBusy;
        StartButton.Disabled = controlsDisabled;
        EjectButton.Disabled = controlsDisabled;
        IngredientsEmptyLabel.Visible = !hasIngredients;
        IngredientsBusyBackground.Visible = _isBusy && hasIngredients;

        if (_isBusy)
            UpdateRemainingTime();
        else
            UpdateTimerDisplay(currentCookTime);

        if (activeButtonIndex == 0)
        {
            InstantCookButton.Pressed = true;
        }
        else
        {
            var buttonIndex = activeButtonIndex - 1;
            if (buttonIndex >= 0 && buttonIndex < CookTimeButtonGrid.ChildCount)
                ((Button) CookTimeButtonGrid.GetChild(buttonIndex)).Pressed = true;
        }
    }

    private Button CreateCookTimeButton(int index)
    {
        var cookTime = (uint) (index * CookTimeStepSeconds);
        var newButton = new Button
        {
            Text = cookTime.ToString(),
            ToggleMode = true,
            Group = CookTimeButtonGroup,
            HorizontalExpand = true,
        };

        newButton.StyleClasses.Add(index == StyleBreakButtonIndex
            ? StyleClass.ButtonOpenRight
            : StyleClass.ButtonOpenBoth);

        newButton.OnPressed += _ => OnCookTimeSelected?.Invoke(index, cookTime);
        return newButton;
    }

    private void UpdateTimerDisplay(uint seconds)
    {
        if (_lastSecondsUpdate == seconds)
            return;

        _lastSecondsUpdate = seconds;
        var minutes = seconds / 60;
        var secs = seconds % 60;
        TimerDisplay.Value = (int) (minutes * 100 + secs);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!_isBusy)
            return;

        UpdateRemainingTime();
    }

    private void UpdateRemainingTime()
    {
        var remaining = Math.Max((_currentCookTimeEnd - _timing.CurTime).TotalSeconds, 0);
        // Don't tick the display down until the current second has actually elapsed.
        UpdateTimerDisplay((uint) Math.Ceiling(remaining));
    }
}
