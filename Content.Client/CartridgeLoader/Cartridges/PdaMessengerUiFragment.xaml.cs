using System.Linq;
using Content.Shared.CartridgeLoader.Cartridges;
using Content.Shared.CCVar;
using Content.Shared.PdaMessenger;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Utility;

namespace Content.Client.CartridgeLoader.Cartridges;

/// <summary>
///     The messenger program: a list of conversations, a contact list to start new ones, and a chat view.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaMessengerUiFragment : BoxContainer
{
    [Dependency] private IConfigurationManager _config = default!;

    private PdaMessengerUiState? _state;
    private string? _recipientId;

    /// <summary>
    ///     Why the user can't send in the open chat, from the last state, or null if they can.
    /// </summary>
    private string? _blocked;

    /// <summary>
    ///     The user whose conversations are shown. When the ID card changes, the view goes back to the start.
    /// </summary>
    private string? _shownUserId;

    /// <summary>
    ///     The conversation and newest message the chat history was last drawn for, so it's only redrawn
    ///     when something changed and the scroll position isn't lost.
    /// </summary>
    private (string? Id, int NewestMessage) _drawnHistory;

    public event Action<string, string>? OnSend;
    public event Action<string?>? OnOpenConversation;

    public PdaMessengerUiFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        NewMessageButton.OnPressed += _ => ShowView(ContactsView);
        ContactsBackButton.OnPressed += _ => ShowView(ConversationsView);
        ChatBackButton.OnPressed += _ => CloseChat();
        SearchInput.OnTextChanged += _ => UpdateContacts();

        MessageInput.IsValid = text => text.Length <= _config.GetCVar(CCVars.PdaMessengerMaxMessageLength);
        MessageInput.OnTextChanged += _ => UpdateSendAvailability();
        MessageInput.OnTextEntered += _ => TrySend();
        SendButton.OnPressed += _ => TrySend();
    }

    public void UpdateState(PdaMessengerUiState state)
    {
        _state = state;

        if (state.Self?.UserId != _shownUserId)
        {
            _shownUserId = state.Self?.UserId;
            _recipientId = null;
            _drawnHistory = default;
            SearchInput.Clear();
            MessageInput.Clear();
            ShowView(ConversationsView);
        }

        StatusLabel.Text = Loc.GetString(state.Status switch
        {
            PdaMessengerStatus.Connected => "pda-messenger-ui-status-connected",
            PdaMessengerStatus.NoId => "pda-messenger-ui-status-no-id",
            PdaMessengerStatus.NoServer => "pda-messenger-ui-status-no-server",
            _ => "pda-messenger-ui-status-disabled",
        }, ("name", state.Self?.Name ?? string.Empty));

        NewMessageButton.Disabled = state.Status != PdaMessengerStatus.Connected;

        UpdateConversations();
        UpdateContacts();
        if (ChatView.Visible)
            UpdateChat();
    }

    private void ShowView(Control view)
    {
        ConversationsView.Visible = view == ConversationsView;
        ContactsView.Visible = view == ContactsView;
        ChatView.Visible = view == ChatView;
    }

    private void UpdateConversations()
    {
        ConversationList.RemoveAllChildren();
        if (_state is not { } state)
            return;

        if (state.Conversations.Count == 0)
        {
            ConversationList.AddChild(new Label
            {
                Text = Loc.GetString("pda-messenger-ui-no-conversations"),
                StyleClasses = { "LabelSubText" },
            });
        }

        foreach (var conversation in state.Conversations)
        {
            if (GetOther(conversation) is not { } other)
                continue;

            var title = GetDisplayName(state.Contacts.FirstOrNull(contact => contact.UserId == other.UserId) ?? other);
            var unread = state.Unread.GetValueOrDefault(conversation.Id);
            if (unread > 0)
                title = Loc.GetString("pda-messenger-ui-unread", ("title", title), ("count", unread));

            var preview = conversation.Messages.Count > 0 ? conversation.Messages[^1].Text : string.Empty;

            var button = new Button { HorizontalExpand = true };
            var labels = new BoxContainer { Orientation = LayoutOrientation.Vertical };
            labels.AddChild(new Label { Text = title, ClipText = true });
            labels.AddChild(new Label { Text = preview, ClipText = true, StyleClasses = { "LabelSubText" } });
            button.AddChild(labels);
            button.OnPressed += _ => OpenChat(other.UserId);
            ConversationList.AddChild(button);
        }
    }

    private void UpdateContacts()
    {
        ContactList.RemoveAllChildren();
        if (_state is not { } state)
            return;

        var search = SearchInput.Text.Trim();
        var contacts = state.Contacts
            .Where(contact => search.Length == 0
                              || contact.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                              || contact.JobTitle.Contains(search, StringComparison.CurrentCultureIgnoreCase))
            .OrderBy(contact => contact.Name, StringComparer.CurrentCultureIgnoreCase)
            .ToList();

        if (contacts.Count == 0)
        {
            ContactList.AddChild(new Label
            {
                Text = Loc.GetString("pda-messenger-ui-no-contacts"),
                StyleClasses = { "LabelSubText" },
            });
        }

        foreach (var contact in contacts)
        {
            var button = new Button { Text = GetDisplayName(contact), ClipText = true, HorizontalExpand = true };
            button.OnPressed += _ => OpenChat(contact.UserId);
            ContactList.AddChild(button);
        }
    }

    private void OpenChat(string recipientId)
    {
        _recipientId = recipientId;
        _drawnHistory = default;
        MessageInput.Clear();
        ShowView(ChatView);
        UpdateChat();
        OnOpenConversation?.Invoke(GetConversationId());
    }

    private void CloseChat()
    {
        _recipientId = null;
        ShowView(ConversationsView);
        OnOpenConversation?.Invoke(null);
    }

    private void UpdateChat()
    {
        if (_state is not { } state || _recipientId is not { } recipientId)
            return;

        var conversationId = GetConversationId();
        var conversation = state.Conversations.FirstOrDefault(c => c.Id == conversationId);

        // Online contacts have the current name and job; the conversation remembers them for when they're offline.
        var online = state.Contacts.FirstOrNull(contact => contact.UserId == recipientId);
        var recipient = online ?? conversation?.Participants.FirstOrNull(contact => contact.UserId == recipientId);
        ChatTitle.Text = recipient is { } known ? GetDisplayName(known) : Loc.GetString("pda-messenger-unknown-name");

        var messages = conversation?.Messages ?? new List<PdaMessengerMessage>();
        var newestMessage = messages.Count > 0 ? messages[^1].Id : -1;
        if (_drawnHistory != (conversationId, newestMessage))
        {
            _drawnHistory = (conversationId, newestMessage);
            History.Clear();
            foreach (var message in messages)
            {
                History.AddMessage(FormatMessage(message, conversation!));
            }
        }

        _blocked = state.Status != PdaMessengerStatus.Connected ? StatusLabel.Text
            : state.SendBlocked is { } reason ? Loc.GetString(reason)
            : online == null ? Loc.GetString("pda-messenger-ui-offline", ("name", ChatTitle.Text))
            : null;

        UpdateSendAvailability();
    }

    /// <summary>
    ///     Shows why the user can't send. A block disables the whole input; a message over the length limit
    ///     only disables Send, so it can be shortened.
    /// </summary>
    private void UpdateSendAvailability()
    {
        var max = _config.GetCVar(CCVars.PdaMessengerMaxMessageLength);
        var length = MessageInput.Text.Trim().Length;
        var reason = _blocked
                     ?? (length > max ? Loc.GetString("pda-messenger-ui-too-long", ("length", length), ("max", max)) : null);

        BlockedLabel.Text = reason ?? string.Empty;
        BlockedLabel.Visible = reason != null;
        MessageInput.Editable = _blocked == null;
        SendButton.Disabled = reason != null;
    }

    private void TrySend()
    {
        UpdateSendAvailability();

        var text = MessageInput.Text.Trim();
        if (SendButton.Disabled || _recipientId is not { } recipientId || text.Length == 0)
            return;

        OnSend?.Invoke(recipientId, text);
        MessageInput.Clear();
    }

    private FormattedMessage FormatMessage(PdaMessengerMessage message, PdaMessengerConversation conversation)
    {
        var sender = conversation.Participants.FirstOrNull(contact => contact.UserId == message.SenderId);
        var name = message.SenderId == _state?.Self?.UserId
            ? Loc.GetString("pda-messenger-ui-you")
            : sender?.Name ?? Loc.GetString("pda-messenger-unknown-name");

        // Names and text are player-written, so they're escaped before going into the markup.
        return FormattedMessage.FromMarkupOrThrow(Loc.GetString("pda-messenger-ui-message",
            ("time", message.SentAt.ToString(@"hh\:mm")),
            ("sender", FormattedMessage.EscapeText(name)),
            ("text", FormattedMessage.EscapeText(message.Text))));
    }

    private string? GetConversationId()
    {
        return _state?.Self is { } self && _recipientId != null
            ? PdaMessengerConversation.GetId(self.UserId, _recipientId)
            : null;
    }

    private PdaMessengerContact? GetOther(PdaMessengerConversation conversation)
    {
        var selfId = _state?.Self?.UserId;
        return conversation.Participants.FirstOrNull(contact => contact.UserId != selfId);
    }

    private static string GetDisplayName(PdaMessengerContact contact)
    {
        return string.IsNullOrEmpty(contact.JobTitle)
            ? contact.Name
            : Loc.GetString("pda-messenger-contact-name", ("name", contact.Name), ("job", contact.JobTitle));
    }
}
