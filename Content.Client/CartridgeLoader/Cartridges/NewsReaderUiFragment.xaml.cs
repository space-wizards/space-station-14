using Content.Client.MassMedia.Ui;
using Content.Client.Message;
using Content.Client.RichText;
using Content.Client.UserInterface.RichText;
using Content.Shared.MassMedia.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.RichText;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NewsReaderUiFragment : BoxContainer
{
    public event Action? OnNextButtonPressed;
    public event Action? OnPrevButtonPressed;
    public event Action? OnNotificationSwitchPressed;
    public event Action<NewsReactionType>? OnReactionPressed;
    public event Action<string>? OnCommentSubmitted;

    public NewsReaderUiFragment()
    {
        RobustXamlLoader.Load(this);

        Next.OnPressed += _ => OnNextButtonPressed?.Invoke();
        Prev.OnPressed += _ => OnPrevButtonPressed?.Invoke();
        NotificationSwitch.OnPressed += _ => OnNotificationSwitchPressed?.Invoke();

        ReactionUpvote.OnPressed += _ => OnReactionPressed?.Invoke(NewsReactionType.Upvote);
        ReactionDownvote.OnPressed += _ => OnReactionPressed?.Invoke(NewsReactionType.Downvote);
        ReactionLaugh.OnPressed += _ => OnReactionPressed?.Invoke(NewsReactionType.Laugh);
        ReactionShock.OnPressed += _ => OnReactionPressed?.Invoke(NewsReactionType.Shock);
        ReactionHeart.OnPressed += _ => OnReactionPressed?.Invoke(NewsReactionType.Heart);

        CommentSubmit.OnPressed += _ => SubmitComment();
        CommentInput.OnTextEntered += _ => SubmitComment();
        CommentInput.OnTextChanged += OnCommentInputChanged;
    }

    private void OnCommentInputChanged(LineEdit.LineEditEventArgs args)
    {
        if (args.Text.Length > SharedNewsSystem.MaxCommentLength)
        {
            CommentInput.ModulateSelfOverride = Color.Red;
            CommentInput.ToolTip = Loc.GetString("news-writer-text-length-exceeded");
            CommentSubmit.Disabled = true;
        }
        else
        {
            CommentInput.ModulateSelfOverride = null;
            CommentInput.ToolTip = string.Empty;
            CommentSubmit.Disabled = false;
        }
    }

    private void SubmitComment()
    {
        var text = CommentInput.Text.Trim();
        if (text.Length == 0 || text.Length > SharedNewsSystem.MaxCommentLength)
            return;

        OnCommentSubmitted?.Invoke(text);
        CommentInput.Text = string.Empty;
    }

    public void UpdateState(
        NewsArticle article,
        int targetNum,
        int totalNum,
        bool notificationOn,
        HashSet<NewsReactionType>? activeReactions = null)
    {
        PageNum.Visible = true;
        PageText.Visible = true;
        ShareTime.Visible = true;
        Author.Visible = true;
        ReactionsContainer.Visible = true;
        CommentsSection.Visible = true;
        CommentInputContainer.Visible = true;

        PageName.Text = article.Title;
        PageText.SetMessage(FormattedMessage.FromMarkupPermissive(article.Content), UserFormattableTags.BaseAllowedTags);

        PageNum.Text = $"{targetNum}/{totalNum}";

        NotificationSwitch.Text = Loc.GetString(notificationOn ? "news-read-ui-notification-on" : "news-read-ui-notification-off");

        var shareTime = article.ShareTime.ToString(@"hh\:mm\:ss");
        ShareTime.SetMarkup(Loc.GetString("news-read-ui-time-prefix-text") + " " + shareTime);

        var author = Loc.GetString("news-read-ui-author-prefix") + " " + (article.Author ?? Loc.GetString("news-read-ui-no-author"));
        Author.SetMessage(FormattedMessage.FromMarkupPermissive(author), UserFormattableTags.BaseAllowedTags);

        Prev.Disabled = targetNum <= 1;
        Next.Disabled = targetNum >= totalNum;

        UpdateReactions(article, activeReactions);
        UpdateComments(article);
    }

    private void UpdateReactions(NewsArticle article, HashSet<NewsReactionType>? activeReactions)
    {
        var counts = article.ReactionCounts;

        SetReactionButton(ReactionUpvote, NewsReactionType.Upvote, "news-read-ui-reaction-upvote", counts, activeReactions);
        SetReactionButton(ReactionDownvote, NewsReactionType.Downvote, "news-read-ui-reaction-downvote", counts, activeReactions);
        SetReactionButton(ReactionLaugh, NewsReactionType.Laugh, "news-read-ui-reaction-laugh", counts, activeReactions);
        SetReactionButton(ReactionShock, NewsReactionType.Shock, "news-read-ui-reaction-shock", counts, activeReactions);
        SetReactionButton(ReactionHeart, NewsReactionType.Heart, "news-read-ui-reaction-heart", counts, activeReactions);
    }

    private static void SetReactionButton(
        Button button,
        NewsReactionType type,
        string symbolLocId,
        Dictionary<NewsReactionType, int>? counts,
        HashSet<NewsReactionType>? activeReactions)
    {
        var count = counts != null && counts.TryGetValue(type, out var c) ? c : 0;
        var symbol = Loc.GetString(symbolLocId);
        button.Text = Loc.GetString("news-read-ui-reaction-button-format", ("symbol", symbol), ("count", count));
        button.Pressed = activeReactions != null && activeReactions.Contains(type);
    }

    private void UpdateComments(NewsArticle article)
    {
        CommentsContainer.Children.Clear();
        var comments = article.Comments;
        var count = comments?.Count ?? 0;

        if (article.CommentsLocked)
        {
            CommentsHeader.Text = Loc.GetString("news-read-ui-comments-header-locked", ("count", count));
            CommentInput.Editable = false;
            CommentInput.PlaceHolder = Loc.GetString("news-read-ui-comments-locked-placeholder");
            CommentSubmit.Disabled = true;
        }
        else if (count >= SharedNewsSystem.MaxCommentsPerArticle)
        {
            CommentsHeader.Text = Loc.GetString("news-read-ui-comments-header", ("count", count));
            CommentInput.Editable = false;
            CommentInput.PlaceHolder = Loc.GetString("news-read-ui-comments-full-placeholder");
            CommentSubmit.Disabled = true;
        }
        else
        {
            CommentsHeader.Text = Loc.GetString("news-read-ui-comments-header", ("count", count));
            CommentInput.Editable = true;
            CommentInput.PlaceHolder = Loc.GetString("news-read-ui-comment-placeholder");
            CommentSubmit.Disabled = CommentInput.Text.Length > SharedNewsSystem.MaxCommentLength;
        }

        if (comments == null || comments.Count == 0)
        {
            var emptyLabel = new Label
            {
                Text = Loc.GetString("news-read-ui-no-comments"),
                FontColorOverride = Color.FromHex("#808080")
            };
            emptyLabel.StyleClasses.Add("LabelSmall");
            CommentsContainer.AddChild(emptyLabel);
            return;
        }

        foreach (var comment in comments)
        {
            CommentsContainer.AddChild(new NewsCommentEntry(comment, canDelete: false));
        }
    }

    public void UpdateEmptyState(bool notificationOn)
    {
        PageNum.Visible = false;
        PageText.Visible = false;
        ShareTime.Visible = false;
        Author.Visible = false;
        ReactionsContainer.Visible = false;
        CommentsSection.Visible = false;
        CommentInputContainer.Visible = false;

        PageName.Text = Loc.GetString("news-read-ui-not-found-text");

        NotificationSwitch.Text = Loc.GetString(notificationOn ? "news-read-ui-notification-on" : "news-read-ui-notification-off");
    }
}

