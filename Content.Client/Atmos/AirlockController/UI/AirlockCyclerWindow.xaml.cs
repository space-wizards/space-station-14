#region

using Content.Client.UserInterface.Controls;
using Content.Shared.Atmos.AirlockController;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

#endregion

namespace Content.Client.Atmos.AirlockController.UI;

[GenerateTypedNameReferences]
public sealed partial class AirlockCyclerWindow : FancyWindow
{
    public event Action? CycleRequested;

    public AirlockCyclerWindow()
    {
        RobustXamlLoader.Load(this);

        CCycleButton.OnPressed += _ => CycleRequested?.Invoke();
    }

    public void SetEntity(EntityUid uid)
    {
        CStatus.SetEntity(uid);
    }

    public void UpdateState(AirlockCyclerUiState state)
    {
        var status = state.Status;
        var idle = status.State == AirlockCycleState.Idle;

        CStatus.Update(status, state.ChamberPressure, state.Bound ? null : "airlock-cycler-ui-unbound");

        // Nothing to call for if the chamber is already here
        CCycleButton.Disabled = !state.Bound
                                || !idle
                                || status.Maintenance
                                || status.Side == state.Side;

        CCycleButton.Text = Loc.GetString(state.Side == AirlockSide.A
            ? "airlock-controller-ui-cycle-a"
            : "airlock-controller-ui-cycle-b");
    }
}
