using Content.Shared.Atmos.AirlockController;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Atmos.AirlockController.UI.Widgets;

/// <summary>
/// Picks a side, or none for the airlock.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AirlockSideSelector : BoxContainer
{
    public Action<AirlockSide?>? OnSideSelected;

    public AirlockSideSelector()
    {
        RobustXamlLoader.Load(this);

        NoneButton.OnPressed += _ => OnSideSelected?.Invoke(null);
        SideAButton.OnPressed += _ => OnSideSelected?.Invoke(AirlockSide.A);
        SideBButton.OnPressed += _ => OnSideSelected?.Invoke(AirlockSide.B);
    }

    public void SetSelection(AirlockSide? side)
    {
        NoneButton.Pressed = side == null;
        SideAButton.Pressed = side == AirlockSide.A;
        SideBButton.Pressed = side == AirlockSide.B;
    }
}
