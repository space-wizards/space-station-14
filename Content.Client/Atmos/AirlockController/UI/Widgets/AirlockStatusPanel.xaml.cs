using Content.Client.Message;
using Content.Shared.Atmos.AirlockController;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Atmos.AirlockController.UI.Widgets;

/// <summary>
/// State, side, pressure and the stall stripe, shared by the controller and its panels
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AirlockStatusPanel : BoxContainer
{
    public AirlockStatusPanel()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetEntity(EntityUid uid)
    {
        EntityView.SetEntity(uid);
    }

    public void Update(AirlockCycleStatus status, float? pressure, string? stateOverride = null)
    {
        CStateLabel.SetMarkup(Loc.GetString(stateOverride ?? AirlockControllerLocale.StateKey(status.State)));
        CSideLabel.SetMarkup(Loc.GetString(AirlockControllerLocale.SideKey(status.Side)));
        CPressureLabel.SetMarkup(pressure is { } value
            ? Loc.GetString("airlock-controller-ui-pressure-value", ("pressure", $"{value:0.#}"))
            : Loc.GetString("airlock-controller-ui-pressure-unknown"));

        // A stall reports the problem without state change
        CStallStripe.Visible = status.Stall != null;
        if (status.Stall is { } reason)
            CStallLabel.SetMarkup(Loc.GetString(AirlockControllerLocale.StallKey(reason)));
    }
}
