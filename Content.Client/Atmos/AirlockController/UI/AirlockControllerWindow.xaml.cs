using Content.Client.UserInterface.Controls;
using Content.Shared.Atmos.AirlockController;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Atmos.AirlockController.UI;

[GenerateTypedNameReferences]
public sealed partial class AirlockControllerWindow : FancyWindow
{
    public event Action<AirlockSide>? CycleRequested;
    public event Action? CancelRequested;
    public event Action? ConfigRequested;

    public AirlockControllerWindow()
    {
        RobustXamlLoader.Load(this);

        CCycleAButton.OnPressed += _ => CycleRequested?.Invoke(AirlockSide.A);
        CCycleBButton.OnPressed += _ => CycleRequested?.Invoke(AirlockSide.B);
        CCancelButton.OnPressed += _ => CancelRequested?.Invoke();
        CConfigButton.OnPressed += _ => ConfigRequested?.Invoke();
    }

    public void SetEntity(EntityUid uid)
    {
        CStatus.SetEntity(uid);
    }

    public void SetConfigAllowed(bool allowed)
    {
        CConfigButton.Disabled = !allowed;
    }

    public void UpdateState(AirlockControllerUiState state)
    {
        var status = state.Status;
        var idle = status.State == AirlockCycleState.Idle;

        CStatus.Update(status, state.ChamberPressure);

        // You can only cycle to the side you aren't already at
        CCycleAButton.Disabled = !idle || status.Side == AirlockSide.A || status.Maintenance;
        CCycleBButton.Disabled = !idle || status.Side == AirlockSide.B || status.Maintenance;

        CCancelButton.Disabled = idle || status.Maintenance;
        CCancelButton.Text = Loc.GetString(state.CancelRequested
            ? "airlock-controller-ui-cancel-emergency"
            : "airlock-controller-ui-cancel");
    }
}
