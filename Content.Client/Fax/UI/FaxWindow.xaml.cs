using Content.Shared.DeviceNetwork;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Fax.UI;

[GenerateTypedNameReferences]
public sealed partial class FaxWindow : DefaultWindow
{
    public event Action? FileButtonPressed;
    public event Action? PaperButtonPressed;
    public event Action? CopyButtonPressed;
    public event Action? SendButtonPressed;
    public event Action? RefreshButtonPressed;
    public event Action<DeviceAddress>? PeerSelected;

    public bool OfficePaper;

    public FaxWindow()
    {
        RobustXamlLoader.Load(this);

        PaperButtonPressed += OnPaperButtonPressed;

        FileButton.OnPressed += _ => FileButtonPressed?.Invoke();
        PaperButton.OnPressed += _ => PaperButtonPressed?.Invoke();
        CopyButton.OnPressed += _ => CopyButtonPressed?.Invoke();
        SendButton.OnPressed += _ => SendButtonPressed?.Invoke();
        RefreshButton.OnPressed += _ => RefreshButtonPressed?.Invoke();
        PeerSelector.OnItemSelected += args =>
            PeerSelected?.Invoke((DeviceAddress)args.Button.GetItemMetadata(args.Id)!);
    }

    /// <summary>
    /// Updates the window with new state.
    /// </summary>
    /// <param name="copyDisabled">Whether the copy button is disabled.</param>
    /// <param name="fileDisabled">Whether printing from a file is disabled.</param>
    /// <param name="sendDisabled">Whether the send button is disabled.</param>
    /// <param name="faxName">The name of the fax machine.</param>
    /// <param name="paper">Readable name of the paper enity inside the fax machine, or null if there is none.</param>
    /// <param name="knownFaxes">Dictionary of known fax machine names by their address.</param>
    /// <param name="destination">Currently selected fax address to send to.</param>
    public void Update(bool copyDisabled, bool fileDisabled, bool sendDisabled, string faxName, string? paper, Dictionary<DeviceAddress, string> knownFaxes, DeviceAddress? destination)
    {
        CopyButton.Disabled = copyDisabled;
        FileButton.Disabled = fileDisabled;
        SendButton.Disabled = sendDisabled;
        FromLabel.Text = faxName;

        if (paper == null)
        {
            PaperStatusLabel.FontColorOverride = Color.Red;
            PaperStatusLabel.Text = Loc.GetString("fax-machine-ui-paper-not-inserted");
        }
        else
        {
            PaperStatusLabel.FontColorOverride = Color.Green;
            PaperStatusLabel.Text = Loc.GetString("fax-machine-ui-paper-inserted", ("paper", paper));
        }

        PeerSelector.Clear();
        if (knownFaxes.Count == 0)
        {
            PeerSelector.AddItem(Loc.GetString("fax-machine-ui-no-peers"));
            PeerSelector.Select(0);
            PeerSelector.Disabled = true;
        }
        else
        {
            PeerSelector.Disabled = false;
            foreach (var (address, name) in knownFaxes)
            {
                var id = AddPeerSelect(name, address);
                if (address == destination)
                    PeerSelector.Select(id);
            }
        }
    }

    private int AddPeerSelect(string name, DeviceAddress address)
    {
        PeerSelector.AddItem(name);
        PeerSelector.SetItemMetadata(PeerSelector.ItemCount - 1, address);
        return PeerSelector.ItemCount - 1;
    }

    private void OnPaperButtonPressed()
    {
        OfficePaper = !OfficePaper;

        PaperButton.Text = Loc.GetString(OfficePaper 
            ? "fax-machine-ui-paper-button-office"
            : "fax-machine-ui-paper-button-normal");
    }
}
