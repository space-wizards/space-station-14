namespace Content.Client.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class AudioTab : Control
{
    [Dependency] private IAudioManager _audio = default!;
    [Dependency] private IClientAdminManager _admin = default!;
    [Dependency] private IConfigurationManager _cfg = default!;

    private AudioDeviceOption _audioDeviceOption = default!;

    public AudioTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        DropDownAudioDevice.Button.Filterable = true;
        _audioDeviceOption = Control.AddOption(new AudioDeviceOption(Control, _cfg, DropDownAudioDevice));
        ReloadAudioDevices();

        var masterVolume = Control.AddOptionPercentSlider(
            CVars.AudioMasterVolume,
            SliderVolumeMaster,
            scale: ContentAudioSystem.MasterVolumeMultiplier);
        masterVolume.ImmediateValueChanged += OnMasterVolumeSliderChanged;

        Control.AddOptionPercentSlider(
            CVars.MidiVolume,
            SliderVolumeMidi,
            scale: ContentAudioSystem.MidiVolumeMultiplier);

        Control.AddOptionPercentSlider(
            CCVars.AmbientMusicVolume,
            SliderVolumeAmbientMusic,
            scale: ContentAudioSystem.AmbientMusicMultiplier);

        Control.AddOptionPercentSlider(
            CCVars.AmbienceVolume,
            SliderVolumeAmbience,
            scale: ContentAudioSystem.AmbienceMultiplier);

        Control.AddOptionPercentSlider(
            CCVars.LobbyMusicVolume,
            SliderVolumeLobby,
            scale: ContentAudioSystem.LobbyMultiplier);

        Control.AddOptionPercentSlider(
            CCVars.InterfaceVolume,
            SliderVolumeInterface,
            scale: ContentAudioSystem.InterfaceMultiplier);

        Control.AddOptionSlider(
            CCVars.MaxAmbientSources,
            SliderMaxAmbienceSounds,
            _cfg.GetCVar(CCVars.MinMaxAmbientSourcesConfigured),
            _cfg.GetCVar(CCVars.MaxMaxAmbientSourcesConfigured));

        Control.AddOptionCheckBox(CCVars.LobbyMusicEnabled, LobbyMusicCheckBox);
        Control.AddOptionCheckBox(CCVars.RestartSoundsEnabled, RestartSoundsCheckBox);
        Control.AddOptionCheckBox(CCVars.EventMusicEnabled, EventMusicCheckBox);
        Control.AddOptionCheckBox(CCVars.AdminSoundsEnabled, AdminSoundsCheckBox);
        Control.AddOptionCheckBox(CCVars.BwoinkSoundEnabled, BwoinkSoundCheckBox);

        Control.Initialize();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _admin.AdminStatusUpdated += UpdateAdminButtonsVisibility;
        UpdateAdminButtonsVisibility();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _admin.AdminStatusUpdated -= UpdateAdminButtonsVisibility;
    }


    private void UpdateAdminButtonsVisibility()
    {
        BwoinkSoundCheckBox.Visible = _admin.IsActive();
    }

    private void OnMasterVolumeSliderChanged(float value)
    {
        // TODO: I was thinking of giving OptionsTabControlRow a flag to "set CVar immediately", but I'm deferring that
        // until there's a proper system for enforcing people don't close the window with pending changes.
        _audio.SetMasterGain(value);
    }

    public void ReloadAudioDevices()
    {
        var configuredDevice = _cfg.GetCVar(CVars.AudioDevice);
        var devices = _audio.GetAudioDevices()
            .Where(device => !string.IsNullOrWhiteSpace(device))
            .Distinct(StringComparer.Ordinal)
            .OrderBy(device => device, StringComparer.OrdinalIgnoreCase)
            .ToList();

        var configuredDeviceIsAvailable = string.IsNullOrEmpty(configuredDevice) ||
                                          devices.Contains(configuredDevice, StringComparer.Ordinal);

        if (!configuredDeviceIsAvailable)
            devices.Insert(0, configuredDevice);

        var entries = new List<AudioDeviceOption.Entry>
        {
            new(string.Empty, Loc.GetString("ui-options-audio-device-default"), false)
        };

        foreach (var device in devices)
        {
            var isUnavailable = !configuredDeviceIsAvailable && device == configuredDevice;
            var label = isUnavailable
                ? Loc.GetString("ui-options-audio-device-unavailable", ("device", device))
                : device;

            entries.Add(new(device, label, isUnavailable));
        }

        _audioDeviceOption.SetEntries(entries);
    }
}

internal sealed class AudioDeviceOption : BaseOption
{
    private readonly IConfigurationManager _cfg;
    private readonly OptionDropDown _dropDown;
    private readonly List<Entry> _entries = new();

    public AudioDeviceOption(
        OptionsTabControlRow controller,
        IConfigurationManager cfg,
        OptionDropDown dropDown)
        : base(controller)
    {
        _cfg = cfg;
        _dropDown = dropDown;
        _dropDown.Button.OnItemSelected += OnItemSelected;
    }

    public void SetEntries(IReadOnlyList<Entry> entries)
    {
        _entries.Clear();
        _entries.AddRange(entries);

        var button = _dropDown.Button;
        button.Clear();

        for (var i = 0; i < _entries.Count; i++)
        {
            var entry = _entries[i];
            button.AddItem(entry.Label, i);
            button.SetItemMetadata(button.GetIdx(i), entry.Value);

            if (entry.Disabled)
                button.SetItemDisabled(button.GetIdx(i), true);
        }
    }

    public override void LoadValue()
    {
        SelectValue(_cfg.GetCVar(CVars.AudioDevice));
    }

    public override void SaveValue()
    {
        _cfg.SetCVar(CVars.AudioDevice, SelectedValue());
    }

    public override void ResetToDefault()
    {
        SelectValue(CVars.AudioDevice.DefaultValue);
    }

    public override bool IsModified()
    {
        return !string.Equals(SelectedValue(), _cfg.GetCVar(CVars.AudioDevice), StringComparison.Ordinal);
    }

    public override bool IsModifiedFromDefault()
    {
        return !string.Equals(SelectedValue(), CVars.AudioDevice.DefaultValue, StringComparison.Ordinal);
    }

    private void OnItemSelected(OptionButton.ItemSelectedEventArgs args)
    {
        _dropDown.Button.SelectId(args.Id);
        ValueChanged();
    }

    private string SelectedValue()
    {
        return (string) _dropDown.Button.SelectedMetadata!;
    }

    private void SelectValue(string value)
    {
        for (var i = 0; i < _entries.Count; i++)
        {
            if (string.Equals(_entries[i].Value, value, StringComparison.Ordinal))
            {
                _dropDown.Button.SelectId(i);
                return;
            }
        }

        _dropDown.Button.SelectId(0);
    }

    public readonly record struct Entry(string Value, string Label, bool Disabled);
}
