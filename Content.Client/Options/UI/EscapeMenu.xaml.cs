using Content.Client.Playtime;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.Options.UI;

[GenerateTypedNameReferences]
public sealed partial class EscapeMenu : DefaultWindow
{
    [Dependency] private ClientsidePlaytimeTrackingManager _playtimeTracking = default!;

    private string _format = "H:mm";

    public EscapeMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Time.OnPressed += _ =>
        {
            _format = _format == "H:mm" ? "h:mm tt" : "H:mm";
        };
        OnOpen += UpdatePlaytime;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        Time.Text = DateTime.Now.ToString(_format);
    }

    private void UpdatePlaytime()
    {
        var minutesToday = _playtimeTracking.PlaytimeMinutesToday;
        var msg = Loc.GetString("clock-playtime-minutes", ("minutes", (int)minutesToday));

        if (minutesToday >= 60)
        {
            var hoursToday = Math.Round(minutesToday / 60f, 1);
            msg = Loc.GetString("clock-playtime-hours", ("hours", hoursToday));
        }

        Time.ToolTip = msg;
    }
}
