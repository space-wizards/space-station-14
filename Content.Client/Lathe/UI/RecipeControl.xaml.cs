using Content.Shared.Lathe;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.Lathe.UI;

[GenerateTypedNameReferences]
public sealed partial class RecipeControl : Control
{
    public Action<string>? OnButtonPressed;
    public Func<string> TooltipTextSupplier;

    public ProtoId<LatheRecipePrototype> RecipeId { get; private set; }
    private LatheSystem _latheSystem;

    public RecipeControl(LatheSystem latheSystem,
        LatheRecipePrototype recipe,
        Func<string> tooltipTextSupplier,
        bool canProduce,
        Control displayControl,
        string? recipeName = null)
    {
        RobustXamlLoader.Load(this);

        _latheSystem = latheSystem;
        RecipeId = recipe.ID;
        TooltipTextSupplier = tooltipTextSupplier;
        SetRecipe(recipe, recipeName);
        SetCanProduce(canProduce);
        SetDisplayControl(displayControl);

        Button.OnPressed += (_) =>
        {
            OnButtonPressed?.Invoke(RecipeId);
        };
        Button.TooltipSupplier = SupplyTooltip;
    }

    public void SetRecipe(LatheRecipePrototype recipe, string? name = null)
    {
        RecipeName.Text = name ?? _latheSystem.GetRecipeName(recipe);
        RecipeId = recipe.ID;
    }

    public void SetTooltipSupplier(Func<string> tooltipTextSupplier)
    {
        TooltipTextSupplier = tooltipTextSupplier;
    }

    public void SetCanProduce(bool canProduce)
    {
        Button.Disabled = !canProduce;
    }

    public void SetDisplayControl(Control displayControl)
    {
        RecipeDisplayContainer.Children.Clear();
        RecipeDisplayContainer.AddChild(displayControl);
    }

    private Control SupplyTooltip(Control sender)
    {
        return new RecipeTooltip(TooltipTextSupplier());
    }
}
