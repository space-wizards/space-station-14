    [GenerateTypedNameReferences]
    public sealed partial class LateJoinGui : FancyWindow
    {
        [Dependency] private IPrototypeManager _prototypeManager = default!;
        [Dependency] private IClientConsoleHost _consoleHost = default!;
        [Dependency] private IConfigurationManager _configManager = default!;
        [Dependency] private IEntitySystemManager _entitySystem = default!;
        [Dependency] private JobRequirementsManager _jobRequirements = default!;
        [Dependency] private IClientPreferencesManager _preferencesManager = default!;
        [Dependency] private ILogManager _logManager = default!;
        [Dependency] private ISharedPlayerManager _playerManager = default!;

        private readonly ClientGameTicker _gameTicker;
        private readonly SpriteSystem _sprites;
        private readonly CrewManifestSystem _crewManifest;
        private readonly ISawmill _sawmill;
        private readonly LobbyUIController _lobbyController;

        private readonly Dictionary<NetEntity, Dictionary<string, List<JobButton>>> _jobButtons = new();
        private readonly Dictionary<NetEntity, Dictionary<string, BoxContainer>> _jobCategories = new();
        private readonly List<ScrollContainer> _jobLists = new();

        private NetEntity? _selectedStation;
        private string? _selectedJobId;

        public LateJoinGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);
            _sprites = _entitySystem.GetEntitySystem<SpriteSystem>();
            _crewManifest = _entitySystem.GetEntitySystem<CrewManifestSystem>();
            _gameTicker = _entitySystem.GetEntitySystem<ClientGameTicker>();
            _sawmill = _logManager.GetSawmill("latejoin.panel");
            _lobbyController = UserInterfaceManager.GetUIController<LobbyUIController>();

            Title = Loc.GetString("late-join-gui-title");

            _jobRequirements.Updated += UpdateJobList;
            _lobbyController.CharacterSetupChanged += UpdateUI;
            UpdateUI();
            RebuildJobList();

            JoinButton.Disabled = true;
            JoinButton.OnPressed += _ => JoinButtonPressed();

            _gameTicker.LobbyJobsAvailableUpdated += UpdateJobList;
        }

        /// <summary>
        /// Rebuild all of the character picker buttons
        /// </summary>
        private void RebuildCharacterList()
        {
            CharacterList.RemoveAllChildren();

            if (_preferencesManager.Preferences == null)
                return;

            var preferences = _preferencesManager.Preferences;
            var group = new ButtonGroup();
            foreach (var (slot, profile) in preferences.Characters)
            {
                var isSelected = (slot == preferences.SelectedCharacterIndex);
                var characterPickerButton =
                    new CharacterPickerButton(_prototypeManager, _playerManager, group, profile, isSelected, true);
                CharacterList.AddChild(characterPickerButton);

                characterPickerButton.OnPressed += _ =>
                {
                    _preferencesManager.SelectCharacter(slot);
                    _lobbyController.ReloadCharacterSetup();
                };
            }
        }

        private void RebuildJobList()
        {
            JobList.RemoveAllChildren();
            _jobLists.Clear();
            _jobButtons.Clear();
            _jobCategories.Clear();

            if (!_gameTicker.DisallowedLateJoin && _gameTicker.StationNames.Count == 0)
                _sawmill.Warning("No stations exist, nothing to display in late-join GUI");

            foreach (var (id, name) in _gameTicker.StationNames)
            {
                var jobList = new BoxContainer
                {
                    Orientation = LayoutOrientation.Vertical,
                    Margin = new Thickness(10),
                };

                var collapseButton = new ContainerButton()
                {
                    HorizontalAlignment = HAlignment.Right,
                    ToggleMode = true,
                    Children =
                    {
                        new TextureRect
                        {
                            StyleClasses = { OptionButton.StyleClassOptionTriangle },
                            Margin = new Thickness(8, 0),
                            HorizontalAlignment = HAlignment.Center,
                            VerticalAlignment = VAlignment.Center,
                        }
                    }
                };

                JobList.AddChild(new StripeBack()
                {
                    HasTopEdge = false,
                    Children =
                    {
                        new PanelContainer()
                        {
                            Children =
                            {
                                new Label()
                                {
                                    StyleClasses = { "LabelBig" },
                                    Text = name,
                                    Align = Label.AlignMode.Center,
                                },
                                collapseButton
                            }
                        }
                    }
                });

                if (_configManager.GetCVar(CCVars.CrewManifestWithoutEntity))
                {
                    var crewManifestButton = new Button()
                    {
                        Text = Loc.GetString("crew-manifest-button-label")
                    };
                    crewManifestButton.OnPressed += _ => _crewManifest.RequestCrewManifest(id);

                    JobList.AddChild(crewManifestButton);
                }

                var jobListScroll = new ScrollContainer()
                {
                    VerticalExpand = true,
                    Children = { jobList },
                    Visible = false,
                };

                if (_jobLists.Count == 0)
                    jobListScroll.Visible = true;

                _jobLists.Add(jobListScroll);

                JobList.AddChild(jobListScroll);

                collapseButton.OnToggled += _ =>
                {
                    foreach (var section in _jobLists)
                    {
                        section.Visible = false;
                    }
                    jobListScroll.Visible = true;
                };

                var firstCategory = true;
                var departments = _prototypeManager.EnumeratePrototypes<DepartmentPrototype>().ToArray();
                Array.Sort(departments, DepartmentUIComparer.Instance);

                _jobButtons[id] = new Dictionary<string, List<JobButton>>();

                foreach (var department in departments)
                {
                    var departmentName = Loc.GetString(department.Name);
                    _jobCategories[id] = new Dictionary<string, BoxContainer>();
                    var stationAvailable = _gameTicker.JobsAvailable[id];
                    var jobsAvailable = new List<JobPrototype>();

                    foreach (var jobId in department.Roles)
                    {
                        if (!stationAvailable.ContainsKey(jobId))
                            continue;

                        jobsAvailable.Add(_prototypeManager.Index<JobPrototype>(jobId));
                    }

                    if (JobUIComparer.TryCreate(
                            _prototypeManager,
                            _gameTicker.JobWeightsByStation.GetValueOrDefault(id),
                            out var comparer))
                    {
                        jobsAvailable.Sort(comparer);
                    }

                    // Do not display departments with no jobs available.
                    if (jobsAvailable.Count == 0)
                        continue;

                    var category = new BoxContainer
                    {
                        Orientation = LayoutOrientation.Vertical,
                        Name = department.ID,
                        ToolTip = Loc.GetString("late-join-gui-jobs-amount-in-department-tooltip",
                            ("departmentName", departmentName))
                    };

                    if (firstCategory)
                    {
                        firstCategory = false;
                    }
                    else
                    {
                        category.AddChild(new Control
                        {
                            MinSize = new Vector2(0, 23),
                        });
                    }

                    category.AddChild(new PanelContainer
                    {
                        Children =
                        {
                            new Label
                            {
                                StyleClasses = { "LabelBig" },
                                Text = Loc.GetString("late-join-gui-department-jobs-label", ("departmentName", departmentName))
                            }
                        }
                    });

                    _jobCategories[id][department.ID] = category;
                    jobList.AddChild(category);

                    foreach (var prototype in jobsAvailable)
                    {
                        var value = stationAvailable[prototype.ID];

                        var jobLabel = new Label
                        {
                            Margin = new Thickness(5f, 0, 0, 0)
                        };

                        var jobButton = new JobButton(jobLabel, prototype.ID, prototype.LocalizedName, value);

                        var jobSelector = new BoxContainer
                        {
                            Orientation = LayoutOrientation.Horizontal,
                            HorizontalExpand = true
                        };

                        var icon = new TextureRect
                        {
                            TextureScale = new Vector2(2, 2),
                            VerticalAlignment = VAlignment.Center
                        };

                        var jobIcon = _prototypeManager.Index(prototype.Icon);
                        icon.Texture = _sprites.Frame0(jobIcon.Icon);
                        jobSelector.AddChild(icon);

                        jobSelector.AddChild(jobLabel);
                        jobButton.AddChild(jobSelector);
                        category.AddChild(jobButton);

                        jobButton.OnPressed += _ => JobButtonPressed(id, jobButton.JobId);

                        var allowed = _jobRequirements.IsAllowed(prototype, (HumanoidCharacterProfile?)_preferencesManager.Preferences?.SelectedCharacter, out var reason);
                        UpdateJobButtonAllowed(jobButton, allowed, reason);

                        if (!_jobButtons[id].ContainsKey(prototype.ID))
                        {
                            _jobButtons[id][prototype.ID] = new List<JobButton>();
                        }

                        _jobButtons[id][prototype.ID].Add(jobButton);
                    }
                }
            }
        }

        private void UpdateUI()
        {
            RebuildCharacterList();
            UpdateJobList();
        }

        private void UpdateJobList()
        {
            // these will be re-set below if there's a job button pressed that isn't disabled after this update
            _selectedStation = null;
            _selectedJobId = null;
            foreach (var (stationId, buttonsByJob) in _jobButtons)
            {
                var stationJobsAvailable = _gameTicker.JobsAvailable[stationId];
                foreach (var (jobId, buttons) in buttonsByJob)
                {
                    var updatedSlots = stationJobsAvailable[jobId];
                    var jobPrototype = _prototypeManager.Index<JobPrototype>(jobId);
                    var allowed = _jobRequirements.IsAllowed(jobPrototype,
                        _preferencesManager.Preferences?.SelectedCharacter,
                        out var reason);
                    foreach (var button in buttons)
                    {
                        button.RefreshLabel(updatedSlots);
                        UpdateJobButtonAllowed(button, allowed, reason);
                    }

                    if (!buttons[0].Disabled && buttons[0].Pressed)
                    {
                        _selectedStation = stationId;
                        _selectedJobId = jobId;
                    }
                }
            }

            JoinButton.Disabled = _selectedStation == null;
        }

        private void UpdateJobButtonAllowed(JobButton button, bool allowed, FormattedMessage? reason)
        {
            if (!allowed)
            {
                button.Disabled = true;

                button.Lock = new TextureRect
                {
                    TextureScale = new Vector2(0.4f, 0.4f),
                    Stretch = TextureRect.StretchMode.KeepCentered,
                    Texture = _sprites.Frame0(new SpriteSpecifier.Texture(new ("/Textures/Interface/Nano/lock.svg.192dpi.png"))),
                    HorizontalExpand = true,
                    HorizontalAlignment = HAlignment.Right,
                };
                button.AddChild(button.Lock);
            }
            else
            {
                if (button.Lock != null)
                {
                    button.RemoveChild(button.Lock);
                    button.Lock = null;
                }

                button.Disabled = button.Amount == 0;
            }

            if (reason != null && !reason.IsEmpty)
            {
                var tooltip = new Tooltip();
                tooltip.SetMessage(reason);
                button.TooltipSupplier = _ => tooltip;
            }
            else
            {
                button.TooltipSupplier = null;
            }
        }

        private void JobButtonPressed(NetEntity station, string jobId)
        {
            _selectedStation = station;
            _selectedJobId = jobId;
            JoinButton.Disabled = false;

            foreach (var (buttonsStationId, buttonsByJob) in _jobButtons)
            {
                foreach (var (buttonsJobId, buttons) in buttonsByJob)
                {
                    var sameJob = buttonsStationId == station && buttonsJobId == jobId;
                    foreach (var button in buttons)
                    {
                        button.Pressed = sameJob;
                    }
                }
            }
        }

        private void JoinButtonPressed()
        {
            if (_selectedStation == null || _selectedJobId == null)
            {
                JoinButton.Disabled = true;
                return;
            }
            _sawmill.Info($"Late joining as ID: {_selectedJobId}");
            _consoleHost.ExecuteCommand($"joingame {CommandParsing.Escape(_selectedJobId)} {_selectedStation}");
            Close();
        }

        protected override void ExitedTree()
        {
            base.ExitedTree();

            _jobRequirements.Updated -= UpdateUI;
            _lobbyController.CharacterSetupChanged -= UpdateUI;
            _gameTicker.LobbyJobsAvailableUpdated -= UpdateJobList;
        }
    }

    sealed class JobButton : ContainerButton
    {
        public Label JobLabel { get; }
        public string JobId { get; }
        public string JobLocalisedName { get; }
        public int? Amount { get; private set; }
        public TextureRect? Lock { get; set; }
        private bool _initialised = false;

        public JobButton(Label jobLabel, ProtoId<JobPrototype> jobId, string jobLocalisedName, int? amount = null)
        {
            JobLabel = jobLabel;
            JobId = jobId;
            JobLocalisedName = jobLocalisedName;
            RefreshLabel(amount);
            AddStyleClass(StyleClassButton);
            _initialised = true;
        }

        public void RefreshLabel(int? amount)
        {
            if (Amount == amount && _initialised)
            {
                return;
            }
            Amount = amount;

            JobLabel.Text = Amount != null ?
                Loc.GetString("late-join-gui-job-slot-capped", ("jobName", JobLocalisedName), ("amount", Amount)) :
                Loc.GetString("late-join-gui-job-slot-uncapped", ("jobName", JobLocalisedName));
        }
    }
}
