using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Cargo.UI;

[GenerateTypedNameReferences]
public sealed partial class OrderLogEntry : BoxContainer
{
    private static readonly StyleBoxFlat StripeStyle = new() { BackgroundColor = Color.FromHex("#040404") };

    public OrderLogEntry()
    {
        RobustXamlLoader.Load(this);
    }

    public void AddOrder(
        Texture? icon,
        string product,
        string accountCode,
        Color accountColor,
        string requester,
        string reason,
        string cost,
        bool striped)
    {
        Icon.Texture = icon;
        ProductName.Text = product;
        Requester.Text = requester;
        Reason.Text = reason;
        PointCost.Text = cost;
        Background.PanelOverride = striped ? StripeStyle : null;

        var message = new FormattedMessage();
        message.PushColor(accountColor);
        message.AddText(accountCode);
        message.Pop();
        AccountCode.SetMessage(message);
    }
}
